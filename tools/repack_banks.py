#!/usr/bin/env python3
"""ЭТАП E: перепаковка банков образов ПО СТОЛБЦАМ + таблицы адресов записей.

    python3 tools/repack_banks.py            # отчёт цифрами, ничего не пишет
    (как стадия сборки — вызывается из tools/build_v06_rom.py)

ЗАЧЕМ.  Вектор хранит экран столбцами: соседние строки растра лежат в
СОСЕДНИХ адресах (адрес = плоскость + столбец*256 + (255-y)).  Банк MSX
хранит образ ПО СТРОКАМ: байты одной строки подряд, шаг между строками
одного столбца = ширина записи.  Из-за этого виток блиттера тащил на себе
шаг источника (`TI_WA`), а полоса из восьми строк одного столбца никак не
могла стать четырьмя `push`.

ПОСЛЕ ПЕРЕПАКОВКИ данные записи лежат СТОЛБЦАМИ: сперва все h байт столбца
0 (строка 0 первой, сверху вниз), потом столбец 1 и так далее.  Тогда

  * источник столбца идёт ПОДРЯД — шаг исчезает;
  * пара соседних строк читается как `mov d,m / inx h / mov e,m / inx h`
    и кладётся одним `push d`: d уходит в СТАРШИЙ адрес (строка y),
    e — в младший (строка y+1), а `push` пишет по УБЫВАНИЮ адреса, то есть
    сверху вниз по экрану.  Разворачивать данные не нужно — порядок строк
    в записи остаётся естественным (сверху вниз).

ФОРМАТ НЕ ДЛИННЕЕ ПРЕЖНЕГО.  Перепаковка — ЧИСТАЯ ПЕРЕСТАНОВКА байтов
ВНУТРИ записи: заголовки `[высота][ширина]` остаются на своих местах, длина
записи и адрес следующей не меняются.  Поэтому банки лежат ТАМ ЖЕ, где
лежали (банк спрайтов 294B..3AA7, банк декораций 8E76..993F), и ни одна
зона памяти никуда не двигается.

ТАБЛИЦА АДРЕСОВ ЗАПИСЕЙ заменяет линейный проход SPR_BANK_VAR/SPR_BANK_HI
(3.0 тыс. тактов на вызов, по вызову на элемент комнаты).  Она
генерируется в `src/v06/bank_ptr.inc` и ложится В ТЕЛО адаптера, а не
отдельной зоной памяти: 58*2 + 53*2 = 222 байта.

ЗЕРКАЛО — НА ЛЕТУ, ВТОРОЙ КОПИИ НЕТ.  Замер: записей декораций, которые
нужны И ПРЯМО И ЗЕРКАЛЬНО, — 32 из 58, вторая копия стоила бы 1525 байт;
разворот байта через таблицу reverse 1E00 стоит +31 такт на ПАРУ строк
(81 такт против 50, замер по листингу tools/cycles_i8080.py: витки TP_ML и
TP_DL2), то есть +15.5 такта на байт образа — около 9 тыс. тактов на
отрисовку половины комнаты, 0.16 кадра из 5.63.  Выбран разворот на лету:
1525 байт дороже.

ЧЕСТНОСТЬ ГЕЙТОВ.  Перепакованные байты — ДРУГИЕ байты, и round-trip-гейты
(verify_disasm/verify_orig/verify_v06) сверяют образ с дизасмом и кассетой.
Поэтому перепаковка сделана СТАДИЕЙ СБОРКИ, а не правкой эталона: она
получает уже готовый образ, СВЕРЯЕТ байты банка с тем, что ожидает увидеть
(заголовки обязаны разобраться и дойти ровно до конца банка), и кладёт
перестановку.  `tools/verify_v06.py` знает про заменённые зоны и проверяет,
что в собранном .rom лежит ровно выход этой программы.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# --- БАНКИ В РАСКЛАДКЕ ВЕКТОРА.  Адреса — из самого образа: их держат
# SPR_BANK_VAR (1B52, `ld hl,8E76`) и SPR_BANK_HI (1B58, `ld hl,294B`).
BANKS = {
    # имя      начало  записей  конец (включительно)  где лежит
    "decor":  (0x8E76, 58, 0x993F),   # банк декораций комнат (оригинал AA76)
    "sprite": (0x294B, 53, 0x3AA7),   # банк подвижных объектов (оригинал E04B)
}

# Адреса, которыми банк объявлен в коде игры — сверяем, чтобы перепаковка
# не разошлась с образом молча.
BANK_DECL = ((0x1B53, 0x8E76), (0x1B59, 0x294B))


def set_decl(addrs) -> None:
    """Переставить адреса объявления банков (сборка i8080: код игры
    пересобран по меткам и операнды `ld hl,банк` уехали вместе с ним;
    новые адреса берутся из карты build/i8080/labels.json)."""
    global BANK_DECL
    BANK_DECL = tuple((a, w) for a, (_o, w) in zip(addrs, BANK_DECL))


def parse(mem: bytes, start: int, count: int, end: int, name: str, base: int = 0):
    """Разобрать банк на записи.  Падает, если заголовки не сходятся."""
    recs, p = [], start
    for i in range(count):
        if p + 2 > end + 1:
            sys.exit(f"repack_banks: банк {name}: запись {i} за концом банка")
        h, w = mem[p - base], mem[p + 1 - base]
        recs.append((i, p, h, w))
        p += 2 + h * w
    if p != end + 1:
        sys.exit(f"repack_banks: банк {name}: заголовки кончились на {p:04X}, "
                 f"а банк кончается на {end + 1:04X}")
    return recs


def transpose(data: bytes, h: int, w: int) -> bytes:
    """[строка][столбец] -> [столбец][строка] (строка 0 первой, сверху вниз)."""
    out = bytearray(h * w)
    for col in range(w):
        for row in range(h):
            out[col * h + row] = data[row * w + col]
    return bytes(out)


def check_decl(mem, base: int) -> None:
    """Банк объявлен в коде игры тем же адресом, что и здесь?"""
    for a, want in BANK_DECL:
        got = mem[a - base] | (mem[a + 1 - base] << 8)
        if got != want:
            sys.exit(f"repack_banks: по {a:04X} ждали адрес банка {want:04X}, "
                     f"в образе {got:04X} — образ или раскладка изменились")


def scan(mem, base: int) -> dict[str, list[int]]:
    """Разобрать банки, НЕ трогая образ: {банк: [адрес заголовка записи]}."""
    check_decl(mem, base)
    return {name: [p for _i, p, _h, _w in parse(mem, start, count, end, name, base)]
            for name, (start, count, end) in BANKS.items()}


def repack(mem: bytearray, base: int, quiet: bool = False) -> dict[str, list[int]]:
    """Переставить банки ПРЯМО В ОБРАЗЕ.  mem[0] == адрес base.

    Возвращает {имя банка: [адрес заголовка каждой записи]}.
    """
    check_decl(mem, base)
    tabs = {}
    for name, (start, count, end) in BANKS.items():
        recs = parse(mem, start, count, end, name, base)
        tab = []
        for _i, p, h, w in recs:
            tab.append(p)
            o = p + 2 - base
            mem[o:o + h * w] = transpose(bytes(mem[o:o + h * w]), h, w)
        tabs[name] = tab
        if not quiet:
            print(f"  банк {name:7s} {start:04X}..{end:04X}  {end - start + 1:5d} б,"
                  f"  записей {count}  -> ПО СТОЛБЦАМ, длина ТА ЖЕ")
    return tabs


# Таблицы адресов записей лежат НЕ В ТЕЛЕ АДАПТЕРА, а в освободившейся зоне
# (бывший SPRSAV): тело упирается в 5F7F, а таблицы — чистые данные, как
# карта чернил.  Их кладёт в образ tools/build_v06_rom.py, зона вписана в
# tools/verify_v06.py.
BKP_ORG = 0x488C                        # 58*2 = 116 -> 488C..48FF
BKP_SPR_ORG = BKP_ORG + 58 * 2          # 53*2 = 106 -> 4900..4969
BKP_END = BKP_SPR_ORG + 53 * 2 - 1


def inc_text(tabs: dict[str, list[int]]) -> str:
    """АДРЕСА таблиц -> include для screen_adapter.asm (сами таблицы — в образ)."""
    out = ["; СГЕНЕРИРОВАНО tools/repack_banks.py — правки вносить ТУДА.",
           "; Адрес ЗАГОЛОВКА записи банка: (hl) = высота, (hl+1) = ширина,",
           "; hl+2 = данные ПО СТОЛБЦАМ (столбец = h подряд идущих байт).",
           "; Заменяет линейный проход SPR_BANK_VAR/SPR_BANK_HI игры.",
           "; Сами таблицы кладёт в образ tools/build_v06_rom.py.",
           f"BKP_DEC         equ     0x{BKP_ORG:04X}",
           f"BKP_DEC_N       equ     {len(tabs['decor'])}",
           f"BKP_SPR         equ     0x{BKP_SPR_ORG:04X}",
           f"BKP_SPR_N       equ     {len(tabs['sprite'])}"]
    return "\n".join(out) + "\n"


def tab_bytes(tabs: dict[str, list[int]]) -> bytes:
    """Обе таблицы подряд, как они лягут в образ с BKP_ORG."""
    out = bytearray()
    for name in ("decor", "sprite"):
        for a in tabs[name]:
            out += bytes((a & 0xFF, a >> 8))
    return bytes(out)


# --- отчёт: цена зеркала ---------------------------------------------------

def report() -> None:
    """Цифры для решения «вторая копия или разворот на лету»."""
    S2 = (ROOT / "ref/msx/orig/SPIRITS.2.orig.payload").read_bytes()
    room = []
    p = 0xAA76 - 0x82A0
    for _i in range(58):
        h, w = S2[p], S2[p + 1]
        room.append((h, w))
        p += 2 + h * w
    d, m = set(), set()
    p = 0x8446 - 0x82A0
    for _i in range(87):
        n = S2[p + 4]
        for k in range(n):
            num = S2[p + 6 + 4 * k]
            (d if num & 0x80 else m).add(num & 0x7F)
        p += 6 + 4 * n
    both = d & m
    by = lambda s: sum(room[i][0] * room[i][1] for i in sorted(s))
    print("ЗЕРКАЛО В БАНКЕ ДЕКОРАЦИЙ (58 записей, 2646 байт данных)")
    print(f"  нужны прямо        {len(d):2d} записей, {by(d):5d} б")
    print(f"  нужны зеркально    {len(m):2d} записей, {by(m):5d} б")
    print(f"  нужны И ТАК И ТАК  {len(both):2d} записей, {by(both):5d} б"
          f"  <- столько стоила бы ВТОРАЯ КОПИЯ")
    print(f"  только зеркально   {len(m - d):2d} записей, {by(m - d):5d} б"
          f"  (эти можно хранить сразу развёрнутыми — но тогда нужен флаг)")
    print("  разворот на лету: пара строк 81 такт против 50 прямой,"
          " то есть +15.5 такта на байт образа")
    print("  ~600 зеркальных байт образа на половину комнаты = +9 тыс. тактов"
          " = 0.16 кадра из 5.63 -> ВЫБРАН РАЗВОРОТ НА ЛЕТУ")


if __name__ == "__main__":
    report()
