// ФИКСАЦИЯ СЛУЧАЙНОСТИ Spirits — общая часть стендов на vector06js.
// Парная реализация для openMSX — tools/openmsx/det-rng.tcl; ряд обязан
// совпадать байт в байт, иначе прогоны сравнивать нельзя.
//
// Вся случайность игры — регистр R (`ld a,r`, ED 5F), ровно пять мест, все
// в SPIRITS.2; ни LFSR, ни затравки, ни JIFFY, ни VDP-статуса в игре нет.
// R считает исполненные команды, а у нас вместо резидентного слоя MSX —
// адаптер с другим кодом, поэтому R расходится с MSX даже при идеально
// одинаковом вводе.  Значит без фиксации сверка средней и нижней третей
// сравнивает два разных розыгрыша, а не меру дефектов.
//
// Подставляется значение В РЕГИСТР A сразу ПОСЛЕ `ld a,r` (PC = адрес + 2).
// Флаги от этого не портятся: во всех пяти местах следующая команда,
// читающая флаги, — `and`/`cp`, то есть флаги пересчитываются.
//
// Счётчик ряда СВОЙ у каждого места: число обращений в одном месте зависит
// от того, сколько кадров прожил прогон, и общий счётчик сдвинул бы все
// остальные.
'use strict';

// (индекс, адрес `ld a,r` в ОРИГИНАЛЬНОЙ раскладке, что решает)
const SITES = [
  [0xBC0A, 'фаза/задержка декора: R кладётся в поле +3 записи объекта'],
  [0xBEA1, 'решение врага: and 0x3F / cp 3 — ветка с вероятностью 3/64'],
  [0xC84B, 'враг поворачивает к герою: and 0x7F / cp 0x6E — 18/128'],
  [0xCBA8, 'выбор одной из двух траекторий: and 1'],
  [0xCE8B, 'СТАРТ ПАРТИИ: and 0x0F -> одна из 16 записей PARAM_TABLE_CEAA,'
    + ' 6 байт в LEVEL_VARS+1..+6 — это и есть «случайный нижний этаж»'],
];

const MOD = 65537;

function makeRng(seed) {
  const st = SITES.map((_s, i) => ((seed >>> 0) + 1 + i * 8191) % MOD);
  return {
    // i — индекс места, значение 0..255
    next(i) {
      st[i] = (st[i] * 75 + 74) % MOD;
      return st[i] & 0xFF;
    },
  };
}

// Ставит перехват в стенд на vector06js.
//   cpu   — объект CPU (нужны getState/setState и pc)
//   adj   — поправка «оригинал -> наша раскладка» (для Вектора -0xB700)
//   seed  — затравка ряда
// Возвращает функцию hook(), которую надо позвать из check_breakpoint.
// hooks — необязательная карта {PC перехвата: индекс места}.  Она нужна
// сборке i8080: там `ld a,r` (2 байта) стал `call il_rnd` (3 байта) и уехал
// вместе со всем кодом, так что «адрес + 2» больше не работает — адреса
// приходят из карты build/i8080/labels.json.
function install(cpu, adj, seed, hooks) {
  const rng = makeRng(seed);
  const at = new Map();          // PC после `ld a,r` -> индекс места
  if (hooks) for (const k of Object.keys(hooks)) at.set(Number(k), hooks[k]);
  else SITES.forEach(([a], i) => at.set((a + 2 + adj) & 0xFFFF, i));
  // Ядро Z80 (z80_adapter) даёт getState/setState, ядро i8080 — set_a().
  const setA = cpu.getState
    ? (v) => { const st = cpu.getState(); st.a = v; cpu.setState(st); }
    : (v) => cpu.set_a(v);
  const hits = SITES.map(() => 0);
  return {
    hits,
    hook() {
      const i = at.get(cpu.pc);
      if (i === undefined) return;
      hits[i]++;
      setA(rng.next(i));
    },
  };
}

module.exports = { SITES, makeRng, install };
