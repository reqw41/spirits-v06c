; ============================================================================
;  ДЖОЙСТИК «П» Вектора-06Ц (ППИ2, порт 06h) -> ответ RDPSG(14) MSX
;  ВЕСЬ КОД — В ПОДМНОЖЕСТВЕ i8080.
; ----------------------------------------------------------------------------
;  КАК ЧИТАЕТ ИГРА (Вектор 12E1, оно же канон CAE3):
;     R7 = FF (все входы PSG на чтение) -> выбрать R14 -> in (A2h) -> and 0x1F.
;  Формат MSX-джойстика, активный ноль: b0 вверх, b1 вниз, b2 влево,
;  b3 вправо, b4 кнопка A, b5 кнопка B.
;
;  КАК ЧИТАЕТ ВЕКТОР: джойстик «П», активный ноль:
;    b0 ВПРАВО, b1 ВЛЕВО, b2 ВВЕРХ, b3 ВНИЗ, b4/b5 = 1 (простой),
;    b6 ОГОНЬ1, b7 ОГОНЬ2.
;  Разъём ПУ через ППИ2: out (4),83h / out (5),9Fh (оба устройства) / in a,(6)
;  (как Scuba Dive и Batty; ППИ2 в Spirits больше ни на что не занят — ни
;  звук, ни ROM-диск, ни covox). Только «П» — решение владельца 2026-10-19
;  («джойстик везде — «П»»); порт 0x0E (джойстик «С») больше не читается:
;  у Вектор Турбо+ на чтение 0Eh никто не отвечает, там мусор.
;
;  Порт без джойстика может отдать мусор (в эмуляторе EMU 06h — ROM-диск).
;  Поэтому V_JOY_RAW отбрасывает значение, у которого b4/b5 не обе единицы,
;  или где «нажаты» сразу вправо и влево; и засчитывает бит только если он
;  уже бывал единицей (v_joy_base_p) — это и нормировка по покою. Постоянный
;  мусор нажатий не даёт, кнопка, зажатая с первого опроса, заработает после
;  отпускания.
;
;  Перестановка Вектор → MSX взята из kvalley-v06c (метка RDPSG). Здесь
;  она обёрнута в push bc/pop bc: у Spirits вызов стоит внутри чужой
;  процедуры, и терять bc дороже, чем платить 21 такт.
;
;  Записи R7 = FF игре больше не нужны: настоящего PSG нет, а зеркало
;  регистров трогать незачем — поэтому в точке врезки остаётся один call.
; ============================================================================

V_JOY_RD:
;  Выход: a = байт, который вернул бы RDPSG(14) на MSX (активный ноль).
;  Портит a и флаги; bc, de, hl целы.
;  Перестановка битов Вектор → MSX (после cpl, 1 = нажато):
;    Вектор b2 ВВЕРХ  → MSX b0
;    Вектор b3 ВНИЗ   → MSX b1
;    Вектор b1 ВЛЕВО  → MSX b2
;    Вектор b0 ВПРАВО → MSX b3
;    Вектор b6 ОГОНЬ1 → MSX b4
;    Вектор b7 ОГОНЬ2 → MSX b5
	call V_JOY_RAW
	cpl			; 1 = нажато
	push bc
	ld b,a			; сохранить сырой байт
	rrca
	rrca			; сдвиг на 2: ВВЕРХ→b0, ВНИЗ→b1, ОГОНЬ1→b4, ОГОНЬ2→b5
	and 0x33		; оставить только эти четыре бита
	ld c,a
	ld a,b
	rlca			; ВЛЕВО: b1 → b2
	and 0x04
	or c
	ld c,a
	ld a,b
	rlca
	rlca
	rlca			; ВПРАВО: b0 → b3
	and 0x08
	or c
	cpl			; обратно в активный ноль MSX; b6/b7 = 1 (простой)
	pop bc
	ret

; ---------------------------------------------------------------------------
;  V_JOY_RAW — сырое чтение джойстика «П» в формате Вектора.
;  Выход: a = нажатия (активный ноль) порта 06h после фильтра.
;  Портит a и флаги; bc, de, hl целы. База v_joy_base_p — в данных адаптера
;  (v_joy_base_s осталась на месте и не используется: раскладка данных та же).
; ---------------------------------------------------------------------------
V_JOY_RAW:
	push bc
	push hl
	ld a,0x83
	out (4),a		; ППИ2: A и C(ст.) — вывод, B и C(мл.) — ввод
	ld a,0x9F
	out (5),a		; опрос P1 и P2 вместе (Scuba Dive)
	in a,(6)
	ld hl,v_joy_base_p
	call vj_port
	pop hl
	pop bc
	ret

; A = сырое значение порта, HL = база -> A = нажатия (0 = нажато) среди
; битов, бывавших единицей; не-джойстик подменяется на FF; база |= значение.
; Портит C.
vj_port:
	ld c,a
	and 0x30
	cp 0x30
	jp nz,vj_bad		; b4/b5 не обе 1 — мусор
	ld a,c
	and 3
	ld a,c
	jp nz,vj_ok		; вправо и влево вместе «нажаты» — мусор
vj_bad:
	ld c,0xFF
vj_ok:
	ld a,c
	or (hl)
	ld (hl),a		; база |= порт
	ld a,c
	cpl
	and (hl)		; ~порт & база = нажатия среди «бывавших 1»
	cpl			; обратно в активный ноль
	ret
