; ============================================================================
;  ДЖОЙСТИК: порт 0x0E Вектора-06Ц -> ответ RDPSG(14) MSX
;  ВЕСЬ КОД — В ПОДМНОЖЕСТВЕ i8080.
; ----------------------------------------------------------------------------
;  КАК ЧИТАЕТ ИГРА (Вектор 12E1, оно же канон CAE3):
;     R7 = FF (все входы PSG на чтение) -> выбрать R14 -> in (A2h) -> and 0x1F.
;  Формат MSX-джойстика, активный ноль: b0 вверх, b1 вниз, b2 влево,
;  b3 вправо, b4 кнопка A, b5 кнопка B.
;
;  КАК ЧИТАЕТ ВЕКТОР: порт 0x0E, отдельная микросхема, инициализация ВВ55
;  НЕ нужна. Активный ноль: b0 ВПРАВО, b1 ВЛЕВО, b2 ВВЕРХ, b3 ВНИЗ,
;  b4/b5 — простой (единицы), b6 ОГОНЬ1, b7 ОГОНЬ2.
;  (RTL ядра MiSTer Vector-06C.sv:294/635, эмулятор vector06js src/io.js.)
;
;  Перестановка взята готовой из kvalley-v06c/tools/kv_z80_to_8080.py, метка
;  RDPSG — проверена там на живой игре (tools/verify/joy_probe.js). Здесь она
;  обёрнута в push bc/pop bc: у Spirits вызов стоит внутри чужой процедуры,
;  и терять bc дороже, чем платить 21 такт.
;
;  Записи R7 = FF игре больше не нужны: настоящего PSG нет, а зеркало
;  регистров трогать незачем — поэтому в точке врезки остаётся один call.
; ============================================================================

V_JOY_RD:
;  Выход: a = байт, который вернул бы RDPSG(14) на MSX (активный ноль).
;  Портит a и флаги; bc, de, hl целы.
;  Перестановка битов Вектор → MSX (после cpl, 1 = нажато):
;    Вектор b2 ВВЕРХ  → MSX b0
;    Вектор b3 ВНИЗ   → MSX b1
;    Вектор b1 ВЛЕВО  → MSX b2
;    Вектор b0 ВПРАВО → MSX b3
;    Вектор b6 ОГОНЬ1 → MSX b4
;    Вектор b7 ОГОНЬ2 → MSX b5
	in a,(0x0E)
	cpl			; 1 = нажато
	push bc
	ld b,a			; сохранить сырой байт
	rrca
	rrca			; сдвиг на 2: ВВЕРХ→b0, ВНИЗ→b1, ОГОНЬ1→b4, ОГОНЬ2→b5
	and 0x33		; оставить только эти четыре бита
	ld c,a
	ld a,b
	rlca			; ВЛЕВО: b1 → b2
	and 0x04
	or c
	ld c,a
	ld a,b
	rlca
	rlca
	rlca			; ВПРАВО: b0 → b3
	and 0x08
	or c
	cpl			; обратно в активный ноль MSX; b6/b7 = 1 (простой)
	pop bc
	ret
