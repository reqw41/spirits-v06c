; ============================================================================
;  ЗВУК: PSG MSX (AY-3-8910) -> таймер КР580ВИ53 Вектора-06Ц
;  Spirits (Topo Soft, 1987), порт на ванильный Вектор-06Ц (AY нет).
;  Подход взят из knightlore-v06c/alien8-v06c (docs/PORT_RECIPE.md §16) —
;  зеркало регистров AY + перенос зеркала в делители таймера.
;  ВЕСЬ КОД — В ПОДМНОЖЕСТВЕ i8080: ни IX/IY, ни JR/DJNZ, ни BIT/SET/RES,
;  ни LDIR, ни теневых регистров. Синтаксис мнемоник — Z80 (как в дизасме).
; ----------------------------------------------------------------------------
;  ПОРТЫ ВИ53 НА ВЕКТОРЕ ПЕРЕСТАВЛЕНЫ против даташита 8253:
;    управляющее слово  = порт 0x08
;    счётчик 0 / 1 / 2  = порты 0x0B / 0x0A / 0x09
;  Написать «как в даташите» — управляющие слова уедут в счётчики и вместо
;  музыки будет вой. У i8080 нет OUT по регистру, поэтому порт счётчика
;  подставляется в заготовку v_stub («out (порт),a : ret», 3 байта в ОЗУ).
; ----------------------------------------------------------------------------
;  ЗАЧЕМ ЗЕРКАЛО, А НЕ ПРЯМАЯ ЗАПИСЬ. Игра задаёт ноту тремя записями подряд:
;  R7 (глушим канал) -> R0/R1 (период) -> R7 (включаем канал). Если писать в
;  счётчик по каждой записи, между младшим и старшим байтом периода счётчик
;  успеет перезапуститься с мусорным делителем. Поэтому все записи копятся в
;  зеркале v_ayreg, а в железо уходят по записи в МИКШЕР (R7).
;
;  ПОЧЕМУ ИМЕННО R7, А НЕ РАЗ В КАДР (в отличие от Knight Lore). У Spirits
;  проигрыватель музыки БЛОКИРУЮЩИЙ (Вектор 243A..2559: свой цикл задержки,
;  прерывание не нужно), а каждый звуковой эффект — пачка пар «регистр,
;  значение», ПОСЛЕДНЯЯ пара которой всегда R7 (дескрипторы 64AA/64B9/64C8/
;  64D7/64E6 кончаются на 07,3E, дескриптор 64F5 — на 07,3F). То есть запись
;  R7 — ровно граница ноты и в музыке, и в эффектах: слив по ней даёт по
;  одному выводу на ноту БЕЗ кадрового прерывания и без лишних записей.
; ----------------------------------------------------------------------------
;  ЧТО ТЕРЯЕТСЯ ПРОТИВ AY (у ВИ53 один меандр на счётчик):
;
;  1. ГРОМКОСТЬ. Порог 6 из 15 (приём King's Valley): тише — молчим, иначе
;     тихие хвосты гудели бы наравне с мелодией. Для Spirits порог сейчас —
;     СТРАХОВКА, а не необходимость: игра пишет в R8/R9/R10 только 00, 0C,
;     0E, 0F и 10 (замер по четырём трассам PSG — MSX-картридж и наш образ,
;     игра и обе мелодии), а единственный нулевой — R10, канал C, которому
;     нот не пишут вовсе: период 0 -> делитель 1 -> его глушит правило
;     «делитель < 64». ЗАМЕР: образ с порогом и образ без порога (cp 6 ->
;     cp 0) дают ПОБАЙТНО ОДИНАКОВЫЕ логи записей в ВИ53.
;     Прежнее обоснование («третий поток нот бродит по памяти с адреса
;     0000») было неверным по причине, хотя мусор и правда звучал: на MSX и
;     CPC указатель третьего голоса (DC87) равен DFE5, а там лежит FF FE —
;     «пауза, повтор», голос корректен и молчит. У НАС это слово не переехало
;     (DFE5 в раскладке Вектора — видимая экранная плоскость), плеер читал
;     оттуда 0x00 и каждый тик играл F#3 на канале C. Причина устранена
;     врезкой 2587 (tools/build_port_rom.py), а не порогом.
;
;  2. ОГИБАЮЩАЯ. Все звуковые эффекты Spirits играют «громкостью 0x10», то
;     есть огибающей (R11/R12 — период, R13 — форма), и НИЧЕМ больше не
;     выключаются: дескриптор ставит R7=3E и уходит. У таймера огибающей нет,
;     значит нота звучала бы вечно. Поэтому ноте с битом 0x10 выдаётся СРОК
;     ЖИЗНИ в кадрах, а V_SND_TICK (раз в кадр) его отсчитывает и по нулю
;     останавливает счётчик. Полный проход огибающей AY (32 ступени) =
;     256*EP/fclk, на MSX это EP/139.8 кадра 50 Гц. Срок у нас: для
;     ЗАТУХАЮЩЕЙ формы (EP+64)/128 кадра — ВЕСЬ проход, округлённый к
;     ближайшему кадру (обоснование у V_LIFE_SET), для НЕПРЕРЫВНОЙ EP/4,
;     упёртый в 255. Форму огибающей дальше этого деления не разбираем: у
;     Spirits их всего две (01 «затухание один раз» и 0E «треугольник без
;     конца»), и для 0E конечный срок ЛУЧШЕ бесконечного — иначе эффект
;     64D7 гудел бы до конца уровня.
;     Длину эффекта в ИГРОВОМ ЦИКЛЕ задаёт не срок, а гашение R7=FF от опроса
;     джойстика — оно у нас воспроизведено (врезка 12E1), как на MSX.
;     Ноты БЕЗ бита 0x10 (мелодия) срока не получают: их перезапускает сам
;     плеер, а в конце трека он пишет R7=3F (Вектор 255C) — полная тишина.
;
;  3. ШУМ. Не поддерживаем ВООБЩЕ, и это не упрощение «на глаз»: шум в игре
;     включает ровно один дескриптор — 64F5 (R7=36: тон A + шум A), у
;     которого период тона 0 (делитель 0 -> отбрасывается порогом 64) и
;     СЛЕДУЮЩЕЙ же парой идёт R7=3F. То есть 64F5 — это команда «замолчать»
;     (им же кончается SFX_64D7_x25, Вектор 2006), и правильный результат
;     для неё — тишина. Ни одного дескриптора, где шум надо было бы слышать,
;     в игре нет. Канал, у которого тон выключен, считается молчащим.
;
;  4. ДЕЛИТЕЛИ < 64 (выше 23 кГц) глушим: слышать там нечего, а запись в
;     счётчик его перезапускает.
; ----------------------------------------------------------------------------
;  ПЕРЕСЧЁТ ПЕРИОДА. AY на MSX тактируется 1 789 772.5 Гц с делением на 16:
;  f = 1789772.5/(16*P). Таймер Вектора тактируется 1 497 600 Гц, в режиме 3
;  даёт меандр f = 1497600/делитель. Отсюда делитель = 13.3878 * P.
;  Считаем 13.375*P = 13P + P/4 + P/8 (V_AY2VI) — расхождение 0.096 %
;  (1.7 цента), то есть строй сохраняется. Максимум: 13.375*4095 = 54771,
;  в 16 бит помещается.
; ----------------------------------------------------------------------------
;  ТРИ ПРИЁМА ИЗ KING'S VALLEY, без которых звук плохой:
;   * управляющее слово ПЕРЕЗАПУСКАЕТ счётчик — слать только при смене
;     владельца (включение/выключение), а не на каждую ноту;
;   * тишина = управляющее слово БЕЗ делителя (счётчик встаёт), а не низкий
;     тон;
;   * при остановке кэш делителя бить в FFFF, иначе повтор ТОЙ ЖЕ ноты после
;     паузы не перезальётся и счётчик промолчит.
; ----------------------------------------------------------------------------
;  РАСКЛАДКА: канал AY A/B/C -> счётчик ВИ53 0/1/2 (порты 0B/0A/09).
;  Перекладывать нечего: у Spirits на Векторе нет ни секундомера бюджета di,
;  ни других потребителей таймера.
; ============================================================================

; ---------------------------------------------------------------- точки входа
; V_PSG_WR   — замена резидентной PSG_WR (Вектор 2569): a = регистр, c = значение
; V_SND_TICK — раз в кадр (из кадрового прерывания): отсчёт сроков жизни нот
; V_SND_INIT — на старте: заготовка v_stub, чистка зеркала, остановка счётчиков
; -----------------------------------------------------------------------------

V_PSG_WR:
;  Вход: a = номер регистра AY, c = значение. Выход: ничего.
;  Портит a и флаги — РОВНО как оригинал (out/ld a,c/out/ret). bc, de, hl целы.
	push hl
	ld h,a			; номер регистра нужен после записи в зеркало
	and 0x0F
	add a,V_AYREG_LO	; зеркало выровнено на 16 -> переноса в старший байт нет
	ld l,a
	ld a,h
	ld h,V_AYREG_HI
	ld (hl),c
	cp 0x07
	jp z,vps_mix
;  Любая запись, кроме микшера, — это новая нота: снимаем метки «погашено по
;  истечении срока», иначе следующий эффект на том же канале не зазвучит.
	xor a
	ld (v_dead),a
	pop hl
	ret
vps_mix:
	push bc
	push de
	call V_SND_EMIT
	pop de
	pop bc
	pop hl
	ret

V_SND_EMIT:
;  Зеркало -> три счётчика. Портит a, bc, de, hl, флаги.
;  ТЕМБР НЕПРЕРЫВНОЙ ОГИБАЮЩЕЙ — БИЕНИЯМИ. Эффект 64D7 (попадание, урон)
;  на AY — тон 413 Гц, промодулированный по амплитуде треугольником формы
;  0E с циклом 17.2 мс (58 Гц): рычащий, жужжащий звук. У ВИ53 громкости
;  нет, и один меандр даёт ровный гул — владелец на слух: «монотонный».
;  Амплитудную модуляцию дают БИЕНИЯ двух близких тонов: каналу B ставим
;  период P - P/8, частота выше на 1/7. ЗАМЕР (tools/snd_sfx_check.py, на
;  модели i8080): канал A 413.2 Гц, канал B 470.5 Гц, разность 57.3 Гц —
;  против 58.3 Гц у треугольника AY (полный треугольник = ДВА прохода
;  огибающей, 2*256*60/1789772.5 = 17.2 мс). Расхождение 1.7 %, поправлять
;  коэффициент 1/8 не за чем. Он подобран под 64D7, другого эффекта
;  с непрерывной формой в игре нет. Канал B свободен: эффекты играют только
;  в A, а блокирующий плеер мелодий с эффектами одновременно не работает.
;  Подделка живёт до следующей записи R7 — любой дескриптор кончается ею.
	ld a,(v_ayreg+8)
	and 0x10
	jp z,vse_go		; A без огибающей
	ld a,(v_ayreg+13)
	and 0x09		; бит 3 CONT, бит 0 HOLD
	cp 0x08
	jp nz,vse_go		; огибающая не непрерывная
	ld a,(v_ayreg+7)
	and 0x01
	jp nz,vse_go		; тон A выключен
	ld hl,(v_ayreg+0)
	ld a,h
	and 0x0F
	ld h,a
	ld d,h
	ld e,l			; de = P
	ld b,0x03
vse_sh:
	ld a,h			; hl = P / 8
	or a
	rra
	ld h,a
	ld a,l
	rra
	ld l,a
	dec b
	jp nz,vse_sh
	ld a,e			; hl = P - P/8
	sub l
	ld l,a
	ld a,d
	sbc a,h
	ld h,a
	ld (v_ayreg+2),hl	; период канала B
	ld a,0x10
	ld (v_ayreg+9),a	; громкость B = «огибающая»: срок тот же
	ld a,(v_ayreg+7)
	and 0xFD
	ld (v_ayreg+7),a	; тон B включить
	ld a,(v_dead)
	and 0xFD
	ld (v_dead),a		; снять с B метку «погашен по сроку»
vse_go:
	ld c,0x00
vse_l:
	push bc
	call V_SND_CH
	pop bc
	inc c
	ld a,c
	cp 0x03
	jp c,vse_l
	ret

V_SND_CH:
;  Один канал: c = 0..2. Решает «звучать/молчать» и выдаёт в счётчик.
	ld b,0x00
	ld hl,v_bit1
	add hl,bc
	ld e,(hl)		; e = 1 << номер канала
	ld a,(v_dead)
	and e
	jp nz,vsc_off		; нота погашена по сроку — ждём новой записи в PSG
	ld a,(v_ayreg+7)
	and e
	jp nz,vsc_off		; тон канала выключен (шум не поддерживаем, см. шапку)
	ld hl,v_ayreg+8
	add hl,bc
	ld a,(hl)
	and 0x10
	jp nz,vsc_per		; огибающая -> считаем громкость максимальной
	ld a,(hl)
	and 0x0F
	cp 0x06
	jp c,vsc_off		; тише 6 из 15 — у таймера громкости нет, молчим
vsc_per:
	ld hl,v_ayreg		; период канала: регистры 2c (мл.) и 2c+1 (ст.)
	add hl,bc
	add hl,bc
	ld a,(hl)
	inc hl
	ld h,(hl)
	ld l,a
	ld a,h
	and 0x0F
	ld h,a			; hl = период AY, 12 бит
	call V_AY2VI		; hl = делитель ВИ53
	ld a,h
	or a
	jp nz,vsc_on
	ld a,l
	cp 0x40
	jp c,vsc_off		; делитель < 64 = выше 23 кГц, слышать нечего

vsc_on:
;  hl = делитель, c = канал.
	ld a,0x0B
	sub c
	ld (v_stub+1),a		; порт счётчика: 0B / 0A / 09 (адреса ВИ53 переставлены!)
	push hl
	ld hl,v_own
	add hl,bc
	ld a,(hl)
	or a
	jp nz,vsc_run		; счётчик уже считает — управляющее слово не слать
	ld (hl),0x01
	call V_VI_CTRL		; включение = смена владельца = перезапуск счётчика
	ld hl,v_div		; ...и бой кэша делителя, иначе та же нота после
	add hl,bc		;    паузы не перезальётся и счётчик промолчит
	add hl,bc
	ld (hl),0xFF
	inc hl
	ld (hl),0xFF
	call V_LIFE_SET		; срок жизни ноты (огибающую AY таймер не умеет)
vsc_run:
	pop hl
	ld d,h
	ld e,l			; de = делитель
	ld hl,v_div
	add hl,bc
	add hl,bc
	ld a,(hl)
	cp e
	jp nz,vsc_wr
	inc hl
	ld a,(hl)
	cp d
	ret z			; делитель тот же — не трогаем (запись = перезапуск счёта)
	dec hl
vsc_wr:
	ld (hl),e
	inc hl
	ld (hl),d
	ld a,e
	call v_stub		; младший байт делителя
	ld a,d
	jp v_stub		; старший байт делителя (хвостовой вызов)

vsc_off:
;  Погасить канал c: тишина = управляющее слово БЕЗ делителя, счётчик встаёт.
	ld hl,v_own
	add hl,bc
	ld a,(hl)
	or a
	ret z			; уже молчит
	ld (hl),0x00
	ld hl,v_life
	add hl,bc
	ld (hl),0x00
;  дальше — V_VI_CTRL, она и останавливает счётчик

V_VI_CTRL:
;  Управляющее слово счётчика c: режим 3 (меандр), загрузка LSB+MSB.
	ld a,c
	rrca
	rrca			; 0 -> 00, 1 -> 40, 2 -> 80
	add a,0x36
	out (0x08),a		; порт управляющего слова ВИ53 на Векторе = 0x08
	ret

V_AY2VI:
;  hl = период AY (12 бит) -> hl = делитель ВИ53 = 13.375 * P.
;  Портит a, hl, флаги; bc и de сохраняются (вызывающему нужен номер канала).
	push bc
	push de
	ld b,h
	ld c,l			; bc = P
	add hl,hl		; 2P
	ld d,h
	ld e,l			; de = 2P
	add hl,hl		; 4P
	add hl,de		; 6P
	add hl,hl		; 12P
	add hl,bc		; 13P
	ld a,b			; bc = P/2
	or a			; сбросить перенос перед rra
	rra
	ld b,a
	ld a,c
	rra
	ld c,a
	ld a,b			; bc = P/4
	or a
	rra
	ld b,a
	ld a,c
	rra
	ld c,a
	add hl,bc		; 13.25P
	ld a,b			; bc = P/8
	or a
	rra
	ld b,a
	ld a,c
	rra
	ld c,a
	add hl,bc		; 13.375P
	inc hl			; три деления пополам всегда отбрасывают остаток,
				; поэтому +1 — не «погрешность», а смещение ошибки
				; из [-1.75, 0] в [-0.75, +1]: на реальных периодах
				; игры расхождение падает втрое (замер adapter_probe)
	pop de
	pop bc
	ret

V_LIFE_SET:
;  Срок жизни новой ноты канала c. Портит a, de, hl, флаги; bc цел.
	ld hl,v_ayreg+8
	add hl,bc
	ld a,(hl)
	and 0x10
	ld hl,v_life
	add hl,bc
	ld (hl),0x00
	ret z			; без огибающей срок не нужен: ноту перезапустит плеер
	push hl
;  СРОК = ВРЕМЯ ОДНОГО ПОЛНОГО ПРОХОДА ОГИБАЮЩЕЙ. У AY он равен 256*EP/fclk;
;  на MSX fclk = 1 789 772.5 Гц, в кадрах 50 Гц это EP/139.8. Берём (EP+64)/128
;  — старший байт от (EP+64)*2, без сдвигов: +9 % к длине и округление к
;  ближайшему кадру.
;
;  ПОЧЕМУ ПОЛНЫЙ ПРОХОД, А НЕ ЧЕТВЕРТЬ. Здесь стояло EP/512 + 2 — «четверть
;  прохода», подобранная на слух по эффекту 64C8 (выстрел), чтобы он не гудел
;  меандром на полной громкости все 18 кадров своей огибающей.  Подобрана она
;  была под НЕВЕРНУЮ картину: на MSX 64C8 тоже не звучит 18 кадров, его режет
;  сама игра — опрос джойстика пишет в микшер R7 = FF и гасит ВСЕ каналы на
;  каждом витке игрового цикла.  Эта запись у нас ВОСПРОИЗВЕДЕНА (врезка 12E1
;  в tools/build_port_rom.py), ЗАМЕР: 511 гашений за 2500 кадров игры, виток
;  4.46 кадра против 4.78 на живом MSX.  То есть в игровом цикле длину эффекта
;  задаёт гашение, ровно как в оригинале, а срок жизни решает только там, где
;  цикл стоит — внутри блокирующих кусков.  И там честная длина — весь проход
;  огибающей, а не его четверть.
;  ЗАМЕР, что четверть ломала: эффект 64E6 (потеря жизни, CA80) на MSX звучит
;  12.82 кадра (полная огибающая: игра в этот момент перерисовывает панель и
;  джойстик не опрашивает — на картридже до следующего R7 = FF 14.75 кадра),
;  а у нас звучал 5.  Владелец на слух: «короче оригинала».
;  Новые сроки против MSX: 64AA/64B9 2 кадра (MSX 1.43), 64C8 20 (MSX 18.31,
;  в игре обрезан гашением до ~4.5), 64E6 14 (MSX 12.82).
;
;  Исключение — НЕПРЕРЫВНЫЕ формы без удержания (R13 = 08, 0A, 0C, 0E): там
;  огибающая не кончается, звук гасит сама игра дескриптором 64F5, и срок —
;  лишь страховка; для них оставлена прежняя щедрая формула EP/4 (у игры
;  такая одна, 64D7: треугольник 0E, 15 кадров).
	ld a,(v_ayreg+13)
	and 0x09		; бит 3 CONT, бит 0 HOLD
	cp 0x08
	jp z,vls_cont
	ld hl,(v_ayreg+11)	; hl = период огибающей (R11 младший, R12 старший)
	ld de,0x0040
	add hl,de		; +64 = полкадра: делим дальше с округлением к
				; БЛИЖАЙШЕМУ кадру, а не вниз (иначе шаг 1.43 кадра
				; превратился бы в 1, а не в 2)
	add hl,hl		; DAD H: (EP+64)*2, старший байт = проход в кадрах
	ld a,0xFF
	jp c,vls_put		; EP >= 0x8000 — упор 255 кадров
	ld a,h			; a = ПОЛНЫЙ проход огибающей в кадрах
	or a
	jp nz,vls_put
	inc a			; проход короче кадра — прозвучать нота всё равно
				; должна кадр: ноль означал бы «бессрочно»
	jp vls_put
vls_cont:
	ld hl,(v_ayreg+11)	; hl = период огибающей (R11 младший, R12 старший)
	ld a,h			; hl = период / 2
	or a
	rra
	ld h,a
	ld a,l
	rra
	ld l,a
	ld a,h			; hl = период / 4 (= время прохода огибающей + 9 %)
	or a
	rra
	ld h,a
	ld a,l
	rra
	ld l,a
	ld a,h
	or a
	ld a,0xFF
	jp nz,vls_put		; больше 255 кадров — упираем в 255 (5.1 с)
	ld a,l
	or a
	jp nz,vls_put
	ld a,0x01		; ноль кадров означал бы «бессрочно», поэтому минимум 1
vls_put:
	pop hl
	ld (hl),a
	ret

V_SND_TICK:
;  РАЗ В КАДР (из кадрового прерывания). Отсчитывает сроки жизни нот с
;  огибающей и по нулю останавливает счётчик. Портит a, bc, de, hl, флаги.
;  Если этой процедуры не звать — мелодия и так верна, а эффекты будут
;  тянуться бесконечно: у ВИ53 нет огибающей, гасить ноту больше некому.
	ld c,0x00
vst_l:
	ld b,0x00
	ld hl,v_life
	add hl,bc
	ld a,(hl)
	or a
	jp z,vst_next		; бессрочная нота (мелодия) — не трогаем
	dec a
	ld (hl),a
	jp nz,vst_next
	push bc
	ld hl,v_own		; срок вышел: счётчик остановить...
	add hl,bc
	ld (hl),0x00
	ld hl,v_bit1		; ...и пометить канал погашенным, чтобы следующая
	add hl,bc		;    запись в микшер не подняла ту же ноту заново
	ld a,(v_dead)
	or (hl)
	ld (v_dead),a
	call V_VI_CTRL
	pop bc
vst_next:
	inc c
	ld a,c
	cp 0x03
	jp c,vst_l
	ret

V_SND_INIT:
;  Заготовка «out (порт),a : ret» в ОЗУ, чистка зеркала и состояния,
;  остановка всех трёх счётчиков. Портит a, bc, hl, флаги.
	ld a,0xD3		; опкод OUT (n),a
	ld (v_stub),a
	ld a,0xC9		; опкод RET
	ld (v_stub+2),a
	ld hl,v_ayreg
	ld b,V_SND_VARS		; зеркало + метки + сроки + кэш делителей, одним куском
vsi_l:
	ld (hl),0x00
	inc hl
	dec b
	jp nz,vsi_l
	ld c,0x00
vsi_c:
	push bc
	call V_VI_CTRL
	pop bc
	inc c
	ld a,c
	cp 0x03
	jp c,vsi_c
	ret
