; ============================================================================
;  КЛАВИАТУРА: матрица MSX (порты AAh/A9h) -> матрица Вектора-06Ц (ВВ55)
;  ВЕСЬ КОД — В ПОДМНОЖЕСТВЕ i8080.
; ----------------------------------------------------------------------------
;  КАК ЧИТАЕТ MSX: out (AAh) = 0xF0|строка (старший полубайт F гасит CAPS,
;  клик и мотор), in (A9h) = 8 бит строки, АКТИВНЫЙ НОЛЬ.
;
;  КАК ЧИТАЕТ ВЕКТОР (ВВ55 №1, адресные линии переставлены, как и у ВИ53):
;    порт 0x00 = управляющее слово (0x8A = порт B на ВХОД, 0x88 = на ВЫХОД)
;    порт 0x03 = порт A: выбор ряда, АКТИВНЫЙ НОЛЬ (0xFE = ряд 0 ... 0x7F = ряд 7)
;    порт 0x02 = порт B: 8 бит ряда, АКТИВНЫЙ НОЛЬ
;    порт 0x01 = порт C: старший полубайт на вход — бит5 СС, бит6 УС, бит7 РУС
;                        (активный ноль), младший — лента/звук
;  Проверено по vector06js (src/io.js, src/keyboard.js) и по рабочему коду
;  kvalley-v06c/src/v06c/vec_saveunder.asm (vec_scan_keys, идёт на MiSTer).
; ----------------------------------------------------------------------------
;  ГРАБЛИ, ОПЛАЧЕННЫЕ В ДРУГИХ ПОРТАХ (reference_vector06c_palette_latch):
;   * порт 0x03 — ЭТО ЖЕ РЕГИСТР ВЕРТИКАЛЬНОЙ РАЗВЁРТКИ. Скан затирает
;     развёртку, поэтому V_KBD_POLL звать ТОЛЬКО в гасящем ходе (из кадрового
;     прерывания), а в конце вернуть значение из v_scroll;
;   * пока порт B на входе, бит mode512 никем не задан и на ЖЕЛЕЗЕ всплывает
;     в 1 -> вертикальные полосы по всему экрану. Держать 0x8A постоянно
;     нельзя: вход на миг скана, сразу обратно 0x88;
;   * запись управляющего слова в порт 0 СБРАСЫВАЕТ выходные защёлки портов
;     A и C. Поэтому порядок в хвосте ОБЯЗАТЕЛЕН: сперва 0x88 в порт 0, и
;     ТОЛЬКО ПОТОМ порт C, развёртка (порт 3) и кайма/режим (порт 2).
;     Восстановишь развёртку до возврата ППА — она затрётся, и верхней
;     строкой экрана покажется низ данных.
;  Значения возврата лежат в ячейках v_ppi_c / v_scroll / v_border: их ведёт
;  адаптер ЭКРАНА, здесь только сохранение-восстановление.
; ----------------------------------------------------------------------------
;  ЗАЧЕМ ТЕНЬ, А НЕ ОПРОС ПО ТРЕБОВАНИЮ. Цикл задержки проигрывателя музыки
;  (Вектор 2460..2477) опрашивает ВСЕ ДЕВЯТЬ строк MSX на каждой из 0x480
;  итераций — свыше 10 000 чтений на один тик мелодии. Сканировать матрицу
;  Вектора столько раз нельзя: это и время, и 10 000 порч развёртки, и
;  моргание mode512 на железе. Поэтому V_KBD_POLL раз в кадр собирает
;  ТЕНЕВЫЕ строки MSX (v_msxrow, 16 байт, ALIGN 16), а V_KBD_ROW только
;  читает готовый байт. Ровно так же устроен Knight Lore (vec_scan + read_port).
; ----------------------------------------------------------------------------
;  КАКИЕ КЛАВИШИ ИГРА РЕАЛЬНО ОПРАШИВАЕТ (выяснено по коду, адреса Вектора):
;
;  1. 1587: таблица D_1595 = 80,45,44,26,46 -> KBD_SCAN, пять клавиш подряд,
;     ответ складывается в b через rl b. Коды (строка<<4)|бит:
;        80 = строка 8 бит 0 = ПРОБЕЛ  -> огонь
;        45 = строка 4 бит 5 = P       -> вправо
;        44 = строка 4 бит 4 = O       -> влево
;        26 = строка 2 бит 6 = A       -> вниз
;        46 = строка 4 бит 6 = Q       -> вверх
;     Это классическая испанская раскладка Q/A/O/P/ПРОБЕЛ. Порядок в таблице
;     совпал с битами джойстика (b0 вверх ... b4 огонь) — оба пути отдают
;     одинаковый байт.
;  2. 088E: строка 0, маска 0x3E, сравнения 3C/3A/36/2E/1E — клавиши 1,2,3,4,5
;     (выбор персонажа в игре, гейт по LEVEL_VARS+7).
;  3. 12BC: строка 6, бит 0 = SHIFT (игровое действие у объекта).
;  4. 1F84 (KBD_CHK) и 155F: строка 3, бит 5 = H — пауза («ждать отпускания,
;     затем ждать любую клавишу»). НА ВЕКТОРЕ эту строку кормит ВК, а не H
;     (пауза переехала на ВК раньше, когда H был читом «влево»; читы комнат
;     теперь на 6..9, H свободна, но пауза осталась на ВК).
;  5. 1567, 18B3, 2465: сплошной перебор строк F0..F8, «нажата любая клавиша».
;
;  ВО ЧТО ОТОБРАЖЕНЫ НА ВЕКТОРЕ (матрица Вектора: код символа = ряд*8+бит+0x20,
;  то есть ряд 2 = '0'..'7', ряд 3 = '8'.., ряд 4 = '@'..'G', ряд 5 = 'H'..'O',
;  ряд 6 = 'P'..'W', ряд 7 = 'X'..'_', где '_' — клавиша ПРОБЕЛ):
;     вверх/вниз/влево/вправо -> ТОЛЬКО КУРСОРЫ ряда 0 (и джойстик, см. ниже).
;       В тени MSX они по-прежнему выглядят как Q/A/O/P — так читает игра —
;       но буквы Q/A/O/P на клавиатуре Вектора в тень НЕ ИДУТ: раскладка
;       Вектора другая (ЙЦУКЕН), испанский QAOP путал бы игрока (решение
;       владельца 2026-09-24).
;     ПРОБЕЛ -> ПРОБЕЛ (ряд 7 бит 7)
;     пауза -> ВК (ряд 0 бит 2)
;     1..5 -> 1..5 (ряд 2 биты 1..5; биты 6/7 = '6'/'7' в тень НЕ копируются —
;                   они отданы читам комнат)
;     SHIFT -> СС (порт 0x01 бит 5)
;  Курсоры — основной ход на железе без джойстика (порт 0x0E у vector06js
;  подкладывает стрелки сам, у настоящего Вектора — нет).
;  Строки MSX 1, 5, 7 и несуществующие 9..15 всегда отдают 0xFF: ни одна
;  клавиша игры в них не живёт, а сплошным перебором «любая клавиша»
;  ловится ПРОБЕЛОМ, цифрами 0..5, курсорами и ВК.
; ----------------------------------------------------------------------------
;  ЧИТЫ (решение владельца, 2026-09-22; docs/cheats.md).
;  Ни одна из клавиш ниже НЕ попадает в тень MSX — игра их не видит, и пока
;  режим не включён, они не делают ничего.
;     F1 + F3   ряд 1 биты 3 и 5   включить режим читов (только в окне
;                                  V_CHEAT_WIN кадров после V_CHEAT_ARM)
;     G         ряд 4 бит 7        god mode вкл/выкл (по фронту)
;     8         ряд 3 бит 0        комната вверх
;     9         ряд 3 бит 1        комната вниз
;     6         ряд 2 бит 6        комната влево
;     7         ряд 2 бит 7        комната вправо
;     K         ряд 5 бит 3        в комнату нижнего («смотрового») окна
;  Скан складывает их в один байт (b), фронты копятся в v_cpend; забирает
;  их V_CHEAT_MOVE (src/v06/cheat.asm, врезка в 0B45).
;  Порядок битов в b (его же читает cheat.asm): b0 вверх b1 вниз b2 влево
;  b3 вправо b4 K b5 G.

; ---------------------------------------------------------------- точки входа
; V_KBD_POLL — раз в кадр, В ГАСЯЩЕМ ХОДЕ: матрица Вектора -> тень строк MSX
; V_KBD_ROW  — a = 0xF0|строка -> a = байт строки MSX (замена out AAh / in A9h)
; V_KBD_SCAN — замена резидентной KBD_SCAN (Вектор 1CDF): c = код, ответ в CF
; V_KBD_INIT — начальная заливка тени (всё отпущено)
; V_CHEAT_ARM — открыть окно включения читов (зовёт V_START связки)
; -----------------------------------------------------------------------------

V_KBD_POLL:
;  Портит a, b, c, d, e, флаги. ЗВАТЬ ТОЛЬКО В ГАСЯЩЕМ ХОДЕ (см. шапку).
;  Порядок ниже: цифры 0..7 → читы 8/9 → курсоры → G → K → пробел →
;  окно F1+F3 → джойстик в тень → фронты читов → СС → хвост ППА.
	ld a,0x8A		; порт B -> ВХОД, порт C старший -> ВХОД
	out (0x00),a

; --- (1) Ряд 2: '0'..'7' в тень MSX; '6'/'7' — читы влево/вправо ---
	ld a,0xFB		; ряд 2 Вектора = '0'..'7'
	out (0x03),a
	in a,(0x02)
	ld c,a
	or 0xC0			; '6'/'7' в тень НЕ идут — читы комнат влево/вправо
	ld (v_msxrow+0),a	; строка 0 MSX: '0'..'5' как на Векторе
	ld a,c
	cpl			; 1 = нажата
	ld e,a
	and 0x40		; '6' -> бит 2 тени читов (влево)
	rrca
	rrca
	rrca
	rrca			; 6 -> 2
	ld b,a			; b — накопитель битов читов
	ld a,e
	and 0x80		; '7' -> бит 3 (вправо)
	rrca
	rrca
	rrca
	rrca			; 7 -> 3
	or b
	ld b,a

; --- (2) Ряд 3: '8'/'9' — читы вверх/вниз (в тень MSX не пишем) ---
	ld a,0xF7		; ряд 3: '8' = бит 0, '9' = бит 1
	out (0x03),a
	in a,(0x02)
	cpl
	and 0x03		; уже на местах b0/b1 (вверх/вниз)
	or b
	ld b,a

; --- (3) Ряд 0: курсоры → тень как MSX Q/A/O/P; ВК → пауза ---
	ld a,0xFE		; ряд 0 Вектора = курсоры
	out (0x03),a
	in a,(0x02)
	cpl			; 1 = нажата: b2 ВК b4 ВЛЕВО b5 ВВЕРХ b6 ВПРАВО b7 ВНИЗ
	ld c,a
	and 0x04		; ВК -> ПАУЗА: строка 3 MSX, бит 5
	rlca
	rlca
	rlca			; 2 -> 5
	cpl
	ld (v_msxrow+3),a
	ld a,c
	and 0x10		; ВЛЕВО -> 'O', бит 4 строки 4 MSX: сдвиг не нужен
	ld d,a			; d копит O/P/Q до записи в v_msxrow+4
	ld a,c
	and 0x20		; ВВЕРХ -> 'Q', бит 6 строки 4: 5 -> 6
	add a,a
	or d
	ld d,a
	ld a,c
	and 0x40		; ВПРАВО -> 'P', бит 5 строки 4: 6 -> 5
	rrca
	or d
	ld d,a
	ld a,c
	and 0x80		; ВНИЗ -> 'A', бит 6 строки 2: 7 -> 6
	rrca
	ld e,a			; e = маска вниз (активная единица)

; --- (4) Ряд 4: чит G; вниз из e → строка 2 MSX ---
	ld a,0xEF		; ряд 4 Вектора: 'G' = бит 7 (чит god mode).
				; Буква 'A' (бит 1) в тень НЕ идёт — ход только
				; со стрелок/джойстика (см. шапку).
	out (0x03),a
	in a,(0x02)
	cpl
	and 0x80		; 'G' -> бит 5 тени читов
	rrca
	rrca
	or b
	ld b,a
	ld a,e			; только стрелка ВНИЗ (-> MSX 'A')
	cpl
	ld (v_msxrow+2),a	; строка 2 MSX: бит 6 = 'A'

; --- (5) Ряд 5: чит K; стрелки O/P/Q из d → строка 4 MSX ---
	ld a,0xDF		; ряд 5: чит 'K' = бит 3 (нижнее окно)
	out (0x03),a
	in a,(0x02)
	cpl
	and 0x08
	rlca			; 3 -> 4
	or b
	ld b,a

	ld a,d			; только стрелки ВЛЕВО/ВПРАВО/ВВЕРХ (-> O/P/Q)
	cpl
	ld (v_msxrow+4),a	; строка 4 MSX: биты 4/5/6 = 'O'/'P'/'Q'

; --- (6) Ряд 7: ПРОБЕЛ → строка 8 MSX бит 0 ---
	ld a,0x7F		; ряд 7 Вектора: ПРОБЕЛ = бит 7
	out (0x03),a
	in a,(0x02)
	cpl
	and 0x80
	rlca			; 7 -> 0
	cpl
	ld (v_msxrow+8),a	; строка 8 MSX: бит 0 = ПРОБЕЛ

;  ОКНО ВКЛЮЧЕНИЯ ЧИТОВ. Ряд 1 Вектора (F1..F5) не нужен игре ни в одной
;  из девяти точек опроса, поэтому он сканируется ТОЛЬКО пока открыто окно.
;  v_carm: 0 — закрыто, V_CHEAT_INF (0xFF) — открыто БЕССРОЧНО, иначе
;  столько кадров ещё осталось. Зажаты F1 и F3 — v_cheat := 1 на всю партию;
;  окно закрылось — ряд 1 больше не читается и цена скана прежняя.
;  ПОЧЕМУ БЕССРОЧНО (правка по наблюдению владельца НА ЖЕЛЕЗЕ, 2026-09-23).
;  V_CHEAT_ARM зовёт V_START, а сразу за ним игра крутит ТИТРЫ и ждёт старта
;  партии — прежние 150 кадров кончались прямо на титрах, и зажатые «в момент
;  старта» F1+F3 уже ничего не включали. Теперь окно без срока держится всё
;  время титров, а срок V_CHEAT_WIN ему ставит ПЕРВЫЙ ВИТОК игрового цикла
;  (V_JOY_PACE связки, врезка 12E1).
	ld a,(v_carm)
	or a
	jp z,vkc_noarm
	inc a			; V_CHEAT_INF (0xFF) — окно БЕЗ СРОКА: идут титры,
	jp z,vkc_scan		; партия ещё не началась, срок не убавляем
	dec a
	dec a
	ld (v_carm),a
vkc_scan:
	ld a,0xFD		; ряд 1 Вектора: F1 = бит 3, F3 = бит 5
	out (0x03),a
	in a,(0x02)
	cpl
	and 0x28		; F1 и F3 ОБЕ нажаты
	cp 0x28
	jp nz,vkc_noarm
	ld a,0x01
	ld (v_cheat),a
;  F1+F3 САМИ СТАРТУЮТ ПАРТИЮ (решение владельца, 2026-09-23). На железе
;  тройное нажатие F1+F3+ПРОБЕЛ теряется: старт не срабатывает, титры
;  крутятся дальше (замер на MiSTer — по отдельности F1+старт и F3+старт
;  запускают, вместе нет). Поэтому пока идут ТИТРЫ, сама пара F1+F3
;  подмешивает в тень ПРОБЕЛ — игра видит «нажата любая клавиша» и
;  начинает партию уже с включённым режимом. Нажимать пробел не надо.
;  Признак титров — v_carm = V_CHEAT_INF: срок окну ставит первый виток
;  игрового цикла, то есть в игре сюда с 0xFF уже не попасть, и пробел
;  не подмешивается (иначе герой жёг бы энергию магией всё окно).
	ld a,(v_carm)
	inc a
	jp nz,vkc_close		; не 0xFF — партия уже идёт, только закрыть окно
	ld a,(v_msxrow+8)
	and 0xFE		; ПРОБЕЛ = строка 8 бит 0, активный ноль
	ld (v_msxrow+8),a
	jp vkc_noarm		; окно НЕ закрываем: держим старт, пока пара зажата
vkc_close:
	xor a
	ld (v_carm),a		; окно больше не нужно
vkc_noarm:

;  ДЖОЙСТИК -> ТЕ ЖЕ КЛАВИШИ. Титры («любая клавиша»), выбор персонажа и
;  пауза опрашивают только клавиатуру, поэтому джойстик подмешивается в
;  тень: ОГОНЬ -> ПРОБЕЛ, ВВЕРХ -> Q, ВНИЗ -> A, ВЛЕВО -> O, ВПРАВО -> P.
;  Порт 0x0E, активный ноль: b0 ВПРАВО b1 ВЛЕВО b2 ВВЕРХ b3 ВНИЗ b6/b7 ОГОНЬ
;  (см. joy.asm); без джойстика порт отдаёт 0xFF — ничего не подмешивается.
	in a,(0x0E)
	cpl			; 1 = нажато
	ld c,a
	and 0xC0
	jp z,vkj_nofire
	ld a,(v_msxrow+8)
	and 0xFE		; ПРОБЕЛ = бит 0, активный ноль
	ld (v_msxrow+8),a
vkj_nofire:
	ld a,c
	and 0x08		; ВНИЗ -> 'A' = строка 2 бит 6: 3 -> 6
	rlca
	rlca
	rlca
	cpl
	ld d,a
	ld a,(v_msxrow+2)
	and d
	ld (v_msxrow+2),a
	ld a,c
	and 0x01		; ВПРАВО -> 'P' = строка 4 бит 5: 0 -> 5
	rlca
	rlca
	rlca
	rlca
	rlca
	ld e,a
	ld a,c
	and 0x02		; ВЛЕВО -> 'O' = строка 4 бит 4: 1 -> 4
	rlca
	rlca
	rlca
	or e
	ld e,a
	ld a,c
	and 0x04		; ВВЕРХ -> 'Q' = строка 4 бит 6: 2 -> 6
	rlca
	rlca
	rlca
	rlca
	or e
	cpl
	ld d,a
	ld a,(v_msxrow+4)
	and d
	ld (v_msxrow+4),a

;  ФРОНТЫ КЛАВИШ ЧИТОВ. b = «нажато сейчас»: b0 '8' b1 '9' b2 '6' b3 '7'
;  b4 'K' b5 'G'. Скан идёт 50 раз в секунду, а потребитель (V_CHEAT_MOVE,
;  врезка 0B45) — раз за виток игрового цикла, то есть втрое реже. Поэтому
;  фронт не отдаётся «как есть», а КОПИТСЯ в v_cpend до того, как его
;  заберут: иначе нажатие между витками пропадало бы. 'G' потребителя не
;  ждёт — переключатель god mode щёлкает прямо здесь.
;  Пока v_cheat = 0, фронты не копятся и god не переключается: без F1+F3
;  клавиши G/6/7/8/9/K не делают РОВНО НИЧЕГО.
	ld a,(v_cprev)
	cpl
	and b			; 1 = фронт нажатия
	ld c,a
	ld a,b
	ld (v_cprev),a
	ld a,(v_cheat)
	or a
	jp z,vkc_nocheat
	ld a,c
	and 0x1F		; 8 9 6 7 K -> копилка фронтов
	ld d,a
	ld a,(v_cpend)
	or d
	ld (v_cpend),a
	ld a,c
	and 0x20		; 'G' — переключить god mode
	jp z,vkc_nocheat
	ld a,(v_god)
	xor 0x01
	ld (v_god),a
vkc_nocheat:

	in a,(0x01)		; порт C, старший полубайт: бит 5 = СС (активный ноль)
	rlca
	rlca
	rlca			; 5 -> 0
	or 0xFE
	ld (v_msxrow+6),a	; строка 6 MSX: бит 0 = SHIFT, остальное отпущено

;  ХВОСТ. Порядок обязателен: управляющее слово сбрасывает защёлки A и C.
	ld a,0x88		; порт B обратно на ВЫХОД (mode512 = 0 задан всю
	out (0x00),a		; видимую часть кадра, иначе полосы на железе)
	ld a,(v_ppi_c)
	out (0x01),a
	ld a,(v_scroll)		; порт 3 = развёртка, её только что затёр выбор ряда
	out (0x03),a
	ld a,(v_border)		; порт 2 = кайма + режим 256/512
	out (0x02),a
	ret

V_KBD_ROW:
;  Вход: a = байт, который игра слала в порт 0xAA (0xF0|строка).
;  Выход: a = байт, который вернул бы in (0xA9) — маска строки, активный ноль.
;  Портит a и флаги; bc, de, hl целы.
	push hl
	and 0x0F
	add a,V_MSXROW_LO	; тень выровнена на 16 -> переноса нет, строки 9..15 = FF
	ld l,a
	ld h,V_MSXROW_HI
	ld a,(hl)
	pop hl
	ret

V_KBD_SCAN:
;  Полная замена резидентной KBD_SCAN (Вектор 1CDF), ABI тот же:
;  вход c = (строка<<4)|бит, выход CF = 1, если клавиша нажата.
;  Портит a и флаги; bc, de, hl целы. Оригинал делал то же самое через
;  djnz — здесь цикл на dec b/jp nz (DCR не трогает перенос ни у i8080,
;  ни у Z80, поэтому найденный бит в CF доживает до ret).
	push bc
	ld a,c
	and 0x07
	inc a
	ld b,a			; b = номер бита + 1
	ld a,c
	rrca
	rrca
	rrca
	rrca			; номер строки в младшем полубайте
	call V_KBD_ROW
	cpl			; активный ноль -> 1 = нажата
vks_l:
	rrca
	dec b
	jp nz,vks_l		; после (бит+1) сдвигов искомый бит лежит в CF
	pop bc
	ret

V_CHEAT_ARM:
;  Открыть окно включения читов БЕЗ СРОКА. Зовёт V_START связки — ОДИН раз,
;  когда заставка и справка уже позади и управление уходит в игру. Дальше
;  игра крутит ТИТРЫ и ждёт старта партии; всё это время V_KBD_POLL смотрит
;  ряд 1 Вектора: зажаты F1 и F3 — режим читов включён до конца партии.
;  СРОК окну ставит первый виток игрового цикла (V_JOY_PACE связки): там
;  v_carm := V_CHEAT_WIN, то есть ещё три секунды уже В ИГРЕ.
;  ПОЧЕМУ ТАК, А НЕ 150 КАДРОВ ОТ V_START (правка 2026-09-23). Замер на
;  стенде: V_START на кадре 169, первый виток игры — только на 563-м
;  (титры ждут старта сколько угодно). Прежние 150 кадров истекали ещё на
;  титрах, и владелец, зажимавший F1+F3 «в момент старта», окна уже не
;  заставал. Цена бессрочного окна — чтение одного ряда матрицы за кадр
;  титров, и только титров.
;  Портит a и флаги.
	xor a
	ld (v_cheat),a
	ld (v_god),a
	ld (v_cpend),a
	ld (v_cprev),a
	ld a,V_CHEAT_INF
	ld (v_carm),a
	ret

V_KBD_INIT:
;  Всё отпущено: 16 байт тени = 0xFF. Портит a, b, hl, флаги.
	ld hl,v_msxrow
	ld b,0x10
vki_l:
	ld (hl),0xFF
	inc hl
	dec b
	jp nz,vki_l
	ret
