; ============================================================================
;  ЧИТЫ (решение владельца, 2026-09-22). Полное описание — docs/cheats.md.
;  ВЕСЬ КОД — В ПОДМНОЖЕСТВЕ i8080, синтаксис мнемоник Z80, как везде в порте.
; ----------------------------------------------------------------------------
;  ГДЕ ЛЕЖИТ. org 4F3E — ничейная дырка между приёмником мёртвой записи
;  2:CE83 (4F36..4F3D) и телом адаптера экрана (5000), 194 байта
;  (docs/v06-memory.md § «4F3E..4FFF СВОБОДНО»). Сюда, а не в адаптер
;  ввода/звука, потому что адаптер после скана читов подошёл к 4DD7 и до
;  связки (4E00) осталось 40 байт. Модуль собирается ОТДЕЛЬНЫМ прогоном
;  ассемблера (tools/build_port_rom.py): положить его внутрь adapter.bin
;  нельзя — образ адаптера кладётся в память одним куском с 4A00, и дырка
;  до 4F3E затёрла бы таблицу звуковых эффектов 4EAA..4F21.
; ----------------------------------------------------------------------------
;  ЧТО ЗДЕСЬ И ЧЕГО ЗДЕСЬ НЕТ. Здесь — только ПОТРЕБИТЕЛИ нажатий. Сам скан
;  клавиатуры и накопление фронтов живут в V_KBD_POLL (src/v06/kbd.asm), там
;  же ячейки v_cheat / v_god / v_cpend: скан идёт раз в кадр, а сюда
;  управление приходит раз за виток игрового цикла (втрое реже).
; ----------------------------------------------------------------------------
;  ПОЧЕМУ ПЕРЕХОД СДЕЛАН ШТАТНЫМ ПУТЁМ, А НЕ ЗАПИСЬЮ НОМЕРА КОМНАТЫ.
;  Стенды tools/objetos_v06js.js и tools/shot_lustra_v06js.js ставят комнату
;  синтетически: врезка на границе витка пишет GAME_VARS+0xC и зовёт
;  перерисовку. Для СТЕНДА этого хватает, для игры — нет: кроме номера
;  комнаты меняются четвёрка соседей D_1D08, отметка «посещена», фоновое
;  окно героя и таблица атрибутов спрайтов. Всё это делает хвост штатного
;  перехода D619 (1F19) -> C38C (0C8C) -> C647 (0F47) -> D184 (1A84), и
;  именно его мы и зовём. Своей отрисовки у чита нет ни строчки.
; ----------------------------------------------------------------------------
;  ТОЧКИ ВРЕЗКИ (адреса Вектора; ставит tools/build_port_rom.py):
;    0B45  call C32C   -> call V_CHEAT_MOVE   (переход в соседнюю комнату)
;    122E  dec a ...   -> jp   V_CHEAT_ENER   (энергия не убывает)
;    0F27  ld (0838),a -> jp   V_CHEAT_DEATH  (смерть не срабатывает)
; ============================================================================

	org	0x4F3E

; ---------------------------------------------------------------------------
;  V_CHEAT_MOVE — врезка в 0B45, ХВОСТ ХОДА ГЕРОЯ.
;  0B45 (канон C245) — то место, куда игра возвращается после любого движения
;  героя (C260 кладёт адрес 0B45 на стек и раздаёт ветки движения), и первым
;  делом зовёт C32C — «не ушёл ли герой за край экрана». Лучшей точки для
;  чита нет: стек ровно тот же, что у штатной смены комнаты, координаты
;  героя уже обновлены, отрисовка кадра ещё не началась.
;  Врезка НЕ заменяет штатную проверку, а надставляет её: сперва C32C,
;  как было, и только потом чит.
; ---------------------------------------------------------------------------
V_CHEAT_MOVE:
	call	GM_EDGE		; C32C: штатный выход за край экрана
	ld	a,(v_cheat)
	or	a
	ret	z		; режим читов выключен — дальше ни байта
	ld	hl,v_cpend
	ld	a,(hl)
	and	0x1F		; b0 8 b1 9 b2 6 b3 7 b4 K
	ret	z
	ld	(hl),0x00	; фронты забрали
;  Номер направления = номер МЛАДШЕГО поднятого бита. Одновременное нажатие
;  двух клавиш разрешается в пользу младшей (8 > 9 > 6 > 7 > K), а не
;  запрещается: игрок всё равно не попадёт в два направления за один виток.
	ld	c,0x00
vcm_sh:
	rrca
	jp	c,vcm_dir
	inc	c
	jp	vcm_sh
vcm_dir:
	ld	a,c
	cp	0x04
	jp	z,vcm_low	; 'K' — комната нижнего окна, соседей не читаем
;  Соседи текущей комнаты — четвёрка D_1D08 (канон D408). Её кладёт туда
;  ldir'ом сама отрисовка комнаты D184 (1A94), поэтому после ЛЮБОГО перехода
;  она уже верна и чит может ходить подряд. Порядок байтов —
;  [вверх][вниз][влево][вправо] (docs/gameplay.md § 2.2), он же порядок
;  клавиш 8 9 6 7.
	ld	b,0x00
	ld	hl,GM_NB
	add	hl,bc
	ld	b,(hl)		; b = номер комнаты-соседа
	ld	a,b
	or	a
	ret	z		; 0 = выхода в эту сторону нет
	inc	a
	ret	z		; FF — на всякий случай тоже «нет»
;  КООРДИНАТА ВХОДА — та же, что ставит штатный C32C: герой появляется у
;  противоположного края новой комнаты. Повторено дословно, включая
;  «Y := 0x20 ДО вызова C36F» в ветке «вверх»: C36F может перерисовать нижнее
;  окно, а захват фона героя D69F (1F9F) делает это только при Y >= 0x60 —
;  оригинал сдвигает героя с нижней половины заранее, чтобы захвата не было.
	ld	a,c
	or	a
	jp	nz,vcm_1
	ld	hl,GV_Y		; ВВЕРХ (8)
	ld	(hl),0x20
	call	GM_LEAVE
	ld	(hl),0x60	; C36F сохраняет hl
	jp	vcm_set
vcm_1:
	dec	a
	jp	nz,vcm_2
	call	GM_LEAVE	; ВНИЗ (9)
	ld	hl,GV_Y
	ld	(hl),0x20
	jp	vcm_set
vcm_2:
	dec	a
	jp	nz,vcm_3
	call	GM_LEAVE	; ВЛЕВО (6)
	ld	hl,GV_X
	ld	(hl),0xA8
	jp	vcm_set
vcm_3:
	call	GM_LEAVE	; ВПРАВО (7)
	ld	hl,GV_X
	ld	(hl),0x00
vcm_set:
	ld	a,b
	ld	(GV_ROOM),a	; GAME_VARS+0xC — номер ВЕРХНЕЙ (игровой) комнаты
	jp	GM_TAIL		; D619: чистка атрибутов + C647 (перерисовка),
				; кончается ret — вернётся в 0B48, как штатный C32C

;  'K' — ПЕРЕЙТИ В КОМНАТУ, КОТОРАЯ ПОКАЗАНА В НИЖНЕМ ОКНЕ.
;  Нижнее («смотровое») окно показывает комнату LEVEL_VARS+0 (167B): туда
;  CA69 кладёт комнату шара, а клавиши 1..5 с шаром в руках — комнаты
;  предметов (docs/gameplay.md § 4). Чит переносит героя ровно туда, куда
;  игрок только что посмотрел. Координаты не трогаем: герой остаётся на
;  своём месте по X/Y, в god mode это безопасно.
vcm_low:
	ld	a,(GM_LOWROOM)
	or	a
	ret	z		; нижнее окно пусто — идти некуда
	ld	b,a
	call	GM_LEAVE
	jp	vcm_set

; ---------------------------------------------------------------------------
;  V_CHEAT_ENER — врезка в 122E (канон C92E), «убавить энергию на единицу».
;  Вход: a = текущий счётчик энергии, его только что прочитал `ld a,0x13` по
;  122C (операнд 122D самомодифицируемый — ЭТО и есть счётчик, поэтому врезка
;  начинается с 122E, а не с 122C: тремя байтами `jp` мы затёрли бы сам
;  счётчик, который пишут 1230 и 1325 и читают 0AC8 и 0F1E).
;  В god mode возвращаемся, НЕ тронув ни счётчик, ни полоску, ни звук.
;  Регистры и флаги целы (push af / pop af), хотя оригинал их и не берёг:
;  входов у процедуры четыре (jp 05F3, jp 0733, call 0AD6, провал из 1226),
;  и проверять каждый дороже, чем сохранить.
; ---------------------------------------------------------------------------
V_CHEAT_ENER:
	push	af
	ld	a,(v_god)
	or	a
	jp	z,vce_run
	pop	af
	ret			; god mode: энергия не убывает
vce_run:
	pop	af
	dec	a		; дальше — байт в байт оригинал 122E..1232
	push	af
	ld	(GM_ENERCNT),a
	jp	GM_ENERGO	; 1233

; ---------------------------------------------------------------------------
;  V_CHEAT_DEATH — врезка в 0F27 (канон C627), «герой умер».
;  Вся смерть в игре — ОДНА запись флага: C625 кладёт a=1 (орёл, плита,
;  тёмная комната 56), C92C через C627 кладёт a=2 (кончилась энергия), и обе
;  ветки сходятся на `ld (0838),a / ret`. Поэтому гасить смерть безопасно:
;  вызывающие (jp 0546, jp 0985, jp 0EDD, jp 0F0A, jp 1260) ждут только
;  возврата, никакого разбора стека за этим `ret` нет.
;  Жизни не убывают следствием: их снимает CA7B, а туда приходят по этому же
;  флагу.
;  a и флаги сохраняются: у оригинала `ld (nn),a / ret` их не трогал.
; ---------------------------------------------------------------------------
V_CHEAT_DEATH:
	push	af
	ld	a,(v_god)
	or	a
	jp	nz,vcd_no
	pop	af
	ld	(GM_DEADF),a
	ret
vcd_no:
	pop	af
	ret			; god mode: флаг смерти не ставится

V_CHEAT_END:
