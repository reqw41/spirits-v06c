; сборка i8080 — новые адреса рекомпилированного кода: он пересобирается по
; меткам и живёт не там, где лежал Z80-оригинал (docs/recompilation.md, §2).
; Оба файла генерирует tools/build_v06_rom.py.
#include        "cpu.inc"
