                inc     de
                ld      a,(RC_PH)
                inc     a
                ld      (RC_PH),a
                dec     c
                jp      nz,RC_COL
                ld      a,(RC_T)
                inc     a
                ld      (RC_T),a
                cp      0x20
                jp      nz,RC_ROW
                ret

