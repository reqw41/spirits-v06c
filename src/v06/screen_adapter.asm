; ---------------------------------------------------------------------
;  RECOLOR_SCREEN — переложить все 768 знакомест из старых кодов в новые.
;  Нужен ТОЛЬКО схеме «Exolon»: в «2 + 1» раздача кодов постоянная.
;  Знакоместа, чей код не меняется (XLAT[c] == c), пропускаются по одному
;  сравнению; пустые — по восьми чтениям одной плоскости.  Полная перекладка идёт
;  только там, где реально лежат пиксели, — а это почти всегда одна панель
;  HUD: игровое поле комнаты к этому моменту уже очищено.
; ---------------------------------------------------------------------
#if SCHEME == SCH_EXOLON
RECOLOR_SCREEN:
                ld      a,0x08
                ld      (RC_T),a
RC_ROW:
                ld      a,(RC_T)
                add     a,a
                add     a,a
                add     a,a
                add     a,0x07
                ld      (RC_PL),a       ; l = t*8+7 — верх ряда знакомест
                ld      a,(RC_T)
                ld      l,a
                ld      h,0x00
                add     hl,hl
                add     hl,hl
                add     hl,hl
                add     hl,hl
                add     hl,hl           ; t*32
                ld      de,INKBASE
                add     hl,de
                ex      de,hl           ; de = запись ряда в карте чернил
                ld      a,PLANE_A
                ld      (RC_PH),a
                ld      c,0x20          ; 32 столбца
; Указатель карты держится в de, счётчик столбцов — в c: CELL_RECOLOR
; сохраняет обе пары.  Перевод старого кода в новый — таблица XLAT, и она
; лежит по адресу, кратному восьми (V_VARS+0x38), поэтому индекс берётся
; одним `or` вместо add hl,de: 101 такт на неизменившееся знакоместо против
; 214 в прежней редакции, а их из 768 подавляющее большинство.
RC_COL:
