; =====================================================================
;  Spirits (MSX) -> Вектор-06Ц.  АДАПТЕР ЭКРАНА И СПРАЙТОВ.
;  Этап 1: две плоскости, 4 цвета (фон C000..DFFF, спрайты E000..FFFF).
;
;  Заменяет резидентный VDP-слой MSX.  Код строго в подмножестве i8080
;  (синтаксис Z80, но без IX/IY, EXX, LDIR, DJNZ, JR, CB-команд) —
;  проверяется tools/check_i8080.py по собранным байтам.
;
;  Раскладка Вектора — docs/v06-memory.md, контракт слоя — docs/msx-vdp-abi.md.
;  Адреса слоя здесь ВЕКТОРНЫЕ (оригинал минус 0xB700).
;
;  Пересчёт адреса.  Игра работает с VRAM SCREEN 2 как с линейным битмапом:
;  таблица имён 1800..1AFF ею НЕ ПИШЕТСЯ НИ РАЗУ (замер по build/runtime/
;  orig.vram: после 117 с прогона там 0 ненулевых байт), значит она остаётся
;  линейной, как её кладёт внешний инициализатор, и адрес образа равен
;    A = (y>>3)*256 + (x>>3)*8 + (y and 7)
;  На Векторе тот же пиксель лежит по
;    V = PLANE + ((A>>3) and 0x1F)*256 + 255 - ((A>>8)*8 + (A and 7))
;  то есть  hi = PLANE + (l>>3),  lo = not ((h*8) or (l and 7)).
;  ЭТАП F: модели адресов VRAM больше нет — A, который даёт игра, это просто
;  тройка (ряд, столбец, строка), и разбирают её CELLSPLIT/CELLADDR один раз
;  на вызов, а не на каждый байт, как делала снятая CONV.
;
;  КАРТА ФАЙЛА (куда смотреть):
;    SCR_INIT / SCR_PATCH / SCR_CLS     старт, патчи резидентного слоя, очистка
;    PAL_ISR / PAL_WRITE / PAL_HOOKUP   палитра из кадрового прерывания
;    CELLSPLIT / CELLADDR               адрес знакоместа → плоскости Вектора
;    INK_* / PUT3 / GET1 / MSKTAB       чернила и запись/чтение плоскостей
;    A_FILL / A_ROOMDRAW / A_CELLCOL    тайлы комнаты, заливка, столбец
;    A_TILEIMG / A_GLYPH8               образ тайла / глиф 8×8
;    A_RDBYTE/WRBYTE/COPY/RDSTRIDE…    побайтовый и полосный VDP-ABI
;    A_SPROBJ / A_SPRFLUSH / SPR_*      аппаратные спрайты MSX → плоскости
;    A_HERO / HERO_APPEND               герой (блит поверх фона)
;    CHA_TILE / CHA_SYNC                люстры
;    MG_*                               объединение коробок / магия
;    A_TITSTART / A_DISSOLVE / A_ICONCOL  титры и иконки
;  Контракт с игрой и полный разбор путей — docs/msx-vdp-abi.md,
;  docs/render-paths.md, docs/adapter-requirements.md.
; =====================================================================

; --- ПЕРЕКЛЮЧАТЕЛЬ СХЕМЫ ЦВЕТА.  Файл scheme.inc пишет tools/build_v06_rom.py
; по ключу --scheme; без ключа там SCHEME = SCH_EXOLON, и образ собирается
; БАЙТ В БАЙТ как до появления второй схемы.
;   SCH_EXOLON — три плоскости под тайлы, шесть чернил в пяти кодах-слотах,
;                раздача кодов своя на комнату (§ 0a требований);
;   SCH_CPC21  — «2 + 1»: тайлы только кодами 1, 2, 3 (плоскости C000 и
;                E000), плоскость A000 отдана подвижным объектам целиком.
;                Раскраска и палитра — из CPC-версии (docs/cpc-render.md
;                § 1.3 и § 3.2): код 1 всегда белый, коды 2 и 3 — перья 2 и 3
;                записи комнаты CPC.  Чернила в коды сводит ПОСТОЯННАЯ
;                таблица INK2CODE, поэтому раздача кодов не меняется никогда
;                и перекладка экрана при смене комнаты не нужна.
SCH_EXOLON      equ     1
SCH_CPC21       equ     2
#include        "scheme.inc"
