                ld      b,a             ; старый код
                or      XLAT & 0xFF
                ld      l,a
                ld      h,XLAT >> 8
                ld      a,(hl)          ; новый код
                cp      b
                jp      z,RC_NEXT
                ld      (ACL_CODE),a
                ex      de,hl
                ld      (ACL_MAP),hl
                ex      de,hl
                ld      a,(RC_PH)
                ld      h,a
                ld      a,(RC_PL)
                ld      l,a
                call    CELL_RECOLOR
