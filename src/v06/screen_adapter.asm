; тело адаптера (5000..631F).  Дырка 4F22..4FFF (222 б) не принадлежит
; никому: sfx-таблица обязана кончаться на 0xAA-выравнивании, а адаптер
; начинается с круглого 5000.
V_VAR2          equ     0x4F22
HP_SRC          equ     V_VAR2+0x00     ; HR_PREP: строка образа героя (2 б)
