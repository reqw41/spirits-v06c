; SPRST — ЧТО СЕЙЧАС НАРИСОВАНО, 33 записи по 4 байта (132 б):
;   +0,+1   адрес левого столбца в плоскости (hi = 0 — не нарисовано)
;   +2      сдвиг s = x and 7
;   +3      кадр героя (у аппаратных спрайтов не используется)
; SPRSAV — САМИ БАЙТЫ нарисованного, 32 записи по 32 байта (два столбца
; образа 16x16), следом HR_SAV — 3 столбца героя по 32 байта.
;
; ЗАЧЕМ СОХРАНЯТЬ БАЙТЫ.  Стирание при XOR — это повторный xor ТОГО ЖЕ
; образа по ТОМУ ЖЕ адресу, а теневую таблицу образов игра обнуляет в
; начале каждого кадра (res:D70F), то есть к следующему вызову прежних
; байтов уже нет.  Отсюда же и отказ от контрольной суммы: раз копия
; всё равно лежит рядом, «изменился ли образ» проверяется сравнением
; самих байтов — точно, а не с вероятностью 1/65536.
;
; ПОСЛЕДНЯЯ ЗАПИСЬ (№32) — ГЕРОЙ («гномик»), первые 32 — аппаратные
; спрайты MSX.  Коробка героя 4 столбца x 32 строки (образ 24x31..24x32
; плюс столбец, в который уезжает горизонтальный сдвиг x and 7), у
; спрайта — 3 x 16.
;
; Обе таблицы лежат ВНЕ тела адаптера: образ .rom заполняет эту область
; нулями, так что отдельная инициализация не нужна, а зоны
; зарегистрированы в docs/v06-memory.md §8 и в tools/verify_v06.py.
; ЭТАП E: СПИСКИ ОБЪЕКТОВ вместо SPRST/SPRSAV/HR_SAV.
;   SPRL — что рисуем в этом кадре (наполняет A_SPROBJ, перехват D0A0),
;   SPRO — что сейчас стоит на экране (копия списка прошлого кадра),
;   MIRBUF — развёрнутый по битам столбец зеркального образа.
; Запись — 8 байт, поля перечислены над A_SPRCLEAR.  Обе таблицы лежат ВНЕ
; тела адаптера: образ .rom заполняет эту область нулями, поэтому
; инициализация не нужна; зоны вписаны в tools/verify_v06.py.
;
; СЛИЯНИЕ E + F (2026-09-22): ОБА СПИСКА УЕХАЛИ С 6100 НА 4400.
; Тело адаптера после слияния этапов E и F — 4495 б («2 + 1»), а зона
; 5000..60E3 держала 4324.  Списки стояли ровно над ней (6100) и мешали
; её продлить.  Новое место — МЁРТВЫЕ ТЕНЕВЫЕ ТАБЛИЦЫ СПРАЙТОВ ИГРЫ:
; 407E..49FF после этапа E не читает и не пишет никто (замер
; tools/trap_stale_v06js.js, счётчик SHADOW: 0 чтений, 0 записей кодом
; игры за 3000 кадров), а её хвост 43C6..49FF лежит в образе НУЛЯМИ
; (ни один блок сборки туда не пишет) — значит инициализация по-прежнему
; не нужна.  Зона адаптера стала 5000..631F, а со слиянием стирания и
; рисования (2026-09-22) — 5000..6425, до самого стека.
SPRL            equ     0x4400          ; 4400..450F (34 x 8)
SPRO            equ     0x4510          ; 4510..461F (34 x 8)
; ОДНА ЗАПИСЬ ВМЕСТО СТИРАНИЯ И РИСОВАНИЯ (мерцание, 2026-09-22): телу
; адаптера понадобились ещё 250 б, и свободных в 5000..631F было 96.
; Зона тела продлена до СТЕКА (5000..6425), а всё, что стояло над ней, —
; MIRBUF и таблицы адресов записей банков — уехало в мёртвые теневые
; таблицы спрайтов игры (4864..49FF, 412 б; замер tools/trap_stale: код
; игры читал эту зону 0 раз и писал 0 раз).  Там же встали две новые
; таблички слияния.  Раскладка — docs/v06-memory.md § 8.
MIRBUF          equ     0x4864          ; 4864..488B (до 40 байт столбца)
                                        ; 488C..4969 — таблицы BKP
                                        ; (tools/repack_banks.py)
; MG_ZBUF — 40 НУЛЕЙ: «столбца образа здесь нет».  Слияние берёт его
; источником для столбца, в который приходит только перенос из соседнего
; (s = w), и тогда виток кладёт в плоскость ровно перенос, а в карту
; переноса — ноль.  Инициализации не требует: образ .rom кладёт сюда нули,
; и НИКТО СЮДА НЕ ПИШЕТ (зона вписана в tools/verify_v06.py).
MG_ZBUF         equ     0x4990          ; 4990..49B7
; MG_CARRY — карта переноса: биты, уехавшие из предыдущего столбца.  Лежит
; ХВОСТОМ СТРАНИЦЫ (последние h байт 49xx), чтобы виток кончался по `inc l`
; -> l = 0 и не тратил тактов на отдельный счётчик.  Обнуляется сама:
; последний столбец коробки (s = w) кладёт в неё нули по всей высоте.
MG_CARRY_PG     equ     0x49            ; 49D8..49FF (до 40 б)
MG_MAXN         equ     40              ; сторож: строк в коробке объединения
MG_MAXC         equ     8               ;         и столбцов
SPRL_LEN        equ     0x0008
SPRL_MAX        equ     34              ; 15 объектов игры + герой, с запасом
                                        ; на дубль второго окна (D655)
HERO_H          equ     0x20            ;  коробка героя: строк
           ;                строк

; ПОДСТАВКА СОБИРАЕМОГО ПРЕДМЕТА — НЕ СПРАЙТ, А ТАЙЛ (решение владельца
; 2026-09-22, docs/adapter-requirements.md § 0e).  Номер записи банка
; подвижных объектов; её рисует ТОЛЬКО хвост 2:CD70/CD72 («предмет уже
; подобран или нет — подставка есть всегда»), других рисовальщиков у неё
; нет: D202 берёт из этого банка только 0x17/0x18/0x19 (значки панели).
PED_NUM         equ     0x16

; ЛЮСТРА — ПАДАЮЩИЙ ОБЪЕКТ 0x1E — ТОЖЕ ТАЙЛ (решение владельца 2026-09-22,
; docs/adapter-requirements.md § 0e).  Рисует её один хвост игры
; (2:BC18/BC22, таблица BCC3 — шесть размещений), чернила MSX 15 (белый),
; INK2CODE даёт КОД 1, а код 1 — это ровно одна плоскость E000.  В отличие
; от подставки люстра ДВИЖЕТСЯ (падает по 4 px в кадр), поэтому у неё есть
; свой крошечный список «что нарисовано» — CHL/CHO ниже.
CHA_NUM         equ     0x1E
CHA_MAX         equ     2               ; на экране их не больше двух: комнаты
                                        ; шести записей BCC3 РАЗНЫЕ, значит одна
                                        ; в верхнем окне и одна в нижнем
CH_LEN          equ     3               ; запись: lo, hi, сдвиг

; Адаптер ввода и звука (src/v06/adapter.asm, другой агент) занимает
; 4A00..4C92, поэтому экранный слой живёт с 5000.
                org     0x5000
; ---------------------------------------------------------------------
;  Точки входа с фиксированными адресами
; ---------------------------------------------------------------------
                jp      SCR_INIT        ; 5000 — палитра, очистка, патчи, пуск
                jp      SCR_PATCH       ; 5003 — только патчи слоя
                jp      SCR_CLS         ; 5006 — очистить обе плоскости

; =====================================================================
;  ИНИЦИАЛИЗАЦИЯ
; =====================================================================
; Палитру на Векторе защёлкивает растр: номер слота берётся из индекса
; цвета пикселя ПОД ЛУЧОМ и равен значению из порта 02 только в кайме и
; гашении.  Плоскости 0 и 1 заняты кодом и данными игры, то есть в
; картинке под лучом лежит произвольный индекс — писать палитру «когда
; попало» нельзя, цвет уедет в случайный слот.  Поэтому палитра грузится
; из кадрового прерывания, со ВТОРОГО (первое после долгого DI приходит
; посреди кадра).
SCR_INIT:
                di
                ld      sp,GAME_STACK
                ; ТРЕТЬЯ ЗОНА ПЕРЕМЕННЫХ (V_VAR3, 4300..) — В НУЛИ.  В отличие
                ; от 6800 и 4F22 она НЕ пуста в образе: 02A0..43C5 — блок
                ; игры целиком, и в мёртвых теневых таблицах спрайтов лежат
                ; байты оригинала.  Замер: 434C в образе 0x0F7F.
                ld      hl,V_VAR3
                ld      b,V_VAR3_LEN
SI_ZV:
                ld      (hl),0x00
                inc     hl
                dec     b
                jp      nz,SI_ZV
                ; безобидный ISR на 0038 — до него ei давать нельзя
                ld      a,0xFB          ; ei
                ld      (0x0038),a
                ld      a,0xC9          ; ret
                ld      (0x0039),a
                call    SCR_CLS
                call    SCR_PATCH
                ; временный ISR палитры
                ld      a,0xC3          ; jp
                ld      (0x0038),a
                ld      hl,PAL_ISR
                ld      (0x0039),hl
                xor     a
                ld      (PAL_CNT),a
                ei
SI_WAIT:
                ld      a,(PAL_CNT)
                cp      0x02
                jp      nz,SI_WAIT
                di
                ld      a,0xFB          ; ei
                ld      (0x0038),a
                ld      a,0xC9          ; ret
                ld      (0x0039),a
                ld      sp,GAME_STACK
                ei
                jp      GAME_ENTRY

PAL_ISR:
                push    af
                push    bc
                push    hl
                ld      a,(PAL_CNT)
                inc     a
                ld      (PAL_CNT),a
                cp      0x02
                jp      nz,PI_OUT
                call    PAL_WRITE
PI_OUT:
                pop     hl
                pop     bc
                pop     af
                ei
                ret

; ---------------------------------------------------------------------
;  PAL_ISR2 — ПОСТОЯННЫЙ перехват кадрового прерывания ради палитры.
;  Ставится ЛЕНИВО, при первой смене палитры (SET_ROOM_PAL): к этому
;  времени связка порта (src/v06/glue.asm, её трогать нельзя) уже положила
;  на 0038 свои три байта `jp V_ISR`, и поставь мы перехват раньше — она бы
;  его затёрла.  Прежние три байта копируются в PAL_OLD и исполняются
;  следом, поэтому цепочка работает и в полном порте (`jp V_ISR`), и в
;  образе одного экранного адаптера (`ei / ret`).
; ---------------------------------------------------------------------
PAL_ISR2:
                push    af
                ld      a,(PAL_DIRTY)
                or      a
                jp      z,PI2_OUT
                push    bc
                push    hl
                xor     a
                ld      (PAL_DIRTY),a
                call    PAL_WRITE
                pop     hl
                pop     bc
PI2_OUT:
                pop     af
                jp      PAL_OLD

; PAL_WRITE — 16 слотов палитры в порт 0C.  Номер слота на Векторе
; защёлкивает растр, и совпадает он со значением порта 02 только в кайме и
; гашении, поэтому звать ТОЛЬКО из прерывания (reference_vector06c_palette_latch).
PAL_WRITE:
                ld      a,SCROLL_TOP
                out     (0x03),a        ; развёртка: картинка по центру экрана
                ld      hl,PAL_TAB+15
                ld      b,0x10
                ld      c,0x0F
PW_L:
                ld      a,c
                out     (0x02),a        ; номер слота (он же цвет каймы)
                ld      a,(hl)
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                dec     hl
                dec     c
                dec     b
                jp      nz,PW_L
                xor     a
                out     (0x02),a
                ret

; Палитра, схема «Exolon» (docs/adapter-requirements.md § 0a):
; P[i] = C[i and 7].  Невидима ОДНА плоскость — 8000 (вес 8), в ней лежит
; хвост блока данных игры.  Видимы три: A000 (вес 4), C000 (вес 2),
; E000 (вес 1).
;
; Восемь кодов (этап C, раздачу считает tools/mk_room_pal.py):
;   0 — пусто/чёрный;
;   3 — СКРЫТЫЙ ЧЁРНЫЙ: чернила MSX 1 (чёрное на чёрном).  Пиксели хранятся,
;       но не видны.  Без него пропадают титры и панель HUD: и то и другое
;       рисуется ДО того, как игра задаёт цвет;
;   4 — БЕЛЫЙ: подвижные объекты (XOR в A000) и белые чернила HUD;
;   1, 2, 5, 6, 7 — пять СЛОТОВ чернил комнаты, раздаются по частоте.
; Таблица ниже — стартовая (до первой комнаты): слоты в порядке общей
; частоты по игре, скрытый чёрный на месте.  Дальше её каждую комнату
; переписывает SET_ROOM_PAL.
;
; В схеме «2 + 1» смысл кодов другой: 0 — чёрный, 1 — БЕЛЫЙ (перо 1 CPC,
; аппаратный код 0B во всех 87 комнатах), 2 и 3 — перья 2 и 3 комнаты,
; 4..7 — ЦВЕТ ПОДВИЖНЫХ ОБЪЕКТОВ: тайлы кодов 4..7 в этой схеме не
; существуют (INK2CODE даёт только 0..3), а спрайт над тайлом кода c даёт
; c xor 4, то есть 4, 5, 6 или 7 — все четыре обязаны быть одним цветом,
; иначе герой менял бы цвет, переходя с фона на фон.  Цвет этот —
; RP21_SPR = светло-серый (решение владельца 2026-09-22, § 0c требований):
; белый оставлен перу 1, самому частому фону, и герой на нём не пропадает.
; Записи 8..15 — зеркало: невидима ровно одна плоскость, 8000.
#if SCHEME == SCH_CPC21
; СТАРТОВЫЕ ЦВЕТА КОДОВ 2 и 3 — не нули: до первой отрисовки комнаты
; (SET_ROOM_PAL) на экране стоят ТИТРЫ, и их строки покрашены чернилами
; 10, 7 и 12, то есть кодами 1, 2 и 2.  При нулевом коде 2 строка 10
; («SPIRITS») была бы чёрной на чёрном.  На MSX она голубая
; (docs/msx-title.md § 2.2), отсюда циан 0xF8 = b 3/3, g 7/7, r 0.
; Код 3 на титрах не встречается; красный 0x07 — самое частое перо 3 в
; таблице комнат.  Байт палитры Вектора — BB GGG RRR (так его строит
; tools/mk_room_pal.py: RGB (0,96,0) -> 0x18, (0,96,255) -> 0xD8;
; проверено снимком — 0x3F даёт жёлтый, 0xF8 голубой), значит циан = 0xF8,
; красный = 0x07.  ВНИМАНИЕ: строка `палитра:` в выводе tools/shot_v06js.js
; печатает io.Palette с переставленными каналами и этому НЕ противоречит —
; авторитет здесь PNG кадрового буфера.
PAL_TAB:
                db      0x00,RP21_WHITE,0xF8,0x07
                db      RP21_SPR,RP21_SPR,RP21_SPR,RP21_SPR
                db      0x00,RP21_WHITE,0xF8,0x07
                db      RP21_SPR,RP21_SPR,RP21_SPR,RP21_SPR
#else
PAL_TAB:
                db      0x00,0x76,0x71,0x00,0xFF,0xFA,0xF6,0x96
                db      0x00,0x76,0x71,0x00,0xFF,0xFA,0xF6,0x96
#endif

; ---------------------------------------------------------------------
;  SCR_CLS — очистить A000..FFFF (все три ВИДИМЫЕ плоскости), 12288 push.
;  Невидимую 8000..9FFF не трогаем: там лежит хвост блока данных игры.
; ---------------------------------------------------------------------
SCR_CLS:
                di
                ld      (SC_HL),hl
                ld      hl,0x0000
                add     hl,sp
                ld      (SAVSP),hl
                ld      hl,0x0000
                ld      sp,hl
                ld      de,0x0000
                ld      bc,0x3000       ; 12288 пар = 24576 байт (A000..FFFF)
SC_L:
                push    de
                dec     bc
                ld      a,b
                or      c
                jp      nz,SC_L
                ld      hl,(SAVSP)
                ld      sp,hl
                ld      hl,(SC_HL)
                ei
                ret

; =====================================================================
;  ПАТЧИ РЕЗИДЕНТНОГО СЛОЯ
; =====================================================================
; Слой заменяется на месте: в голову каждой процедуры кладётся jp, а там,
; где заменяется кусок цикла, — call и nop'ы до конца куска.
SCR_PATCH:
                ld      hl,JP_TAB
                ld      b,JP_N
SP_J:
                push    bc
                ld      e,(hl)
                inc     hl
                ld      d,(hl)
                inc     hl
                ld      a,0xC3
                ld      (de),a
                inc     de
                ld      a,(hl)
                inc     hl
                ld      (de),a
                inc     de
                ld      a,(hl)
                inc     hl
                ld      (de),a
                pop     bc
                dec     b
                jp      nz,SP_J
                ld      hl,CALL_TAB
                ld      b,CALL_N
SP_C:
                push    bc
                ld      e,(hl)
                inc     hl
                ld      d,(hl)
                inc     hl
                ld      a,0xCD
                ld      (de),a
                inc     de
                ld      a,(hl)
                inc     hl
                ld      (de),a
                inc     de
                ld      a,(hl)
                inc     hl
                ld      (de),a
                inc     de
                ld      b,(hl)          ; сколько nop'ов дописать
                inc     hl
                xor     a
SP_CN:
                ld      (de),a
                inc     de
                dec     b
                jp      nz,SP_CN
                pop     bc
                dec     b
                jp      nz,SP_C
                ; --- адреса, собранные из байтов: переезд их не двигал
                ; (docs/v06-memory.md §5, проверка 4 — «единственное место,
                ; где переезд не доделан»).  На MSX это была свободная RAM,
                ; на Векторе F3xx и D5xx попадают прямо в экранные плоскости:
                ; без этих двух байт игра пишет свои таблицы на экран.
                ld      hl,BYTE_TAB
                ld      b,BYTE_N
SP_B:
                ld      e,(hl)
                inc     hl
                ld      d,(hl)
                inc     hl
                ld      a,(hl)
                inc     hl
                ld      (de),a
                dec     b
                jp      nz,SP_B
                ret

BYTE_TAB:
#if CPU_I8080 == 0                      ; для i8080 ВПЕЧЕНО В ИСХОДНИК (см. ниже)
                dw      G_19AE
                db      0x3C            ; res:D0AD ld h,0xF3 -> таблица 3C17..3C96
                dw      G_1BE8
                db      0x1E            ; res:D2E7 ld b,0xD5 -> таблица 1Exx
#endif
                ; Шестой адрес из байтов, мимо которого прошли все проверки:
                ; указатель на теневую таблицу образов спрайтов F800 кладётся
                ; в запись объекта ДВУМЯ 8-битными командами
                ;   res:D0FA ld (ix-3),0x00 / res:D0FE ld (ix-2),0xF8
                ; Поиск знал формы `ld h,n` и `ld d,n`, а `ld (ix+d),n` — нет.
                ; Без правки образы спрайтов писались по F800 — в плоскость
                ; спрайтов, 114 760 записей за 3000 кадров. Найдено
                ; tools/trap_stale_v06js.js.  F800 - 0xB700 = 4100.
#if CPU_I8080 == 0                      ; для i8080 ВПЕЧЕНО В ИСХОДНИК (см. ниже)
                dw      G_1A01
                db      0x41            ; res:D0FE ld (ix-2),0xF8 -> 0x41
#endif
                ; --- переходы, не переехавшие вместе с образом.  Дизассемблер
                ; ходит по потоку управления, и куски, до которых он не дошёл,
                ; печатаются сырыми байтами; их операнды остались с
                ; оригинальными адресами.  Тот же дефект, что описан в
                ; docs/v06-memory.md §4 (C1E8), только его чинили в
                ; entries.json, а этих не нашли.
                ;
                ; ШЕСТЬ ПРЕЖНИХ ПАТЧЕЙ ОТСЮДА УБРАНЫ: 0714/0735/0746/0755/
                ; 0758/0767 — это обработчики объектов (оригинал BE09..BE8C),
                ; они теперь разбираются как код (точки входа BF09/BF12/BF1A/
                ; BF36/BF3B/BF51/BF68 в tools/entries.json плюс 19 записей в
                ; STALE), и все их операнды переезжают сами.  Байтовый патч
                ; чинил у них только 6 переходов из 19 адресов; остальные 13
                ; (BF2A, BF23, BF14, BF15, BF18, BF1B, BF2B, BF2E, BF31)
                ; оставались адресами MSX и молча били в блок данных
                ; 8847..BF88 — в карты комнат.  Найдено ловушкой «исполнение
                ; внутри области данных» (tools/trap_stale_v06js.js).
                ;
                ; Оставшиеся восемь — куски, которые ловушка за 3000 кадров НЕ
                ; исполняла ни разу (DEAD_062D, D_10D2, D_1263, DEAD_1329,
                ; D_23CA).  Они оставлены как страховка: поправка -0xB700
                ; кратна странице, поэтому правится ровно один старший байт.
                dw      G_062F
                db      0x19            ; call 0xD0A0 -> 0x19A0
                dw      G_063B
                db      0x1C            ; call 0xD3F8 -> 0x1CF8
                dw      G_0641
                db      0x04            ; jp   0xBB89 -> 0x0489
                dw      G_10D5
                db      0x1B            ; call 0xD21D -> 0x1B1D
                dw      G_1266
                db      0x15            ; call 0xCCA7 -> 0x15A7
                dw      G_126F
                db      0x1A            ; call 0xD184 -> 0x1A84
                dw      G_1334
                db      0x1B            ; call 0xD21D -> 0x1B1D
                dw      G_23CD
                db      0x21            ; call 0xD868 -> 0x2168
                ; --- ВЫГРУЗКА ОКНА ГЕРОЯ ОТКЛЮЧЕНА.  D98E (228E) звать
                ; нельзя запретить: её первый байт САМОМОДИФИЦИРУЕТСЯ
                ; (2:BCFE кладёт 0xC9, BD21 — значение из a), и любой jp,
                ; положенный туда, игра испортит сама (docs/render-paths.md,
                ; Р6/П6).  Поэтому глушим на уровень ниже: D70D (200D) —
                ; единственный исполнитель выгрузки, зовут её только из
                ; 2298 и 22A5, то есть изнутри самой D98E, и её первый байт
                ; никто не переписывает.  Один байт 0xC9 убивает весь путь
                ; D70D/DA56/DA89 — 288 байт образов и 36 заливок цвета в
                ; кадр.
                dw      G_200D
                db      0xC9            ; res:D70D -> ret
                ; --- МАССИВ ОБЪЕКТОВ НАЧИНАЕТСЯ НА ОДИН СЛОТ ВЫШЕ.
                ; D0F2 клал ix = F229 (3B29) и затравку цепочки указателя
                ; образов в (ix-3)/(ix-2) = F226/F227.  Эти две ячейки лежат
                ; ВНУТРИ буфера зеркалирования F1A9..F228 (128 б, D2CC):
                ; образ 32x4 = 128 байт затирает их целиком.  В оригинале
                ; это сходило с рук только потому, что ПЕРВЫМ объектом кадра
                ; всегда был ГЕРОЙ (24x31 = 93 б, не переполняет) и он читал
                ; затравку раньше, чем её мог испортить чей-то зеркальный
                ; образ.  Герой из массива ушёл — первым стал аппаратный
                ; спрайт, и его же D2CC стирает затравку ДО того, как D447
                ; её прочтёт (D0A0 зовёт D2CC на 19E6, D447 на 19E9).
                ; Итог был: цепочка уезжает в 0x0080, D447 пишет образы в
                ; низкую память, через 25 кадров игра срывается.
                ; Лечится одним байтом: ix = 3B32, тогда затравка ложится в
                ; 3B2F/3B30 — за концом буфера зеркалирования.  Слотов
                ; массива при этом 15, ровно как было при живом герое.
#if CPU_I8080 == 0                      ; для i8080 ВПЕЧЕНО В ИСХОДНИК (см. ниже)
                dw      G_19F4
                db      0x32            ; res:D0F2 ld ix,F229 -> 3B32
#endif
                ; --- ЗАХВАТ ОКНА ПОД ГЕРОЕМ ОТКЛЮЧЁН.  D6A9 (1FA9) читала
                ; 288 байт экрана в 8030 и 36 знакомест цвета (jp D9AA) при
                ; каждой отрисовке комнаты — чистую копию фона под окном
                ; save-under.  Окна больше нет, читать её некому: буферы
                ; 8000..82F3 (756 б) не читает ни .2, ни слой.  Глушим два
                ; входа, а не саму D6A9: её ПЕРВЫЙ БАЙТ самомодифицируется
                ; (D007 кладёт 0xC9, D017 возвращает 0xCD, docs/render-paths
                ; Р4), а 1F92/1F9F не трогает никто, и зовут их только из
                ; 0F5A и 0F44, оба — `jp`, так что ret уходит правильно.
                dw      G_1F92
                db      0xC9            ; res:D692 -> ret
                dw      G_1F9F
                db      0xC9            ; res:D69F -> ret
                ; --- МЁРТВАЯ ЗАПИСЬ 2:CE83 `ld de,0x7F9C / ld bc,8 / ldir`.
                ; 0x7F9C на MSX не принадлежит ни одному сегменту (образ
                ; начинается с 82A0), читателей у этих 8 байт в живом коде
                ; нет (docs/render-paths.md, C.1).  Ассемблер операнд не
                ; двигал — по значению в каноне это КОНСТАНТА, а не адрес.
                ; Пока блок данных лежал на 8847, запись уходила в свободную
                ; зону; после переезда блока на 6847 адрес 7F9C пришёлся бы
                ; на карты комнат (оригинал 9B9C) — 8 затёртых байт карты.
                ; Правим ОБА байта операнда: 7F9C -> 4F36.  Прежний приёмник
                ; 679C..67A3 отдан КАРТЕ ЧЕРНИЛ (6500..67FF, § 2 v06-memory):
                ; ей нужны 768 подряд идущих байт, и восемь байт посреди них
                ; были бы дыркой.  Кратность странице тут не нужна: оба байта
                ; всё равно пишутся явно.
                ; СЛИЯНИЕ E + F: второй переезд, 60E4 -> 4F36.  60E4..60EB
                ; попали под продлённое тело адаптера (5000..631F); 4F36 —
                ; та же ничейная дырка 4F22..4FFF, что и вторая зона
                ; переменных, и она НЕ входит ни в одну зону слежения
                ; tools/trap_stale_v06js.js (иначе восемь законных записей
                ; ldir'а красили бы гейт).
                dw      G_1784
                db      0x36            ; 2:CE83 ld de,0x7F9C -> 0x4F36
                dw      G_1785
                db      0x4F
                ; --- ЭТАП D: ЗЕРКАЛЬНЫЙ ПУТЬ ЧЕРЕЗ АДРЕСА VRAM УМЕР.
                ; D141 (1A41..1A6B) — вывод байта справа налево с разворотом
                ; бит — вызывался ровно из одного места, ветки `jp z,L_1A41`
                ; внутри D202 (1B18).  D202 перехвачен целиком (A_TILEIMG
                ; рисует и прямо, и зеркально прямо из банка), значит в 1A41
                ; больше никто не приходит.  Адаптерный A_MIRROR (99 байт)
                ; снят; чтобы уцелевший оригинал не писал в порты 98/99
                ; Вектора, если сюда всё же придут по сомнительному
                ; `jp nz,L_1A49` из 172C, в голову цикла кладётся ret.
                dw      G_1A50
                db      0xC9            ; res:D150 -> ret
                ; --- ПРЯМОЙ ПУТЬ ЧЕРЕЗ АДРЕСА VRAM ТОЖЕ УМЕР.
                ; VDP_WR_STRIDE8 (1B1D) звали из двух мест: из D202 (1B18,
                ; ветка «бит 7 = прямой вывод») и из двух кусков игры,
                ; которые ловушка за 3000 кадров не исполняла ни разу
                ; (10D5, 1334 — их адреса чинит BYTE_TAB выше).  Замер:
                ; 32 вызова за 3000 кадров, ВСЕ с возвратом на 1AB0, то есть
                ; из D202.  D202 перехвачен — адаптерный A_WRSTRIDE (56 б)
                ; снят, а в голову оригинала кладётся ret: её первый байт —
                ; `push bc`, так что ret там стек не ломает.
#if SCHEME == SCH_EXOLON
                dw      G_1B1D
                db      0xC9            ; res:D21D -> ret
#endif
                ; --- ЦВЕТ ЗНАКОМЕСТА МИМО A_FILL.  Цикл D1BD зовёт
                ; VDP_FILL(bc=8) на КАЖДОЕ знакоместо цветового
                ; прямоугольника — то есть ради одного байта карты чернил
                ; гоняет разбор адреса и деление длины.  Перебиваем ОПЕРАНД
                ; call'а (1AE9/1AEA), опкод остаётся на месте: врезка через
                ; CALL_TAB сюда не годится, она дописывает минимум один nop,
                ; а лишнего байта в 1AE8..1AEA нет.
                ; Тот же приём для поиска записи в банке ЦВЕТА (1AD5):
                ; перебиваем операнд, опкод call остаётся.
                ; --- ЗНАЧКИ ПАНЕЛИ OBJETOS: КООРДИНАТА, ПЕРЕЕХАВШАЯ КАК АДРЕС.
                ; 2:CD9A/CDA2/CDAA кладут `ld bc,0xC860 / 0xC880 / 0xE860` —
                ; это ПАРА КООРДИНАТ (b = X, c = Y) для D202, а не адрес.
                ; Генератор раскладки видит число внутри образа, заводит на
                ; него метку и двигает вместе с кодом (-0xB700), и значки
                ; уезжают с колонок 25..29 панели в колонки 2..5 ИГРОВОГО
                ; ПОЛЯ, где их тут же затирает очистка половины экрана.
                ; Это и есть «485 пикселей OBJETOS» из docs/known-issues.md:
                ; замер с этим патчем даёт 0 расхождений из 48001 против 485
                ; без него (tools/cmp_color_msx.py).  Правится один старший
                ; байт на каждую пару — младший (Y) не менялся.
                ; Правильное место правки — tools/disasm_msx.py (не двигать
                ; эти три операнда вовсе); патч в адаптере не трогает образ и
                ; потому не требует пересдачи round-trip-гейтов.
#if CPU_I8080 == 0                      ; для i8080 ВПЕЧЕНО В ИСХОДНИК (см. ниже)
                dw      G_169C
                db      0xC8            ; 2:CD9A ld bc,0x1160 -> 0xC860
                dw      G_16A4
                db      0xC8            ; 2:CDA2 ld bc,0x1180 -> 0xC880
                dw      G_16AC
                db      0xE8            ; 2:CDAA ld bc,0x3160 -> 0xE860
#endif
                dw      G_1AD6
                db      BK_COL & 0xFF
                dw      G_1AD7
                db      BK_COL >> 8
                dw      G_1AE9
                db      A_CELLCOL & 0xFF
                dw      G_1AEA
                db      A_CELLCOL >> 8
                ; --- ЭТАП E: ЧИСТКА ТЕНЕВЫХ ТАБЛИЦ СПРАЙТОВ УМЕРЛА.
                ; D0F2 (19F2) начинал кадр двумя `ldir`: 128 байт теневой SAT
                ; байтом 0xD1 и 2048 байт теневой таблицы образов нулём —
                ; 2176 байт, около 46 тыс. тактов на КАЖДЫЙ кадр.  Обе
                ; таблицы мертвы: объект попадает на экран прямо из D0A0
                ; (перехват A_SPROBJ), а SAT и образы не читает больше никто.
                ; Перепрыгиваем оба цикла одним переходом на их продолжение
                ; 1D90 (D490 — сброс указателей).  Три байта вместо
                ; `ld hl,407E`.
#if CPU_I8080 == 0                      ; для i8080 ВПЕЧЕНО В ИСХОДНИК (см. ниже)
                dw      G_1A02
                db      0xC3
                dw      G_1A03
                db      0x90
                dw      G_1A04
                db      0x1D
#endif
                ; --- ЭТАП F: «СКРЫТОЕ ЦВЕТОМ» НЕ РИСУЕТСЯ ЗАРАНЕЕ.
                ; ВСЁ ЭТО — ТОЛЬКО ОСНОВНАЯ СХЕМА «2 + 1».  В «Exolon»
                ; восьмой код («скрытый чёрный», чернила MSX 1 -> код 3)
                ; есть, спрятанное там ХРАНИТСЯ и проявляется цветом, как на
                ; MSX, и переделывать нечего; а места в её зоне адаптера нет
                ; вовсе (docs/v06-memory.md § 11: свободен один байт).
#if SCHEME == SCH_CPC21
                ; ПЕЧАТЬ СТРОКИ ТИТРОВ В СКРЫТЫЕ СТРОКИ 17..19 ОТМЕНЕНА:
                ; перебиваем ОПЕРАНД `call CDF9` внутри цикла титров
                ; (2:CF73, 1873).  Врезка через CALL_TAB сюда не годится —
                ; она дописывает минимум один nop, а лишнего байта нет.
                dw      G_1874
                db      A_TITLINE & 0xFF
                dw      G_1875
                db      A_TITLINE >> 8
                ; ПОКАЗ ЗНАЧКА OBJETOS = ОТРИСОВКА: перебиваем операнд
                ; `call CF28` по 1634 — общий хвост 2:CD12/CD1F/CD2C.
                ; Остальные три вызова CF28 (0F15, 1518, 16F1) идут мимо:
                ; там цвет и так ложится ДО образа.
                dw      G_1635
                db      A_ICONCOL & 0xFF
                dw      G_1636
                db      A_ICONCOL >> 8
                ; ЗНАЧКИ БОЛЬШЕ НЕ РИСУЮТСЯ ЗАРАНЕЕ: 2:CD94 (1694) —  ret.
                dw      G_1694
                db      0xC9
                ; ПАНЕЛЬ HUD: «СНАЧАЛА ЦВЕТ, ПОТОМ ОБРАЗ».  В 2:CA3D
                ; порядок был CFCA, CD94, DAE9, CA0C, CF07 — то есть весь
                ; поток тайлов панели ложился под чернилами 1 и проявлялся
                ; цветом.  Меняем местами два `call`: 1343 зовёт CF07,
                ; 134C — CD94, которая теперь ret.  Правятся только
                ; операнды, опкоды на месте.
                dw      G_1344
                db      G_1807 & 0xFF   ; 1343: call CD94 -> call CF07
                dw      G_1345
                db      G_1807 >> 8
                dw      G_134D
                db      G_1694 & 0xFF   ; 134C: call CF07 -> call CD94 = ret
                dw      G_134E
                db      G_1694 >> 8
#endif
                ; --- ЭТАП F: МОДЕЛЬ АДРЕСОВ VRAM УМЕРЛА ЦЕЛИКОМ.
                ; Ни одна из этих четырёх процедур слоя больше не нужна:
                ; текущего адреса записи и чтения нет, побайтовых чтения и
                ; записи нет.  Уцелевшие входы (A_FILL, A_COPY, A_RDSTRIDE,
                ; A_GLYPH8) разбирают свой `hl` сами, один раз на вызов.
                ; В головы кладутся заглушки — ровно ради тех вызовов, что
                ; ловушка за 3000 кадров ВСЁ ЖЕ исполняет: res:D619 (1F1E и
                ; 1F27) гасит аппаратные спрайты в VRAM, и на Векторе эта
                ; VRAM никому не принадлежит.  Считает их
                ; tools/trap_stale_v06js.js.
                dw      G_1BFD
                db      0xC9            ; VDP_SET_RADDR -> ret
                dw      G_1C06
                db      0xC9            ; VDP_SET_WADDR -> ret
#if SCHEME == SCH_CPC21
                dw      G_1C20
                db      0xAF            ; VDP_RD_BYTE   -> xor a
                dw      G_1C21
                db      0xC9            ;                  ret
                dw      G_1C28
                db      0xC9            ; VDP_WR_BYTE   -> ret
#endif
BYTE_END:
BYTE_N          equ     (BYTE_END-BYTE_TAB)/3
; ВРЕЗКИ, СНЯТЫЕ ОТСЮДА В СБОРКЕ i8080 (CPU_I8080 = 1).  Каждая правила ОДИН
; БАЙТ внутри команды игры, а после рекомпиляции Z80 -> i8080 этого байта на
; прежнем месте нет: команда развёрнута в несколько.  Три из них впечены в
; исходник (tools/recompile_i8080.py, OPERAND_PATCH: 19F2, 19FE, 1A02), а
; четыре целят в МЁРТВЫЙ код, который рекомпиляция не собирает вовсе
; (19AD, 1BE7 — тела D0A0 и D2CC за перехватом; 169A/16A2/16AA — 2:CD9A и
; соседи за `ret` по 1694).  docs/recompilation.md, §2.
; --- Три «спорных» адреса из байтов (docs/v06-memory.md §5, проверка 4)
; РАЗОБРАНЫ и НЕ патчатся: все три — значения, а не адреса.
;   2:C118 `ld l,c / ld h,0xA8` — координата, а не банк спрайтов: соседние
;     ветки кладут в ту же пару `ld h,b`, `ld l,0x60`, `ld l,0x20`,
;     `ld h,0x00`, а через четыре команды та же константа встречается как
;     порог сравнения `ld a,0xA8 / cp b`.  Пара тут же уходит в `push hl`.
;     Патч 0xA8 -> 0xAC был бы сдвигом координаты на 4.
;   2:BEC1 `ld d,0x98` — флаг, а не ROOM_MAPS: единственное употребление —
;     `ld h,d` в L_BE8D (res-адрес BE9B), дальше `ld a,h / cpl / and 0x80`,
;     то есть читается только бит 7; сам d тут же затирается `ld a,r / ld d,a`.
;   2:C3D3 `ld d,0xF8` — знаковое смещение: рядом `ld d,0x10`, `ld e,0xF6`.

JP_TAB:
                dw      G_1C11,A_FILL           ; VDP_FILL
                dw      G_1C33,A_COPY           ; VDP_COPY_TO_VRAM (1C32 = ex de,hl)
                dw      G_1CB4,A_RDSTRIDE       ; VDP_RD_STRIDE8
                dw      G_2168,A_HERO           ; D868 «нарисовать героя»
                dw      G_1A84,A_ROOMDRAW       ; D184 ROOMDRAW: палитра комнаты
                ; --- ЭТАП D: ПРЯМОЙ ВЫВОД ТАЙЛОВ
                dw      G_1A9F,A_ROOMLOOP       ; D19F цикл элементов комнаты
                dw      G_1B02,A_TILEIMG        ; D202 образ элемента из банка
                dw      G_1746,A_GLYPH8         ; 2:CE46 глиф 8 байт = знакоместо
                ; --- ЭТАП E: ПРЯМОЙ ВЫВОД ПОДВИЖНЫХ ОБЪЕКТОВ
                dw      G_19A0,A_SPROBJ         ; D0A0 «положить объект»
#if SCHEME == SCH_CPC21
                ; --- ЭТАП F: ТИТРЫ МИМО СКРЫТОЙ КОПИИ
                dw      G_183E,A_TITSTART       ; 2:CF3E вход в титры
                dw      G_150D,A_ENDSTART       ; 2:CC0D вход на экран итога
                dw      G_1921,A_DISSOLVE       ; D021 растворение
                dw      G_1B1D,A_WRSTRIDE       ; VDP_WR_STRIDE8 — ожила
#else
                ; В «Exolon» скрытая копия живёт под кодом 3 и переносится
                ; штатным D021, значит побайтовые чтение и запись ей нужны.
                dw      G_1C20,A_RDBYTE         ; VDP_RD_BYTE
                dw      G_1C28,A_WRBYTE         ; VDP_WR_BYTE
#endif
JP_END:
JP_N            equ     (JP_END-JP_TAB)/4

; адрес, цель, сколько nop'ов после call
; --- ТРИ SAVE-UNDER ОКНА ГЕРОЯ (1FC7, 204D, 2070) ГЛУШАТСЯ, А НЕ ЗАМЕНЯЮТСЯ.
; Раньше на их месте стоял адаптерный A_RDRUN (75 б), читавший плоскости в
; буферы окна 8000..82F3.  Окна нет: D692/D69F/D70D заглушены ret'ом ещё на
; этапе A, а D8CF (единственный, кто звал 204D/2070) вызывался только из
; D868, то есть из перехваченного A_HERO.  Замер (tools, 3000 кадров):
; 1FC7 — 0 вызовов, 204D — 0, 2070 — 0.  Буферы 8000..82F3 после переезда
; блока данных лежат ВНУТРИ КАРТ КОМНАТ (6847..8B9B), поэтому оставлять там
; исходный `in a,(0x98)` нельзя — он бы писал мусор в карты; кладём ret.
CALL_TAB:
                dw      G_1FC7,A_RDNUL
                db      8                       ; 1FC7..1FD1 save-under 0x30 б
                dw      G_204D,A_RDNUL
                db      10                      ; 204D..2059 save-under 0x08 б
                dw      G_2070,A_RDNUL
                db      10                      ; 2070..207C save-under 0x30 б
                dw      G_1F64,A_SPRFLUSH
                db      21                      ; 1F64..1F7B заливка таблиц спрайтов
CALL_N          equ     4

; =====================================================================
;  ЗНАКОМЕСТО: РАЗБОР ПАРАМЕТРА И АДРЕС В ПЛОСКОСТИ
; =====================================================================
;  ЭТАП F: МОДЕЛИ АДРЕСОВ VRAM БОЛЬШЕ НЕТ.  До него слой держал ТЕКУЩИЙ
;  адрес записи и чтения (VRAW/VADDR, их ставили A_SETRADDR/A_SETWADDR), а
;  процедура CONV раскладывала его обратно в «столбец, строка» на КАЖДЫЙ
;  байт.  Теперь параметр `hl`, который игра передаёт трём уцелевшим входам
;  (A_FILL, A_COPY, A_RDSTRIDE, A_GLYPH8), разбирается ОДИН РАЗ на вызов и
;  сразу в терминах знакомест: игра адресует таблицы VDP как
;      A = ряд*256 + столбец*8 + строка,
;  то есть hl И ЕСТЬ тройка (ряд, столбец, строка), записанная в два байта.
;
;  CELLSPLIT — разобрать hl на (AF_ROW, AF_COL, TMPQ).
;  AF_ROW держит ряд ВМЕСТЕ с номером таблицы (биты 5..6): 00..17 — образы,
;  1B — атрибуты спрайтов, 20..37 — цвет.  Бит 13 адреса, который прежде
;  добирался из самомодифицируемого байта MASKW (res:D30D+1), отброшен: его
;  ставила только res:DA86, а она лежит за заглушённой D70D и не
;  исполняется — это считает ловушка tools/trap_stale_v06js.js.
;  Вход hl; портит a; сохраняет hl, bc, de.
CELLSPLIT:
                ld      a,l
                and     0x07
                ld      (TMPQ),a
                ld      a,l
                rrca
                rrca
                rrca
                and     0x1F
                ld      (AF_CX),a
                ld      a,h
                and     0x3F
                ld      (AF_ROW),a
                ret

;  CELLADDR — адрес байта в плоскости A000 по разобранному знакоместу:
;  hi = PLANE_A + столбец, lo = 255 - (ряд*8 + строка).
;  Портит a; сохраняет bc, de.
CELLADDR:
                ld      a,(AF_ROW)
                and     0x1F
                add     a,a
                add     a,a
                add     a,a
                ld      l,a
                ld      a,(TMPQ)
                or      l
                cpl
                ld      l,a
                ld      a,(AF_CX)
                add     a,PLANE_A
                ld      h,a
                ret

; =====================================================================
;  ЧЕРНИЛА: МАСКИ ПЛОСКОСТЕЙ ПО КОДУ ЗНАКОМЕСТА
; =====================================================================
; MSKTAB — по коду 0..7 три маски: плоскость A (вес 4), C (вес 2), E (вес 1).
; Запись — ровно три байта: этапу D понадобились восемь байт в теле адаптера
; под патч координат значков OBJETOS (BYTE_TAB), и выравнивающий четвёртый
; байт отдан им; индекс считается как 3*код (`ld l,a / add a,a / add a,l`).
MSKTAB:
                db      0x00,0x00,0x00          ; 0  пусто/чёрный
                db      0x00,0x00,0xFF          ; 1
                db      0x00,0xFF,0x00          ; 2
                db      0x00,0xFF,0xFF          ; 3  скрытый чёрный
                db      0xFF,0x00,0x00          ; 4  белый (он же спрайты)
                db      0xFF,0x00,0xFF          ; 5
                db      0xFF,0xFF,0x00          ; 6
                db      0xFF,0xFF,0xFF          ; 7

; ---------------------------------------------------------------------
;  INK_SET — выставить маски трёх плоскостей по знакоместу, в котором
;  лежит байт hl (адрес в плоскости A000).
;  Маски кладутся в операнды `and` внутри PUT3/PUTM и AF_CELL8 — так в
;  цикле не нужен четвёртый регистровый указатель, которого у 8080 нет.
;  Кэш по АДРЕСУ в карте: подряд идущие байты одного знакоместа (а это
;  восемь строк растра одного столбца) разбор не повторяют.
;  Вход hl; сохраняет hl, bc, de; портит a.
; ---------------------------------------------------------------------
; INK_ADDR — адрес знакоместа в карте чернил по адресу байта в плоскости A000.
; Вход hl; выход de; портит a; сохраняет hl, bc.
INK_ADDR:
                ld      a,l
                rrca
                rrca
                rrca
                and     0x1F            ; t = l>>3  (8..31 при y = 0..191)
                ld      d,a
                and     0x07
                rlca
                rlca
                rlca
                rlca
                rlca                    ; (t and 7)*32
                ld      e,a
                ld      a,h
                and     0x1F            ; столбец
                add     a,e
                ld      e,a             ; младший байт адреса карты
                ld      a,d
                rrca
                rrca
                rrca
                and     0x03
                add     a,INKBASE>>8
                ld      d,a
                ret

; INK_CODE — код знакоместа по адресу hl в плоскости; портит a, de.
INK_CODE:
                call    INK_ADDR
                ld      a,(de)
                ret

INK_SET:
                push    de
                call    INK_ADDR
                ld      a,(IS_PTR)
                cp      e
                jp      nz,IS_NEW
                ld      a,(IS_PTR+1)
                cp      d
                jp      z,IS_OUT        ; то же знакоместо — маски уже стоят
IS_NEW:
                ld      a,e
                ld      (IS_PTR),a
                ld      a,d
                ld      (IS_PTR+1),a
                push    hl
                ld      a,(de)          ; код 0..7
                ld      (IS_CODE),a     ; этап E: по нему сливаются полосы
                ld      l,a
                add     a,a
                add     a,l             ; 3*код — запись MSKTAB три байта
                ld      l,a
                ld      h,0x00
; В схеме «2 + 1» плоскость A000 отдана подвижным объектам целиком, тайлы в
; неё не пишут НИКОГДА (INK2CODE даёт только коды 0..3).  Значит и маски
; A000 незачем ни хранить, ни ставить: запись `and 0` + `ld (hl),a` не
; «ничего не делает», а КЛАДЁТ НОЛЬ поверх спрайта.  Отсюда же ненужность
; сторожа слотов — он существовал ровно ради этих записей.
#if SCHEME == SCH_CPC21
                ld      de,MSKTAB+1
#else
                ld      de,MSKTAB
#endif
                add     hl,de
#if SCHEME == SCH_EXOLON
                ld      a,(hl)
                ld      (P3_MA+1),a
                ld      (P8_MA+1),a
                ld      (TI_MA),a
                inc     hl
#endif
                ld      a,(hl)
                ld      (P3_MC+1),a
                ld      (P8_MC+1),a
                ld      (TI_MC),a
                inc     hl
                ld      a,(hl)
                ld      (P3_ME+1),a
                ld      (P8_ME+1),a
                ld      (TI_ME),a
                pop     hl
IS_OUT:
                pop     de
                ret

; INK_FLUSH — сбросить кэш INK_SET.  Обязателен после любой записи в карту
; чернил: ключ кэша — адрес, а не содержимое.
INK_FLUSH:
                ld      a,0xFF
                ld      (IS_PTR),a
                ld      (IS_PTR+1),a    ; FFFF — адрес, которого карта не даёт
                ret

 ; ---------------------------------------------------------------------
;  PUT3 — положить байт образа a по адресу hl (плоскость A000) во ВСЕ ТРИ
;  плоскости, замаскировав кодом знакоместа.  Сохраняет hl, bc, de.
;  GET1 (ниже) — обратное, и ПО ОДНОЙ плоскости: байт образа лежит в каждой
;  плоскости своего кода ОДИНАКОВЫМ, поэтому собирать его из трёх (прежний
;  GET3) незачем.  Плоскость берётся младшая из кода (CR_SRC), то есть
;  A000 с её подвижными объектами в чтение не попадает никогда.
; ---------------------------------------------------------------------
PUT3:
                ld      (P3_B),a
                call    INK_SET
                ld      a,(P3_B)
                ; PUTM — то же самое, но БЕЗ разбора знакоместа: маски уже
                ; выставлены (INK_SET).  Вход тот же, a = байт.  Этим пишут
                ; полосой — когда все восемь байт лежат в одном знакоместе
                ; (A_GLYPH8).
PUTM:
                ld      (P3_B),a
#if SCHEME == SCH_EXOLON
P3_MA:          and     0x00
                ld      (hl),a
#endif
                ld      a,h
                add     a,0x20
                ld      h,a
                ld      a,(P3_B)
P3_MC:          and     0x00
                ld      (hl),a
                ld      a,h
                add     a,0x20
                ld      h,a
                ld      a,(P3_B)
P3_ME:          and     0x00
                ld      (hl),a
                ld      a,h
                sub     0x40
                ld      h,a
                ret

GET1:
                push    de
                push    hl
                call    INK_ADDR        ; de = запись знакоместа в карте
                ld      a,(de)
                and     0x07
                jp      z,G1_Z          ; кода нет — и пикселей нет
                ld      e,a
                ld      d,0x00
                ld      hl,CR_SRC       ; младшая плоскость кода
                add     hl,de
                ld      a,(hl)
                pop     hl
                push    hl
                add     a,h
                ld      h,a
                ld      a,(hl)
                pop     hl
                pop     de
                ret
G1_Z:
                pop     hl
                pop     de
                xor     a
                ret

; =====================================================================
;  VDP_FILL — самая ходовая процедура слоя (11 call-sites из .2)
;  вход  a = байт, hl = адрес VRAM, bc = длина
;  выход a и hl сохранены, bc = 0
;  Внутри группы из 8 байт VRAM адреса Вектора идут ПОДРЯД ВНИЗ, поэтому
;  целые группы заливаются четырьмя push (11 тактов на 2 байта).
; =====================================================================
A_FILL:
                push    de              ; оригинал de НЕ ТРОГАЕТ, а вызывающий
                                        ; res:CDB3 держит в e счётчик 12 строк
                push    af              ; байт заливки сразу на стек: разбор
                                        ; знакоместа идёт через a
                ld      (AF_HL0),hl     ; вызывающему hl вернуть как дали
                call    CELLSPLIT
                ld      a,(AF_ROW)
                cp      0x18
                jp      c,AF_PAT
                cp      0x1B            ; таблица атрибутов спрайтов 1B00..1B7F?
                jp      z,AF_SAT
                cp      0x20            ; ТАБЛИЦА ЦВЕТА 2000..37FF
                jp      c,AF_DONE
                cp      0x38
                jp      c,AF_COL
                jp      AF_DONE         ; имена, образы спрайтов — игнор
AF_SAT:
                pop     af              ; байт заливки
                push    af
                cp      0xD0            ; Y >= 0xD0 — гашение
                jp      c,AF_DONE
                push    bc
                call    A_SPRCLEAR      ; портит всё, кроме стека
                pop     bc
                jp      AF_DONE

; --- ТАБЛИЦА ОБРАЗОВ: байт кладётся во все три плоскости по коду знакоместа.
; Заливка идёт ЗНАКОМЕСТАМИ: голова (хвост первого знакоместа), целые
; знакоместа, хвост.  Внутри знакоместа код один, поэтому маски ставятся один
; раз на восьмёрку (кэш INK_SET по адресу в карте).
AF_PAT:
                ld      a,b
                or      c
                jp      z,AF_DONE
#if SCHEME == SCH_EXOLON
                push    bc
                call    SPR_GUARD_ALL   ; заливка пишет и в плоскость A000
                pop     bc
#endif
                call    CELLADDR
                ld      (AF_HL),hl
                pop     af
                push    af
                ld      (AF_VAL),a
                ; n1 = 8 - q, но не больше длины
                ld      a,0x08
                ld      hl,TMPQ
                sub     (hl)
                ld      (AF_N1),a
                ld      a,b
                or      a
                jp      nz,AF_N1OK
                ld      a,(AF_N1)
                cp      c
                jp      c,AF_N1OK
                ld      a,c
                ld      (AF_N1),a
AF_N1OK:
                ld      a,c             ; bc -= n1
                ld      hl,AF_N1
                sub     (hl)
                ld      c,a
                jp      nc,AF_NB
                dec     b
AF_NB:
                ld      hl,(AF_HL)
                ld      a,c
                and     0x07
                ld      (AF_TAIL),a
                ld      a,b             ; bc >>= 3 — число целых знакомест
                or      a
                rra
                ld      b,a
                ld      a,c
                rra
                ld      c,a
                ld      a,b
                or      a
                rra
                ld      b,a
                ld      a,c
                rra
                ld      c,a
                ld      a,b
                or      a
                rra
                ld      b,a
                ld      a,c
                rra
                ld      c,a
                ld      a,(AF_N1)
                ld      (AF_CNT),a
                or      a
                jp      z,AF_H2
AF_HEAD:
                ld      a,(AF_VAL)
                call    PUT3
                dec     l
                ld      a,(AF_CNT)
                dec     a
                ld      (AF_CNT),a
                jp      nz,AF_HEAD
AF_H2:
                call    AF_NEXTCOL
                ld      a,b
                or      c
                jp      z,AF_TAILGO
AF_GRP:
                call    INK_SET         ; знакоместо целиком — маски один раз
                call    AF_CELL8        ; l возвращается на верх знакоместа,
                call    ACL_NEXT        ; поэтому шаг вправо — БЕЗ `l += 8`
                dec     bc
                ld      a,b
                or      c
                jp      nz,AF_GRP
AF_TAILGO:
                ld      a,(AF_TAIL)
                ld      (AF_CNT),a
                or      a
                jp      z,AF_FIN
AF_TL:
                ld      a,(AF_VAL)
                call    PUT3
                dec     l
                ld      a,(AF_CNT)
                dec     a
                ld      (AF_CNT),a
                jp      nz,AF_TL
AF_FIN:
AF_DONE:
                pop     af
                pop     de
                ld      hl,(AF_HL0)
                ld      bc,0x0000
                ret

; AF_NEXTCOL — hl на верхний байт следующего знакоместа вправо.
AF_NEXTCOL:
                ld      a,l
                add     a,0x08
                ld      l,a
                inc     h
                ld      a,h
                cp      PLANE_A_END
                ret     nz
                ld      h,PLANE_A
                ld      a,l
                sub     0x08
                ld      l,a
                ret

; ACL_NEXT — следующее знакоместо ВПРАВО для цветового прохода.  В отличие от
; AF_NEXTCOL, `l` не трогается: там он к этому моменту уже восемь раз ушёл
; вниз по знакоместу и возвращается наверх, а здесь мы всё время стоим на
; верхнем байте.  Из-за этой разницы первая версия цветового прохода уезжала
; на ряд знакомест вверх каждые восемь столбцов — на карте чернил это было
; видно диагональными клиньями незакрашенных знакомест.
ACL_NEXT:
                inc     h
                ld      a,h
                cp      PLANE_A_END
                ret     nz
                ld      h,PLANE_A
                ld      a,l
                sub     0x08
                ld      l,a
                ret

; AF_CELL8 — восемь байт ЦЕЛОГО знакоместа, ЧЕРЕЗ SP (§ 4 требований).
; Маски уже стоят (INK_SET), поэтому значение по плоскостям считается один
; раз.  Восемь байт знакоместа — это восемь ПОДРЯД ИДУЩИХ адресов вниз, то
; есть ровно четыре `push` парой одинаковых байт: 11 тактов на два байта
; против 12 на один у прежнего развёрнутого `ld (hl),a / dec l`.
;
; ЗАМЕР ПО ЛИСТИНГУ (tools/cycles_i8080.py, тот же приём, что в § 0a):
; прежний AF_PUT8 стоил 118 тактов на плоскость плюс 17 на `call` = 135;
; здесь плоскость стоит `ld sp,hl` 5 + 4 x `push de` 44 = 49 плюс 12 на
; перевод hl на следующую плоскость.  На знакоместо из двух плоскостей
; («2 + 1») было 310 тактов, стало 163 — экономия 147.
;
; DI КОРОТКИМ КУСКОМ.  Окно с чужим SP — ровно 98 тактов (два раза по
; четыре push плюс перевод hl), при пороге «меньше 2000» (прерывание на
; Векторе не защёлкивается).  Настоящий SP снимается `add hl,sp` и
; возвращается `ld sp,hl`: `ld (nn),sp` — команда Z80, её нельзя.
; de внутри A_FILL свободен: он спасён `push de` на входе.
AF_CELL8:
                ld      a,(AF_VAL)
                ld      (P3_B),a
#if SCHEME == SCH_EXOLON
P8_MA:          and     0x00
                ld      (AF_VA),a
                ld      a,(P3_B)
#endif
P8_MC:          and     0x00
                ld      (AF_VC),a
                ld      a,(P3_B)
P8_ME:          and     0x00
                ld      (AF_VE),a
                ld      (AF_SV),hl
                ld      hl,0x0000
                add     hl,sp
                ld      (SAVSP),hl
                ld      hl,(AF_SV)
                inc     hl              ; sp = верх знакоместа + 1
                di
#if SCHEME == SCH_EXOLON
                ld      a,(AF_VA)       ; плоскость A000 — вес 4
                ld      d,a
                ld      e,a
                ld      sp,hl
                push    de
                push    de
                push    de
                push    de
#endif
                ld      a,h
                add     a,0x20
                ld      h,a             ; плоскость C000 — вес 2
                ld      a,(AF_VC)
                ld      d,a
                ld      e,a
                ld      sp,hl
                push    de
                push    de
                push    de
                push    de
                ld      a,h
                add     a,0x20
                ld      h,a             ; плоскость E000 — вес 1
                ld      a,(AF_VE)
                ld      d,a
                ld      e,a
                ld      sp,hl
                push    de
                push    de
                push    de
                push    de
                ld      hl,(SAVSP)
                ld      sp,hl
                ei
                ld      hl,(AF_SV)      ; hl — на верху знакоместа, как был
                ret

; =====================================================================
;  ТАБЛИЦА ЦВЕТА MSX -> КАРТА ЧЕРНИЛ
; =====================================================================
;  Адрес цвета = 0x2000 + (y>>3)*256 + (x and F8) + (y and 7): на MSX цвет
;  задаётся на КАЖДУЮ строку знакоместа.  Игра, однако, всегда заливает все
;  восемь строк одним байтом — замер по трём дампам VRAM живого MSX
;  (tools/cmp_hero_msx.py, итерации 40/70/120): знакомест с разным цветом по
;  строкам 0 из 768.  Поэтому карта чернил хранится на ЗНАКОМЕСТО, а не на
;  строку, и это не упрощение «на глаз», а измеренный факт.
;
;  Младший полубайт (ФОН) игнорируется: он чёрный у 97.2 % знакомест
;  (docs/render-paths.md, A.7), остальные 2.8 % — фон «красный», и нулевые
;  биты образа у них на MSX красные.  У нас они чёрные — известное
;  расхождение, вынесено в docs/known-issues.md.
;
;  Если код знакоместа МЕНЯЕТСЯ, пиксели, которые в нём уже лежат, надо
;  переложить между плоскостями: на MSX смена цветового байта перекрашивает
;  ВСЁ знакоместо, и старые пиксели тоже.  Этим же держится порядок «сначала
;  образ, потом цвет», в котором игра рисует элементы комнаты: образ ложится
;  по СТАРОМУ коду, а цвет тут же перекладывает его по новому.
AF_COL:
                ld      a,b
                or      c
                jp      z,AF_DONE
                pop     af
                push    af
                rrca
                rrca
                rrca
                rrca
                and     0x0F            ; чернила MSX
                ld      e,a
                ld      d,0x00
                ld      hl,INK2CODE
                add     hl,de
                ld      a,(hl)
                ld      (ACL_CODE),a
                ; число знакомест = (q + длина + 7) >> 3
                ld      a,(TMPQ)
                add     a,c
                ld      c,a
                jp      nc,ACL_N1
                inc     b
ACL_N1:
                ld      a,c
                add     a,0x07
                ld      c,a
                jp      nc,ACL_N2
                inc     b
ACL_N2:
                ld      a,b
                or      a
                rra
                ld      b,a
                ld      a,c
                rra
                ld      c,a
                ld      a,b
                or      a
                rra
                ld      b,a
                ld      a,c
                rra
                ld      c,a
                ld      a,b
                or      a
                rra
                ld      b,a
                ld      a,c
                rra
                ld      c,a
                ld      a,b
                or      c
                jp      z,AF_DONE
                ; hl = ВЕРХНИЙ байт первого знакоместа в плоскости A000:
                ; строка внутри знакоместа цветовому проходу не нужна.
                ld      a,(AF_ROW)
                and     0x1F
                add     a,a
                add     a,a
                add     a,a
                cpl                     ; l = 255 - ряд*8
                ld      l,a
                ld      a,(AF_CX)
                add     a,PLANE_A
                ld      h,a
ACL_L:
                push    bc
                call    INK_ADDR        ; de = адрес в карте чернил
                ld      a,(de)
                ld      c,a
                ex      de,hl
                ld      (ACL_MAP),hl
                ex      de,hl
                ld      a,(ACL_CODE)
                cp      c
                jp      z,ACL_SAME
                call    CELL_RECOLOR
ACL_SAME:
                pop     bc
                call    ACL_NEXT
                dec     bc
                ld      a,b
                or      c
                jp      nz,ACL_L
                jp      AF_DONE

; ---------------------------------------------------------------------
;  CELL_RECOLOR — переложить знакоместо из старого кода в (ACL_CODE).
;  Вход hl = верхний байт знакоместа в плоскости A000, (ACL_MAP) = его
;  запись в карте чернил.  Сохраняет hl, bc, de.
;
;  ЭТАП D: ЧИТАЕМ ОДНУ ПЛОСКОСТЬ, А НЕ ТРИ.  Байт образа лежит в КАЖДОЙ
;  плоскости своего кода ОДИНАКОВЫМ (и PUT3, и полосный вывод кладут один и
;  тот же байт под маской 0xFF), поэтому собирать его из трёх плоскостей
;  (GET3 на каждый байт) незачем — достаточно прочитать любую плоскость,
;  которая есть в старом коде.  Берём МЛАДШИЙ бит кода: сначала E000, потом
;  C000 и только для кода 4 — A000, где лежат ещё и подвижные объекты.
;  Было 8 x GET3 + 8 x PUT3 (каждый со своим разбором знакоместа), стало
;  8 чтений и 24 записи без разбора вовсе.
; ---------------------------------------------------------------------
CELL_RECOLOR:
                push    de
                push    bc
                push    hl
                ld      hl,(ACL_MAP)
                ld      a,(hl)
                and     0x07
                jp      z,CR_MAPONLY    ; кода нет — и пикселей нет
                ld      e,a
                ld      d,0x00
                ld      hl,CR_SRC
                add     hl,de
                ld      a,(hl)
                ld      (CR_OFS),a      ; смещение плоскости-источника
#if SCHEME == SCH_EXOLON
                call    SPR_GUARD_ALL   ; в плоскости A000 лежат ещё и слоты:
                                        ; и читать, и писать её можно только
                                        ; с погашенными подвижными объектами
#endif
                pop     hl
                push    hl
                ld      a,(CR_OFS)
                add     a,h
                ld      h,a
                ; ПУСТО ЛИ ЗНАКОМЕСТО — восемь байт ОДНОЙ плоскости, без
                ; цикла: пустых знакомест на этом пути большинство (цвет
                ; кладётся ДО образа, а поле только что очищено), и цена
                ; проверки важнее цены самой перекладки.
                xor     a
                or      (hl)
                dec     l
                or      (hl)
                dec     l
                or      (hl)
                dec     l
                or      (hl)
                dec     l
                or      (hl)
                dec     l
                or      (hl)
                dec     l
                or      (hl)
                dec     l
                or      (hl)
                jp      z,CR_MAPONLY    ; пусто — в остальных плоскостях нули
                                        ; по построению, писать нечего
                ld      a,l             ; вернуть l на верх знакоместа
                add     a,0x07
                ld      l,a
                ld      de,CELLBUF
                ld      b,0x08
CR_RD:
                ld      a,(hl)
                ld      (de),a
                inc     e
                dec     l
                dec     b
                jp      nz,CR_RD
                pop     hl
                push    hl
#if SCHEME == SCH_EXOLON
                ld      a,(ACL_CODE)
                and     0x04
                call    CR_W8
#endif
                ld      a,h
                add     a,0x20
                ld      h,a
                ld      a,(ACL_CODE)
                and     0x02
                call    CR_W8
                ld      a,h
