; --- ТРИ ВИДИМЫЕ ПЛОСКОСТИ (этап C, схема «Exolon», § 0a требований).
; Байт экрана — 8 пикселей ПО ГОРИЗОНТАЛИ, соседние строки растра лежат в
; соседних адресах: адрес = PLANE + столбец*256 + (255 - y).  Знакоместо MSX
; 8x8 — это ВОСЕМЬ ПОДРЯД ИДУЩИХ байт одного столбца, ровно как на MSX, где
; знакоместо тоже 8 подряд.  Поэтому «чернила на знакоместо» ложатся на
; Вектор один в один.
;
; Код цвета пикселя = бит A*4 + бит C*2 + бит E.  Один и тот же байт образа
; кладётся во все три плоскости, замаскированный по коду знакоместа:
;   плоскость A000 (вес 4) получает байт, если в коде есть 4, иначе нули,
;   C000 (вес 2) — если есть 2, E000 (вес 1) — если есть 1.
; Нули обязательны: блит MSX ЗАМЕЩАЕТ байт, а не накладывает его, и без
; обнуления соседних плоскостей от прежнего элемента остались бы пиксели.
PLANE_A         equ     0xA0            ; вес 4 — она же плоскость подвижных
                                        ; объектов (XOR), см. § 0a
PLANE_C         equ     0xC0            ; вес 2
PLANE_E         equ     0xE0            ; вес 1
PLANE_A_END     equ     0xC0            ; hi за последним (31-м) столбцом
PLANE_SPR       equ     PLANE_A         ; подвижные объекты живут в A000

; --- ВЕРТИКАЛЬНАЯ РАЗВЁРТКА (порт 3).  Картинка MSX — 192 строки, и лежат
; они в СТРОКАХ ПАМЯТИ 255..64 (адресный младший байт l = 255 - y): адресная
; арифметика адаптера от развёртки не зависит вовсе, развёртка лишь решает,
; какая строка памяти показана сверху.  При 0xFF картинка прижата к верху,
; и все 64 пустые строки собираются внизу.  SCROLL_TOP = 0x1F ставит
; экранную строку r на строку памяти (0x1F - r) mod 256, то есть r = 32
; показывает 255 (MSX y = 0), r = 223 — 64 (MSX y = 191): по 32 пустые
; строки сверху и снизу, картинка по центру.
; То же значение держит ячейка v_scroll в src/v06/adapter.asm — её
; восстанавливает V_KBD_POLL после скана клавиатуры (выбор ряда затирает
; порт 3).  Менять эти два места ТОЛЬКО ВМЕСТЕ.
SCROLL_TOP      equ     0x1F

; --- ТЕМП РАСТВОРЕНИЯ ТИТРОВ: витков паузы между восемью проходами
; A_DISSOLVE.  Виток — 24 такта (dec hl / ld a,h / or l / jp nz).
AD_DELAY        equ     4600

; --- КАРТА ЧЕРНИЛ: код цвета (0..7) на каждое знакоместо, 32 x 24 = 768 б.
; Адрес = INKBASE + (l>>3)*32 + столбец, где l = 255-y — младший байт адреса
; в плоскости.  При y = 0..191 получается l = 64..255, то есть (l>>3) = 8..31,
; и карта занимает 6500..67FF.  Столбец = (hi плоскости) and 0x1F, и внутри
; одной строки растра (l фиксирован) старший байт адреса карты НЕ МЕНЯЕТСЯ:
; (l>>3 and 7)*32 + 31 <= 255.
INKBASE         equ     0x6400          ; карта 6500..67FF

REV_PAGE        equ     0x1E            ; страница reverse(i) внутри самой игры

; --- ЗОНА ПЕРЕМЕННЫХ В СВОБОДНОЙ ДЫРКЕ 6800..6846 (71 байт).
; Тело адаптера упирается в стек на 5F00, а этапу D нужны свои ячейки.
; Дырка между картой чернил (кончается на 67FF) и блоком данных игры
; (начинается с 6847) ничем не занята, образ .rom кладёт туда нули — значит
; инициализация не нужна, ровно как у SPRST/SPRSAV.  Зона вписана в список
; tools/verify_v06.py.  Здесь лежат ТОЛЬКО ячейки с нулевым стартовым
; значением.
;
; ПАРЫ RL_Y/RL_X и TI_L/TI_H обязаны лежать ИМЕННО в этом порядке: обе
; читаются одним `ld hl,(nn)` (младший байт — Y и строка, старший — X и
; столбец).
V_VARS          equ     0x6800
RL_N            equ     V_VARS+0x00     ; сколько элементов комнаты осталось
RL_NUM          equ     V_VARS+0x01     ; номер образа с битом 7
RL_Y            equ     V_VARS+0x02     ; Y элемента (со смещением половины)
RL_X            equ     V_VARS+0x03     ; X элемента
RL_PTR          equ     V_VARS+0x04     ; следующий элемент в списке комнаты
TI_NUM          equ     V_VARS+0x06
TI_L            equ     V_VARS+0x07     ; приёмник: строка (255-Y)
TI_H            equ     V_VARS+0x08     ;           столбец в плоскости A
TI_W            equ     V_VARS+0x09     ; ширина образа в байтах
TI_CN           equ     V_VARS+0x0A     ; столбцов осталось
TI_ROWS0        equ     V_VARS+0x0B     ; высота образа
TI_ROWS         equ     V_VARS+0x0C     ; строк осталось в столбце
TI_CSRC         equ     V_VARS+0x0D     ; источник текущего столбца (2 б)
P3_B            equ     V_VARS+0x0F     ; байт образа и сборка по плоскостям (3)
ACL_CODE        equ     V_VARS+0x12     ; новый код знакоместа
ACL_MAP         equ     V_VARS+0x13     ; его запись в карте (2 б)
CELLBUF         equ     V_VARS+0x15     ; образ знакоместа на перекладку (8 б)
TG_C0           equ     V_VARS+0x1D     ; сторож слотов: диапазон столбцов
TG_C1           equ     V_VARS+0x1E
TG_W            equ     V_VARS+0x1F
SPR_ANY         equ     V_VARS+0x20     ; 1 = есть живые слоты
SPR_MINCOL      equ     V_VARS+0x21
SPR_MAXCOL      equ     V_VARS+0x22
CR_OFS          equ     V_VARS+0x23     ; плоскость-источник перекладки
RC_T            equ     V_VARS+0x24     ; RECOLOR_SCREEN: ряд знакомест
RC_PL           equ     V_VARS+0x25
RC_PH           equ     V_VARS+0x26
ASF_N           equ     V_VARS+0x2A     ; счётчик слотов в проходе
ASF_OFF         equ     V_VARS+0x2B     ; 1 = A_SPRCLEAR: все слоты погашены
ASF_TERM        equ     V_VARS+0x2C     ; 1 = в списке встретился Y = 0xD0
ASF_PDF         equ     V_VARS+0x2D     ; 1 = 32 байта образа изменились
SATPTR          equ     V_VARS+0x2E     ; (2 б)
RECPTR          equ     V_VARS+0x30     ; запись слота в SPRST (2 б)
SAVPTR          equ     V_VARS+0x32     ; сохранённый образ слота (2 б)
; XLAT — ОБЯЗАТЕЛЬНО по адресу, кратному восьми: RECOLOR_SCREEN берёт
; XLAT[код] одним `or`, без сложения (см. RC_COL).
XLAT            equ     V_VARS+0x38     ; старый код -> новый (8 б)
BK_SI           equ     V_VARS+0x34     ; кэш записи банка ОБРАЗОВ (4 б)
BK_SC           equ     V_VARS+0x40     ; кэш записи банка ЦВЕТА (4 б)
AF_N1           equ     V_VARS+0x44     ; A_FILL: длина головы заливки
AF_TAIL         equ     V_VARS+0x45     ;         длина хвоста
; 6846 НЕ ТРОГАТЬ: это ROOM_MAPS-1, с него игра читает запись комнаты 0
; (res:1A6C `ld hl,0x6846`, ldir по 1A9A).
V_VARS_END      equ     V_VARS+0x45

; --- ВТОРАЯ ЗОНА ПЕРЕМЕННЫХ: дырка 4F22..4F35 (20 байт) между таблицей
