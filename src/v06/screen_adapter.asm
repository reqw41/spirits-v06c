;  перехвачен.  Но зовут её и ТРИ ЭФФЕКТА, читающие экран через
;  VDP_RD_STRIDE8 (docs/render-paths.md, E.2): створка двери 8374 (03BA,
;  03C6), переходы между комнатами C6A7 (0FEE, 0FF8) и C719 (107B, 1088,
;  10BD, 10CA, 140C).  Все они читают полосу, сдвигают её и пишут обратно
;  в ДВЕ половины экрана — с `ret` в голове запись пропадала, и эффекты
;  ничего не рисовали.  Здесь она возвращается, но уже нативной: та же
;  раскладка, что у A_RDSTRIDE, только наоборот.
;  Вход hl = адрес VRAM, de = источник, b = строк, c = ширина в байтах.
A_WRSTRIDE:
                ld      a,b
                or      a
                ret     z
                ld      a,c
                or      a
                ret     z
                call    CELLSPLIT
                ld      a,(AF_ROW)
                cp      0x18
                ret     nc
                call    CELLADDR
                call    CLAMP_W
AW_ROW:
                push    hl
                push    bc
AW_COL:
                ld      a,(de)
                inc     de
                call    PUT3
                inc     h
                dec     c
                jp      nz,AW_COL
                pop     bc
                pop     hl
                ld      a,(CLIP_SKIP)
                or      a
                jp      z,AW_NS
                call    SKIP_DE
AW_NS:
                dec     l
                dec     b
                jp      nz,AW_ROW
                ret
#endif

; Обрезать ширину по правому краю плоскости (столбцов всего 32).
; вход  hl = вектор-адрес, c = ширина
; выход c = обрезанная ширина, (CLIP_SKIP) = сколько байт источника пропустить
CLAMP_W:
                xor     a
                ld      (CLIP_SKIP),a
                ld      a,PLANE_A_END
                sub     h
                cp      c
                ret     nc
                ld      (CW_T),a
                ld      a,c
                ld      (CW_HL),hl
                ld      hl,CW_T
                sub     (hl)
                ld      (CLIP_SKIP),a
                ld      hl,(CW_HL)
                ld      a,(CW_T)
                ld      c,a
                ret

SKIP_DE:                                ; de += (CLIP_SKIP)
                ld      (CW_HL),hl
                ld      a,(CLIP_SKIP)
                ld      l,a
                ld      h,0x00
                add     hl,de
                ex      de,hl
                ld      hl,(CW_HL)
                ret

; A_RDNUL — заглушка трёх мёртвых save-under окна героя (см. CALL_TAB).
A_RDNUL:
                ret

; =====================================================================
;  ЭТАП D: ПРЯМОЙ ВЫВОД ТАЙЛОВ
; =====================================================================
;  До этапа D комната рисовалась через АДРЕСА VRAM MSX: игра считала
;  A = (y>>3)*256 + (x and F8) + (y and 7), а адаптер на КАЖДЫЙ байт
;  раскладывал этот адрес обратно в (столбец, строка), искал знакоместо в
;  карте чернил и ставил три маски.  Замер: половина комнаты 3.03 млн тактов
;  = 50.6 кадра.
;
;  Теперь цикл элементов комнаты (D19F, 1A9F), вывод образа (D202, 1B02) и
;  зеркальная ветка (D141, 1A41) заменены целиком.  Адрес в плоскости
;  считается ОДИН РАЗ на элемент (h = столбец, l = 255-y), разбор знакоместа
;  и масок — ОДИН РАЗ на полосу из восьми строк одного столбца, а не на байт.
;
;  ПОРЯДОК ПЕРЕВЁРНУТ: СНАЧАЛА ЦВЕТ, ПОТОМ ОБРАЗ.  Игра делает наоборот
;  (D1B0 образ, D1B5 цвет), и на MSX это одно и то же: цветовой байт красит
;  ВСЁ знакоместо, и уже лежащие в нём пиксели тоже.  У нас «перекрасить» —
;  это ПЕРЕЛОЖИТЬ пиксели между плоскостями (CELL_RECOLOR), и цена зависит от
;  того, что в знакоместе лежит:
;    * образ-потом-цвет: в знакоместе уже лежит образ ЭТОГО элемента, и
;      перекладка идёт на КАЖДОМ из ~108 знакомест комнаты — очистка половины
;      экрана (2:CC9A) красит поле белым (0xF1 -> код 4), так что код меняется
;      всегда;
;    * цвет-потом-образ: в знакоместе лежит только то, что оставили ПРЕДЫДУЩИЕ
;      элементы, а поле только что очищено.  Перекладка срабатывает лишь на
;      перекрытиях с ДРУГИМИ чернилами — замер по всем 87 комнатам
;      (build/analysis): 26 знакомест НА ВСЮ ИГРУ, в среднем 0.3 на комнату,
;      максимум 4.
;  Результат на экране тот же байт в байт: перекладка — это чистая
;  перекодировка хранимых пикселей, и порядок «записать под старым кодом и
;  переложить» равен порядку «переложить и записать под новым».
; ---------------------------------------------------------------------
;  A_ROOMLOOP — перехват 1A9F (D19F), цикл элементов комнаты.
;  Вход: hl = первый элемент (4 байта), b = сколько их.
;  Смещение Y половины экрана лежит в операнде 1AA5 (его ставит 1A8B) —
;  читаем оттуда, чтобы не дублировать самомодификацию игры.
; ---------------------------------------------------------------------
A_ROOMLOOP:
                ld      a,b
                or      a
                ret     z
                ld      (RL_N),a
RL_L:
                ld      a,(hl)          ; +0 номер образа (бит 7 = прямой)
                ld      (RL_NUM),a
                inc     hl
                ld      a,(hl)          ; +1 Y
                ld      c,a
                ld      a,(G_1AA5)      ; смещение Y: 0 верх, 0x60 низ
                add     a,c
                ld      (RL_Y),a
                inc     hl
                ld      a,(hl)          ; +2 X
                ld      (RL_X),a
                inc     hl
                ld      a,(hl)          ; +3 код цвета
                inc     hl
                ld      (RL_PTR),hl
                ld      hl,(RL_Y)       ; l = Y, h = X
                ld      b,h
                ld      c,l
                call    G_1ABD          ; D1BD: карта чернил + буфер атрибутов
                ld      hl,(RL_Y)
                ld      b,h
                ld      c,l
                ld      a,(RL_NUM)
                call    A_TILEIMG
                ld      hl,(RL_PTR)
                ld      a,(RL_N)
                dec     a
                ld      (RL_N),a
                jp      nz,RL_L
                ret

; ---------------------------------------------------------------------
;  КЭШ ПОИСКА ЗАПИСИ БАНКА (BK_IMG вместо 1B52, BK_COL вместо 1B4C)
;  Банк — записи [высота][ширина][байты] подряд, и запись #b игра ищет
;  ЛИНЕЙНЫМ проходом от начала.  Замер: 3.0 тыс. тактов на вызов, по вызову
;  на элемент комнаты в КАЖДОМ из двух банков — 151 тыс. тактов на комнату,
;  пятая часть всей отрисовки.  Подряд идущие элементы просят ТУ ЖЕ запись
;  в 44 % случаев (образ) и в 50 % (цвет) — замер по всем 87 комнатам, —
;  поэтому довольно кэша на одну запись на банк.
;  Ключ — индекс И СТАРШИЙ БАЙТ БАЗЫ: базу банка образов перебивают
;  2:CD94/CDB2, переключая его на банк подвижных объектов 294B и обратно.
;  Вход b = индекс, выход hl = адрес записи; портит a, de (как и оригинал).
;
;  ЭТАП E: КЭШ БАНКА ОБРАЗОВ (BK_IMG) УМЕР — у обоих банков образов теперь
;  есть ТАБЛИЦА АДРЕСОВ ЗАПИСЕЙ (src/v06/bank_ptr.inc, её считает
;  tools/repack_banks.py), и запись находится ОДНИМ чтением пары байт вместо
;  линейного прохода с кэшем.  Кэш банка ЦВЕТА (BK_COL) остался: банк цвета
;  8B9C не перепакован (там байт на знакоместо, а не битмап) и ищется
;  по-прежнему линейно.
; ---------------------------------------------------------------------
BK_COL:
                ld      hl,SPR_BANK_A89C
                ld      (BK_CALL+1),hl
                ld      hl,BK_SC
BK_GO:
                ld      a,b
                cp      (hl)
                jp      nz,BK_MISS
                inc     hl
                ld      a,(SPR_BANK_VAR+2)
                cp      (hl)
                jp      nz,BK_MISS2
                inc     hl
                ld      a,(hl)
                inc     hl
                ld      h,(hl)
                ld      l,a
                ret
BK_MISS:
                ld      (hl),a
                inc     hl
BK_MISS2:
                ld      a,(SPR_BANK_VAR+2)
                ld      (hl),a
                inc     hl
                push    hl
BK_CALL:        call    0x0000
                pop     de
                ex      de,hl
                ld      (hl),e
                inc     hl
                ld      (hl),d
                ex      de,hl
                ret

; ---------------------------------------------------------------------
;  A_CELLCOL — ЦВЕТ ОДНОГО ЗНАКОМЕСТА, врезка в 1AE9 (операнд `call
;  VDP_FILL` внутри цикла D1BD).
;  Оригинал звал VDP_FILL(bc=8) — «залить восемь строк знакоместа одним
;  цветовым байтом».  У нас цвет знакоместа — ОДИН байт карты чернил, и вся
;  машинерия A_FILL (разбор адреса записи, деление длины на знакоместа,
;  цикл по ним) ради него не нужна.  Замер: 1.5 тыс. тактов на знакоместо
;  против 0.25 тыс.
;  Вход a = цветовой байт MSX (чернила в старшем полубайте), hl = адрес в
;  таблице цвета MSX.  Сохраняет a? НЕТ — но и VDP_FILL его сохранял только
;  «на бумаге»: вызывающий (1AEB) пользуется дальше лишь hl, de и bc.
; ---------------------------------------------------------------------
A_CELLCOL:
                push    de
                push    bc
                push    hl
                ld      c,a             ; цветовой байт
                ld      a,h
                and     0x1F            ; ряд знакомест
                cp      0x18
                jp      nc,ACC_OUT      ; ниже 191-й строки карты чернил нет
                add     a,a
                add     a,a
                add     a,a
                cpl
                ld      b,a             ; l = 255 - ряд*8 (верх знакоместа)
                ld      a,l
                and     0xF8
                rrca
                rrca
                rrca
                add     a,PLANE_A
                ld      h,a
                ld      l,b
                ld      a,c
                rrca
                rrca
                rrca
                rrca
                and     0x0F            ; чернила MSX
                ld      e,a
                ld      d,0x00
                push    hl
                ld      hl,INK2CODE
                add     hl,de
                ld      a,(hl)          ; код знакоместа
                pop     hl
                ld      (ACL_CODE),a
                call    INK_ADDR        ; de = запись в карте чернил
                ld      a,(de)
                ld      c,a
                ex      de,hl
                ld      (ACL_MAP),hl
                ex      de,hl
                ld      a,(ACL_CODE)
                cp      c
                call    nz,CELL_RECOLOR ; код тот же — карту трогать незачем
ACC_OUT:
                pop     hl
                pop     bc
                pop     de
                ret

; ---------------------------------------------------------------------
;  A_TILEIMG — перехват 1B02 (D202): образ элемента ПРЯМО ИЗ БАНКА.
;  ЭТАП E: банк перепакован ПО СТОЛБЦАМ, полоса выводится через SP (push).
;  Вход a = номер записи банка, бит 7 = 1 прямой вывод / 0 зеркальный;
;       b = X, c = Y (верх образа).  Портит всё.
;
;  ПОЧЕМУ PUSH ЗДЕСЬ ОКУПАЕТСЯ, А У ПОДВИЖНЫХ ОБЪЕКТОВ НЕТ.  Элемент комнаты
;  кладётся ПО ГРАНИЦЕ ЗНАКОМЕСТА: A_TILEIMG берёт `x and 0xF8`, младшие три
;  бита X не участвуют вовсе.  Значит байт образа ложится в байт экрана БЕЗ
;  СДВИГА, приёмник только ПИШЕТСЯ, и пара соседних строк одного столбца —
;  это ровно один `push`.  У спрайтов x произволен, байт растекается в два
;  столбца, и приёмник приходится ЧИТАТЬ (подробности — над BLIT_SPR).
;
;  Адрес записи банка берётся из ТАБЛИЦЫ (src/v06/bank_ptr.inc, её считает
;  tools/repack_banks.py): линейный проход SPR_BANK_VAR (3.0 тыс. тактов на
;  вызов) и кэш BK_IMG умерли.  Какой из двух банков образов сейчас выбран,
;  видно по операнду самой игры (1B53/1B54): 2:CD94/CDB2 перебивают его на
;  банк подвижных объектов 294B ради значков панели OBJETOS и обратно на
;  банк декораций 8E76.
; ---------------------------------------------------------------------
A_TILEIMG:
                ld      (TI_NUM),a
                ld      a,c
                cpl
                ld      (TI_L),a        ; l = 255 - Y
                ld      a,b
                and     0xF8
                rrca
                rrca
                rrca
                add     a,PLANE_A
                ld      (TI_H),a        ; h = плоскость A + столбец
                ; --- запись банка ОДНИМ чтением таблицы
                ld      a,(TI_NUM)
                and     0x7F
                add     a,a             ; *2: запись таблицы — слово
                ld      l,a
                ld      h,0x00
                ld      a,(G_1B54)      ; старший байт базы банка у игры
                cp      0x8E
                ld      de,BKP_DEC
                jp      z,TI_BK
                ld      de,BKP_SPR
TI_BK:
                add     hl,de
                ld      a,(hl)
                inc     hl
                ld      h,(hl)
                ld      l,a             ; hl = заголовок записи
                ld      a,(hl)
                ld      (TI_ROWS0),a    ; высота = длина столбца
                inc     hl
                ld      a,(hl)
                ld      (TI_W),a        ; ширина в байтах = столбцов
                inc     hl
                ld      (TI_CSRC),hl    ; данные ПО СТОЛБЦАМ
                ld      a,(TI_NUM)
                and     0x80
                jp      nz,TI_DIR
                ; --- ЗЕРКАЛО: столбцы приёмника справа налево, байты через
                ; таблицу reverse 1E00.  Второй, заранее развёрнутой копии
                ; банка нет — решение по замеру, см. tools/repack_banks.py.
                ld      a,0x01
                ld      (TI_MIRF),a
                ld      hl,TP_MIR
                ld      (TPO_J+1),hl    ; виток выбирается раз на элемент
                ld      a,0xFF
                ld      (TI_CST+1),a    ; шаг столбца приёмника -1
                ld      a,(TI_W)
                dec     a
                ld      hl,TI_H
                add     a,(hl)
                ld      (TI_H),a        ; начинаем с ПРАВОГО столбца
                jp      TI_GO
TI_DIR:
                xor     a
                ld      (TI_MIRF),a
                ld      hl,TP_DL
                ld      (TPO_J+1),hl
                ld      a,0x01
                ld      (TI_CST+1),a
TI_GO:
                ld      a,(TI_W)
                ld      (TI_CN),a
                or      a
                ret     z
TI_COL:
                ld      hl,(TI_CSRC)    ; источник столбца — h байт ПОДРЯД
                ld      (TP_SRC),hl
                ld      a,(TI_ROWS0)
                ld      (TI_ROWS),a
                ld      a,(TI_L)
                ld      (TP_L),a
                ld      a,(TI_H)
                and     0x1F
#if SCHEME == SCH_EXOLON
                add     a,PLANE_A
#else
                add     a,PLANE_C
#endif
                ld      (TC_HI),a       ; старший байт приёмника — на столбец
TI_STRIP:
                ld      a,(TP_L)
                cp      0x40            ; l < 0x40 — строки ниже 191-й:
                jp      c,TI_CDONE      ; на MSX они уходили в таблицу имён
                ld      l,a
                ld      a,(TI_H)
                ld      h,a
                call    INK_SET         ; маски знакоместа -> TI_MA/TI_MC/TI_ME
                ; --- ДЛИНА ПОЛОСЫ.  Полоса — это строки одного столбца с
                ; ОДИНАКОВЫМИ масками, а не «до низа знакоместа»: соседние
                ; знакоместа столбца чаще всего одного кода, и тогда полосы
                ; сливаются в один прогон push.  Разбор знакоместа и вся
                ; обвязка (di, подмена SP, нечётная строка) платятся раз на
                ; ПРОГОН, а не раз на восемь строк.
                ld      a,(TP_L)
                and     0x07
                inc     a
                ld      c,a             ; до низа этого знакоместа
                ld      a,(TI_ROWS)
                cp      c
                jp      nc,TI_EXL
                ld      c,a             ; образ кончается раньше
                jp      TI_NLEN
TI_EXL:
                ld      a,(TI_ROWS)
                sub     c
                jp      z,TI_NLEN       ; строк больше нет
                ld      b,a             ; сколько останется после полосы
                ld      a,(TP_L)
                sub     c               ; верх следующего знакоместа
                cp      0x40
                jp      c,TI_NLEN
                ld      l,a
                ld      a,(TI_H)
                ld      h,a
                call    INK_CODE
                ld      hl,IS_CODE
                cp      (hl)
                jp      nz,TI_NLEN      ; другой код — полоса кончилась
                ld      a,b
                cp      0x08
                jp      c,TI_EX1
                ld      a,0x08
TI_EX1:
                add     a,c
                ld      c,a
                jp      TI_EXL
TI_NLEN:
                ld      a,(TI_ROWS)
                sub     c
                ld      (TI_ROWS),a
                ld      a,c
                ld      (TP_N),a
                and     0x01
                ld      (TP_ODD),a      ; нечётную строку кладём обычной записью
                ld      a,c
                rrca
                and     0x7F
                ld      (TP_PAIRS),a    ; остальные — парами через push
                ; Конец источника полосы — для ЗЕРКАЛЬНОГО витка: там все
                ; четыре пары регистров заняты (таблица reverse, источник,
                ; пара на push, SP), счётчика не осталось, и виток кончается
                ; по младшему байту источника.
                ld      a,(TP_SRC)
                add     a,c
                ld      (TM_END+1),a
                ; --- байт нечётной строки: один раз на полосу, а не на
                ; плоскость (в плоскость с нулевой маской пойдёт ноль)
                call    TP_ODDROW
                ; --- приёмник: тот же столбец в каждой плоскости, верх полосы
                ld      a,(TP_L)
                ld      e,a
                ld      a,(TC_HI)
                ld      d,a
#if SCHEME == SCH_EXOLON
                ld      a,(TI_MA)
                call    TP_ONE
                ld      a,(TP_L)
                ld      e,a
                ld      a,(TC_HI)
                add     a,0x20
                ld      d,a
#endif
                ld      a,(TI_MC)
                call    TP_ONE
                ld      a,(TP_L)
                ld      e,a
                ld      a,(TC_HI)
#if SCHEME == SCH_EXOLON
                add     a,0x40
#else
                add     a,0x20
#endif
                ld      d,a
                ld      a,(TI_ME)
                call    TP_ONE
                ; --- следующая полоса того же столбца
                ld      a,(TP_N)
                ld      c,a
                ld      b,0x00
                ld      a,(TP_L)
                sub     c
                ld      (TP_L),a
                ld      hl,(TP_SRC)
                add     hl,bc
                ld      (TP_SRC),hl
                ld      a,(TI_ROWS)
                or      a
                jp      nz,TI_STRIP
TI_CDONE:
                ld      hl,(TI_CSRC)    ; следующий столбец источника: +высота
                ld      a,(TI_ROWS0)
                ld      c,a
                ld      b,0x00
                add     hl,bc
                ld      (TI_CSRC),hl
                ld      a,(TI_H)
TI_CST:         add     a,0x01
                ld      (TI_H),a
                ld      a,(TI_CN)
                dec     a
                ld      (TI_CN),a
                jp      nz,TI_COL
                ret

; ---------------------------------------------------------------------
;  TP_PLANE — ПОЛОСА (строки одного столбца внутри ОДНОГО знакоместа) в ОДНУ
;  плоскость через подмену SP.
;  Вход a = маска плоскости (0x00 — знакоместо этой плоскости не занимает,
;  кладём НУЛИ; 0xFF — кладём байты образа), (TP_SRC) источник полосы,
;  (TP_DST) адрес ВЕРХНЕЙ строки полосы в плоскости, (TP_ODD)/(TP_PAIRS).
;
;  НУЛИ ОБЯЗАТЕЛЬНЫ, а не «пропустить»: блит MSX ЗАМЕЩАЕТ байт образа, и от
;  прежнего элемента в этом знакоместе иначе остались бы пиксели.
;
;  ПОЧЕМУ ПОРЯДОК СТРОК В БАНКЕ ЕСТЕСТВЕННЫЙ.  `push de` кладёт d по SP-1
;  (старший адрес), e по SP-2, и SP УМЕНЬШАЕТСЯ; на Векторе меньший адрес —
;  строка НИЖЕ.  Значит d = верхняя строка пары, e = нижняя, а читаются они
;  как `ld d,(hl) / inc hl / ld e,(hl) / inc hl` из подряд идущих байт
;  столбца СВЕРХУ ВНИЗ.  Разворачивать данные при перепаковке не пришлось.
;
;  НЕЧЁТНАЯ СТРОКА.  Полоса — от 1 до 8 строк, и при нечётной длине одна
;  строка парой не накрывается.  Она кладётся ОБЫЧНОЙ записью и ПЕРВОЙ
;  (верхней): тогда пары начинаются строкой ниже и ни одна запись не выходит
;  за образ.  Класть её последней было бы на команду дешевле, но тогда
;  последняя пара накрывала бы строку ПОД образом — чужое знакоместо.
;
;  di — ТОЛЬКО на время подмены SP, и SP восстанавливается тут же.  Самый
;  длинный кусок — полоса из восьми строк: четыре пары по 50 тактов плюс
;  обвязка, около 280 тактов (замер по листингу, tools/cycles_i8080.py).
;  Прерывание на Векторе не защёлкивается (reference_vector06c_interrupt_
;  not_latched), поэтому длинный di — это потерянный кадр музыки и опроса
;  клавиатуры.
; ---------------------------------------------------------------------
TP_ONE:
                ld      (TP_MSK),a
                ld      hl,0x0000
                add     hl,sp
                ld      (TP_SAV),hl     ; настоящий SP на время подмены
                ld      a,(TP_MSK)
                or      a
                jp      nz,TPO_B
                xor     a               ; маска 0 — в плоскость идут НУЛИ
                jp      TPO_OD
TPO_B:
                ld      a,(TP_ODDB)
TPO_OD:
                ld      h,d
                ld      l,e
                ld      b,a
                ld      a,(TP_ODD)
                or      a
                jp      z,TPO_P
                ld      (hl),b          ; нечётная строка — обычной записью
                dec     hl              ; пары начинаются строкой ниже
TPO_P:
                inc     hl              ; SP = адрес верхней строки пар + 1
                ld      a,(TP_PAIRS)
                or      a
                ret     z
                ld      b,a
                ld      a,(TP_MSK)
                or      a
                jp      z,TP_ZERO
                di
                ld      sp,hl
TPO_J:          jp      TP_DL           ; прямо или зеркально — ставится раз
                                        ; на элемент, в A_TILEIMG
                ; --- ПРЯМО: два чтения подряд и один push на пару строк
TP_DL:
                ld      hl,(TP_PSRC)
TP_DL2:
                ld      d,(hl)
                inc     hl
                ld      e,(hl)
                inc     hl
                push    de
                dec     b
                jp      nz,TP_DL2
                jp      TP_FIN
                ; --- ЗЕРКАЛО: каждый байт через таблицу reverse 1E00
TP_MIR:
                ld      hl,(TP_PSRC)    ; `ld de,(nn)` — не i8080 (префикс ED)
                ex      de,hl
                ld      h,REV_PAGE
TP_ML:
                ld      a,(de)
                inc     de
                ld      l,a
                ld      b,(hl)
                ld      a,(de)
                inc     de
                ld      l,a
                ld      c,(hl)
                push    bc
                ld      a,e
TM_END:         cp      0x00
                jp      nz,TP_ML
                jp      TP_FIN
                ; --- НУЛИ: источник не нужен вовсе
TP_ZERO:
                di
                ld      sp,hl
                ld      de,0x0000
TP_ZL:
                push    de
                dec     b
                jp      nz,TP_ZL
TP_FIN:
                ld      hl,(TP_SAV)
                ld      sp,hl
                ei
                ret

; TP_ODDB — байт нечётной строки полосы (раз на полосу; в плоскость с
; нулевой маской вместо него уйдёт ноль).  Источник пар начинается сразу
; за ней.
TP_ODDROW:
                ld      hl,(TP_SRC)
                ld      a,(TP_ODD)
                or      a
                jp      z,TP_OW
                ld      b,(hl)
                inc     hl
                ld      a,(TI_MIRF)
                or      a
                jp      z,TP_OW2
                push    hl
                ld      l,b
                ld      h,REV_PAGE
                ld      b,(hl)
                pop     hl
TP_OW2:
                ld      a,b
                ld      (TP_ODDB),a
TP_OW:
                ld      (TP_PSRC),hl    ; источник ПАР
                ret

; =====================================================================
;  A_GLYPH8 — перехват 1746 (2:CE46): глиф 8x8 ОДНИМ знакоместом
; =====================================================================
;  Печатник символов клал байт за байтом через VDP_RD_BYTE + VDP_WR_BYTE:
;  восемь разборов адреса, восемь сторожей слотов, восемь разборов
;  знакоместа — при том, что все восемь байт лежат в ОДНОМ знакоместе, то
;  есть в восьми подряд идущих адресах одного столбца Вектора.  Замер до
;  правки: WRBYTE 131 962 такта на итерацию игры при 128 вызовах — больше
;  трети всей итерации.
;
;  Вход hl = адрес VRAM знакоместа (h = строка 0..23, l = столбец*8),
;       de = 8 байт образа глифа.  Байт по 174D (2:CE4D) — режим: 0 обычная
;  запись, 0xA9 (`xor c`) — XOR-печать, её включают только титры (2:CF5E).
A_GLYPH8:
                ld      a,(G_174D)
                or      a
                push    hl
                ld      hl,AG_PUT
                jp      z,AG_SM
                ld      hl,AG_RD
AG_SM:
                ld      (AGJ+1),hl
                pop     hl
                call    CELLSPLIT
                ld      a,(AF_ROW)
                cp      0x18
                ret     nc              ; вне таблицы образов
                call    CELLADDR
#if SCHEME == SCH_EXOLON
                call    GUARD_W1
#endif
                call    INK_SET
                ld      b,0x08
AG_L:
                ld      a,(de)
                inc     de
AGJ:            jp      AG_PUT
AG_RD:
                ld      c,a
                call    GET1            ; XOR-режим: прочитать, что там лежит
                xor     c
AG_PUT:
                call    PUTM
                dec     l
                dec     b
                jp      nz,AG_L
                ret

; =====================================================================
;  ЭТАП E: ПОДВИЖНЫЕ ОБЪЕКТЫ — ПРЯМО ИЗ ПЕРЕПАКОВАННОГО БАНКА
; =====================================================================
;  ЧТО УМЕРЛО.  До этапа E путь был такой: игра звала D0A0 на каждый объект
;  кадра, тот раскладывал образ на спрайты MSX 16x16 и копировал их в
;  ТЕНЕВУЮ ТАБЛИЦУ ОБРАЗОВ (F800, 2048 б), заполнял ТЕНЕВУЮ SAT (F77E), а
;  адаптер в D664 шёл по SAT и блитил образы из теневой таблицы.  Перед
;  каждым кадром обе таблицы чистились двумя `ldir` (2176 байт).
;
;  Теперь перехвачен САМ D0A0 (19A0): в этой точке доступно ВСЁ — номер
;  записи банка с битом зеркала в `a`, X в `b`, Y низа в `c`
;  (docs/render-paths.md, F.7), — и объект просто записывается в СВОЙ список
;  SPRL.  Умерли: раскладка образов D447, зеркальный буфер D2CC, заполнение
;  теневой SAT D340, пересчёт размеров D381, обе чистки (`ld hl,407E` и
;  `ld hl,40FE` в D0F2 — патч в BYTE_TAB перепрыгивает их одним `jp`), а
;  вместе с ними теневые таблицы 407E..49FF (2434 б) и копии образов SPRSAV
;  (1024 б) с HR_SAV (96 б).
;
;  СТИРАНИЕ — PUSH НУЛЕЙ, а не повторный xor.  В схеме «2 + 1» плоскость
;  A000 принадлежит подвижным объектам ЦЕЛИКОМ, тайлы в неё не пишут
;  (docs/adapter-requirements.md § 0c), поэтому «стереть» — это положить
;  нули, а не восстанавливать фон.  Нули кладутся через SP: коробка 3x16 —
;  24 push вместо 32 витков блиттера, 630 тактов вместо 3800.
;  В схеме «Exolon» плоскость A000 ОБЩАЯ с тайлами, нулями там стирать
;  нельзя — стирание остаётся повторным xor того же образа (#if ниже).
;
;  КАЖДЫЙ КАДР СТИРАЕТСЯ И РИСУЕТСЯ ВСЁ.  Сравнения «изменился ли слот»
;  (CMP_N по 32 байтам) больше нет: она стоила дороже, чем стереть и
;  нарисовать заново, а заодно требовала хранить нарисованные байты.
;  Сначала идут ВСЕ стирания, потом ВСЕ рисования — окно, в котором луч
;  может увидеть объект стёртым, получается коротким и одним на кадр.
;
;  ПЕРЕКРЫТИЯ.  Блиттер кладёт байт через `or`: два объекта в перекрытии
;  СЛИВАЮТСЯ, а не выедают друг друга дырками (так было при xor).  Цена та
;  же — `or (hl)` ровно столько же тактов, сколько `xor (hl)`.
;
;  ПОЧЕМУ РИСОВАНИЕ НЕ ЧЕРЕЗ PUSH.  X объекта произволен, поэтому байт
;  образа сдвигается на x and 7 и РАСТЕКАЕТСЯ в два соседних столбца:
;  правый столбец получает хвост предыдущего байта, то есть приёмник
;  приходится ЧИТАТЬ.  `push` приёмник только пишет.  Посчитано по составу
;  команд (tools/cycles_i8080.py): виток «прочитать байт, повернуть, две
;  маски, два `or (hl)`» — 111 тактов на байт образа; любой вариант с push
;  требует либо второго прохода поворота (28 тактов на байт лишних), либо
;  буфера сдвинутых столбцов (36 тактов на байт на запись плюс 25 на
;  чтение) — оба дороже.  Поэтому push у подвижных объектов достаётся
;  СТИРАНИЮ (там пишется константа) и не достаётся рисованию.
; ---------------------------------------------------------------------
;  СПИСОК ОБЪЕКТОВ КАДРА.  Запись 8 байт:
;    +0 lo   младший байт адреса левого столбца (255 - y верхней строки)
;    +1 hi   старший (плоскость + столбец); 0 — запись пуста
;    +2 s    сдвиг x and 7
;    +3 w    столбцов ИСТОЧНИКА (коробка на один шире)
;    +4 h    строк
;    +5,+6   данные записи банка (ПО СТОЛБЦАМ)
;    +7 mir  1 = выводить зеркально
;  SPRL — что рисуем в этом кадре, SPRO — что нарисовано сейчас на экране.
; ---------------------------------------------------------------------
A_SPRCLEAR:
                xor     a
                ld      (HR_LIVE),a     ; герой тоже гаснет и сам не воскреснет
                ld      (SPRL_N),a      ; список кадра пуст
#if SCHEME == SCH_CPC21
                ld      (CHL_N),a       ; и список люстр тоже
                inc     a
                ld      (PD_DIRTY),a    ; экран гасят — подставку рисовать заново
#endif
                jp      SPR_ERASEALL    ; стереть всё, что стоит на экране

; ---------------------------------------------------------------------
;  A_SPROBJ — перехват 19A0 (D0A0) «положить объект».
;  Вход a = номер записи банка (бит 7 = зеркало), b = X, c = Y НИЗА.
;  Выход: как у оригинала — b = X, c = Y ВЕРХА (это единственное, что
;  вызывающие могли бы прочитать; поля записи объекта по ix не читает
;  никто, кроме цепочки +6/+7, а она жила только ради D447).
; ---------------------------------------------------------------------
A_SPROBJ:
                ld      (SO_NUM),a
                ld      a,b
                ld      (SO_X),a
                ld      a,c
                ld      (SO_Y),a
                ld      a,(SO_NUM)
                and     0x7F
                add     a,a
                ld      l,a
                ld      h,0x00
                ld      de,BKP_SPR
                add     hl,de
                ld      a,(hl)
                inc     hl
                ld      h,(hl)
                ld      l,a             ; hl = заголовок записи банка
                ld      a,(hl)
                ld      (SO_H),a
                inc     hl
                ld      a,(hl)
                ld      (SO_W),a
                inc     hl
                ld      (SO_SRC),hl
                ; --- геометрия
                ld      a,(SPRL_N)
                cp      SPRL_MAX
                jp      nc,SO_RET       ; список полон (замер: бывает до 14)
                ld      a,(SO_Y)
                ld      hl,SO_H
                sub     (hl)            ; y верха — ровно то, что клал D340
                cp      0xC1
                jp      nc,SO_RET       ; погашен или за экраном
                inc     a               ; экранная строка = y + 1 (F.8 п.1)
                cpl
                ld      (SO_LO),a
                ld      a,(SO_X)
                and     0x07
                ld      (SO_S),a
                ld      a,(SO_X)
                and     0xF8
                rrca
                rrca
                rrca
                ld      c,a
                ld      hl,SO_W
                add     a,(hl)
                cp      0x20            ; столбец + ширина + перенос <= 32
                jp      nc,SO_RET
                ld      a,c
                add     a,PLANE_SPR
                ld      (SO_HI),a
#if SCHEME == SCH_CPC21
                ld      a,(SO_NUM)
                and     0x7F
                cp      PED_NUM
                jp      z,PED_TILE      ; подставка — в тайловые плоскости
                cp      CHA_NUM
                jp      z,CHA_TILE      ; люстра — туда же, но она ПАДАЕТ
#endif
                call    SPR_APPEND
SO_RET:
                ld      a,(SO_X)
                ld      b,a
                ld      a,(SO_Y)
                ld      hl,SO_H
                sub     (hl)
                ld      c,a
                ret

#if SCHEME == SCH_CPC21
; ---------------------------------------------------------------------
;  PED_TILE — ПОДСТАВКА КАК ТАЙЛ (решение владельца 2026-09-22).
;
;  ПОЧЕМУ ЭТО ВООБЩЕ ВОЗМОЖНО.  Подставку рисует ровно один хвост игры
;  (2:CD70 `ld a,0x16` / CD72), и он зовётся КАЖДЫЙ кадр, подобран предмет
;  или нет (`CD5C` уходит на `CD70` именно тогда, когда предмет уже взят).
;  Координаты её в уровне ПОСТОЯННЫ: пара (комната, X) приходит из
;  PARAM_TABLE_CEAA один раз на уровень (2:CE6A), Y = 0x50 (+0x60 у нижнего
;  окна) зашит в CD73.  Значит подставка не двигается и не исчезает, пока
;  не сменилась комната или уровень, — а это всегда перерисовка половины
;  экрана.  Поэтому ни стирания, ни сохранения фона не нужно вовсе:
;  достаточно рисовать её ЗАНОВО после каждой перерисовки (флаг PD_DIRTY).
;
;  В КАКУЮ ПЛОСКОСТЬ.  Цвет подставки на MSX — атрибут спрайта
;  `F317+0x16` = `0x0C`, чернила 12 (тёмно-зелёный); таблица слияния CPC
;  (INK2CODE) сводит чернила 12 в КОД 2, а код 2 — это РОВНО ОДНА плоскость,
;  `C000` (MSKTAB: 0,FF,0).  Значит «рисовать по коду знакоместа» здесь
;  вырождается в «рисовать в C000», и маски не нужны: цвет пикселя задаёт
;  плоскость, а не запись карты чернил.
;
;  КАРТУ ЧЕРНИЛ НЕ ТРОГАЕМ.  Карта — это цвет ФОНА комнаты, и смена кода
;  знакоместа перекладывает уже лежащие там пиксели (CELL_RECOLOR).  Замер
;  по всем 18 возможным размещениям предмета: 23 строки подставки из 24
;  лежат в знакоместах, ГДЕ ФОНА НЕТ ВООБЩЕ (код 1, 0 пикселей), и только
;  последняя, 24-я, попадает в знакоместо пола. Перекрашивать там нечего, а
;  если бы мы всё же сменили код, то (а) испортили бы цвет пола под
;  подставкой и (б) увели бы карту чернил от живого MSX, где в этих
;  знакоместах стоит 0xF1 — то есть сломали бы гейт cmp_color_msx 0/768.
;  Запись в плоскость C000 идёт через `or`, фон под подставкой остаётся.
;
;  Вход — разобранный объект в SO_* (как у SPR_APPEND).  Выход — SO_RET.
; ---------------------------------------------------------------------
PED_TILE:
                ld      a,(PD_DIRTY)
                or      a
                jp      z,SO_RET        ; уже лежит в плоскости тайлов
                ld      a,(SO_LO)
                ld      (BL_LO),a
                ld      a,(SO_HI)
                add     a,PLANE_C-PLANE_A
                ld      (BL_HI),a       ; тот же столбец, но плоскость C000
                ld      a,(SO_S)
                ld      (BL_S),a
                ld      a,(SO_W)
                ld      (BL_W),a
                ld      a,(SO_H)
                ld      (BL_H),a
                ld      hl,(SO_SRC)
                ld      (BL_SRC),hl
                ld      a,(SO_NUM)
                and     0x80
                ld      (BL_MIR),a
                call    BLIT_OBJ
                jp      SO_RET

; ---------------------------------------------------------------------
;  ЛЮСТРА — ПАДАЮЩИЙ ОБЪЕКТ 0x1E КАК ТАЙЛ (решение владельца 2026-09-22).
;
;  ЧТО ЭТО.  2:BBD5 обходит шесть записей таблицы BCC3 (комната, X, Y низа,
;  таймер, Y исходный).  Пока комната записи показана В ВЕРХНЕМ окне, таймер
;  убывает каждый кадр; дойдя до нуля, BC25 роняет люстру на 4 px в кадр,
;  пока три пробы теневого буфера атрибутов F34D (X+6/X+12/X+18 на строке Y,
;  класс >= 0x40) не упрутся в пол.  После посадки люстра ЛЕЖИТ НА ПОЛУ и
;  рисуется каждый кадр там же; таймер перезаряжается `ld a,r` только когда
;  комната ушла с экрана (BC0A), и тогда же Y возвращается к исходному.
;  Касание героя на лету — смерть (BC40 -> C625).
;
;  ПОЧЕМУ ТАЙЛ ЗАКОННА.  Цвет спрайта на MSX — F317+0x1E = 0x0F, чернила 15
;  (БЕЛЫЙ); INK2CODE сводит белый в КОД 1, а код 1 — ровно одна плоскость,
;  E000 (MSKTAB: 00,00,FF), и код 1 БЕЛЫЙ во всех 87 комнатах.  Значит ни
;  масок, ни карты чернил: пишем `or`-ом в E000, и цвет совпадает с MSX.
;
;  СТИРАНИЕ НУЛЯМИ В ПЛОСКОСТИ ТАЙЛОВ — ПО ЗАМЕРУ, А НЕ ПО ВЕРЕ.
;  tools/chandelier_check.py перебирает все шесть размещений и все 87
;  возможных комнат во втором окне: коробка стирания (W+1 столбцов на H
;  строк, ровно то, что чистит WP_SETUP) НЕ СОДЕРЖИТ НИ ОДНОГО ПИКСЕЛЯ ФОНА
;  во ВСЕХ положениях падения, кроме ПОСЛЕДНЕГО — того, где люстра уже
;  села.  Там в коробку попадает одна-единственная строка растра (нижняя,
;  она же первая строка знакоместа пола), 12..40 пикселей.  Но последнее
;  положение НЕ СТИРАЕТСЯ НИКОГДА: люстра в нём больше не двигается, запись
;  совпадает со старой, и проход её не трогает; а уходит она с экрана только
;  вместе с перерисовкой половины экрана (PD_DIRTY), когда стирать уже
;  нечего.  Рисование в этой строке тоже безвредно: 24-я строка образа 0x1E
;  ПУСТАЯ (замер: tools/chandelier_check.py печатает образ), то есть `or`
;  туда не кладёт ни бита.
;
;  СПИСОК НА ДВЕ ЗАПИСИ.  Подставке хватало флага, люстре — нет: она
;  движется, и старую коробку надо стирать.  CHL — что нарисовать в этом
;  кадре, CHO — что уже стоит на экране; сравнение по всем трём байтам,
;  как в SPR_SYNC.  Две записи — потому что комнаты шести размещений
;  различны, и одновременно видно не больше двух (верхнее окно и нижнее).
;
;  Вход — разобранный объект в SO_* (как у SPR_APPEND).  Выход — SO_RET.
; ---------------------------------------------------------------------
CHA_TILE:
                ld      a,(CHL_N)
                cp      CHA_MAX
                jp      nc,SO_RET
                ld      l,a
                add     a,a
                add     a,l             ; *3
                ld      l,a
                ld      h,0x00
                ld      de,CHL
                add     hl,de
                ld      a,(SO_LO)
                ld      (hl),a
                inc     hl
                ld      a,(SO_HI)
                add     a,PLANE_E-PLANE_A
                ld      (hl),a          ; тот же столбец, но плоскость E000
                inc     hl
                ld      a,(SO_S)
                ld      (hl),a
                ; геометрия у всех шести размещений одна — запись банка 0x1E
                ld      a,(SO_W)
                ld      (CH_W),a
                ld      a,(SO_H)
                ld      (CH_H),a
                ld      hl,(SO_SRC)
                ld      (CH_SRC),hl
                ld      a,(CHL_N)
                inc     a
                ld      (CHL_N),a
                jp      SO_RET

; ---------------------------------------------------------------------
;  CHA_SYNC — привести плоскость E000 к списку кадра.  Зовётся ПЕРВЫМ делом
;  из A_SPRFLUSH, то есть после всех D0A0 кадра и ДО сброса PD_DIRTY.
;
;  PD_DIRTY = 1 значит «тайловые плоскости перестроены» (A_ROOMDRAW или
;  A_SPRCLEAR): нарисованного больше нет, стирать НЕЧЕГО и НЕЛЬЗЯ — под
;  коробкой уже лежит новая комната.  Этим же закрыт единственный путь, на
;  котором люстра пропадает из кадра: пропасть она может только со сменой
;  комнаты, а смена комнаты — это перерисовка половины экрана.
; ---------------------------------------------------------------------
CHA_SYNC:
                ld      a,(CHL_N)
                ld      hl,CHO_N
                or      (hl)
                ret     z               ; ни там, ни там ничего — выход даром
                ld      a,(PD_DIRTY)
                or      a
                jp      z,CHS_GO
                xor     a
                ld      (CHO_N),a       ; экран перестроен: забыть, не стирая
CHS_GO:
                xor     a
                ld      (CH_I),a
CHS_L:
                ld      a,(CH_I)
                ld      hl,CHL_N
                cp      (hl)
                jp      c,CHS_HASNEW
                ld      hl,CHO_N
                cp      (hl)
                jp      nc,CHS_DONE     ; оба списка кончились
                call    CHS_OLD
                call    SPR_WIPEBOX     ; новой нет, старую стереть
                jp      CHS_NX
CHS_HASNEW:
                ld      a,(CH_I)
                ld      hl,CHO_N
                cp      (hl)
                jp      nc,CHS_DRAW     ; старой нет — только нарисовать
                call    CHS_SAME
                jp      z,CHS_NX        ; не сдвинулась — НЕ ТРОГАЕМ
                call    CHS_OLD
                call    SPR_WIPEBOX     ; стереть старую коробку нулями ...
CHS_DRAW:
                call    CHS_NEW
                call    BLIT_OBJ        ; ... и нарисовать новую
CHS_NX:
                ld      a,(CH_I)
                inc     a
                ld      (CH_I),a
                cp      CHA_MAX
                jp      c,CHS_L
CHS_DONE:
                ld      de,CHL
                ld      hl,CHO
                ld      b,CHA_MAX*CH_LEN
                call    CPY_N           ; список кадра стал нарисованным
                ld      a,(CHL_N)
                ld      (CHO_N),a
                xor     a
                ld      (CHL_N),a
                ret

; CH_OFS — de = CH_I * CH_LEN
CH_OFS:
                ld      a,(CH_I)
                ld      e,a
                add     a,a
                add     a,e
                ld      e,a
                ld      d,0x00
                ret

; CHS_OLD / CHS_NEW — запись старого / нового списка в BL_*
CHS_OLD:
                ld      hl,CHO
                jp      CHS_LOAD
CHS_NEW:
                ld      hl,CHL
CHS_LOAD:
                push    hl
                call    CH_OFS
                pop     hl
                add     hl,de
                ld      a,(hl)
                ld      (BL_LO),a
                inc     hl
                ld      a,(hl)
                ld      (BL_HI),a
                inc     hl
                ld      a,(hl)
                ld      (BL_S),a
                ld      a,(CH_W)
                ld      (BL_W),a
                ld      a,(CH_H)
                ld      (BL_H),a
                ld      hl,(CH_SRC)
                ld      (BL_SRC),hl
                xor     a
                ld      (BL_MIR),a      ; BC22 зовёт D0A0 с a = 0x1E, без бита 7
                ret

; CHS_SAME — совпадают ли записи CHL[i] и CHO[i]?  Z=1 — да.
CHS_SAME:
                call    CH_OFS
                ld      hl,CHL
                add     hl,de
                push    hl
                ld      hl,CHO
                add     hl,de
                pop     de
                ld      b,CH_LEN
                jp      CMP_N
#endif

; SPR_APPEND — дописать объект (SO_LO..SO_SRC, SO_NUM) в SPRL
SPR_APPEND:
                ld      a,(SPRL_N)
                add     a,a
                add     a,a
                add     a,a             ; *8
                ld      l,a
                ld      h,0x00
                ld      de,SPRL
                add     hl,de
                ld      a,(SO_LO)
                ld      (hl),a
                inc     hl
                ld      a,(SO_HI)
                ld      (hl),a
                inc     hl
                ld      a,(SO_S)
                ld      (hl),a
                inc     hl
                ld      a,(SO_W)
                ld      (hl),a
                inc     hl
                ld      a,(SO_H)
                ld      (hl),a
                inc     hl
                ld      a,(SO_SRC)
                ld      (hl),a
                inc     hl
                ld      a,(SO_SRC+1)
                ld      (hl),a
                inc     hl
                ld      a,(SO_NUM)
                and     0x80
                ld      (hl),a          ; 0x80 = зеркало
                ld      a,(SPRL_N)
                inc     a
                ld      (SPRL_N),a
                ret

; ---------------------------------------------------------------------
;  A_SPRFLUSH — врезка в 1F64 (D664).  Один проход на кадр: дописать
;  героя, стереть всё старое, нарисовать всё новое.
; ---------------------------------------------------------------------
A_SPRFLUSH:
#if SCHEME == SCH_CPC21
                call    CHA_SYNC        ; ЛЮСТРА: читает PD_DIRTY ДО сброса
                xor     a
                ld      (PD_DIRTY),a    ; все D0A0 кадра уже прошли: если
                                        ; подставку надо было положить, она
                                        ; положена, и второй раз незачем
#endif
                call    HERO_APPEND
                ; --- ВТОРОЕ ОКНО.  Если (1A23) != 0, игра дублировала свой
                ; список спрайтов на нижнее окно со смещением Y +0x60
                ; (D655).  За 112 с прогона на MSX это не сработало ни разу
                ; (docs/render-paths.md, F.8 п.3), но путь живой: повторяем
                ; список со сдвигом строки на -0x60 (lo = 255 - (y+0x60)).
                ld      a,(G_1A23)
                or      a
                call    nz,SPR_DUP
                jp      SPR_SYNC

; SPR_DUP — дописать копию списка со смещением Y на второе окно
SPR_DUP:
                ld      a,(SPRL_N)
                or      a
                ret     z
                ld      (SD_N),a
                ld      hl,SPRL
                ld      (SD_PTR),hl
SPD_L:
                ld      a,(SPRL_N)
                cp      SPRL_MAX
                ret     nc
                ld      hl,(SD_PTR)
                ld      a,(hl)
                sub     0x60            ; y += 0x60  ->  lo -= 0x60
                ld      (SO_LO),a
                inc     hl
                ld      a,(hl)
                ld      (SO_HI),a
                inc     hl
                ld      a,(hl)
                ld      (SO_S),a
                inc     hl
                ld      a,(hl)
                ld      (SO_W),a
                inc     hl
                ld      a,(hl)
                ld      (SO_H),a
                inc     hl
                ld      a,(hl)
                ld      (SO_SRC),a
                inc     hl
                ld      a,(hl)
                ld      (SO_SRC+1),a
                inc     hl
                ld      a,(hl)
                ld      (SO_NUM),a
                inc     hl
                ld      (SD_PTR),hl
                call    SPR_APPEND
                ld      a,(SD_N)
                dec     a
                ld      (SD_N),a
                jp      nz,SPD_L
                ret

; ---------------------------------------------------------------------
;  SPR_SYNC — ПРИВЕСТИ ЭКРАН К СПИСКУ КАДРА, СЛОТ ЗА СЛОТОМ.
;
;  РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-09-22: «стереть всё и нарисовать всё заново» НЕ
;  ГОДИТСЯ — спрайты мерцают на железе уже сейчас, а такой проход добавил бы
;  неподвижным объектам стирание и отрисовку в каждом кадре.  Поэтому:
;
;    * слот, у которого НЕ ИЗМЕНИЛИСЬ ни адрес, ни сдвиг, ни образ, ни
;      зеркало, НЕ ТРОГАЕТСЯ ВОВСЕ — ни стирания, ни рисования.  Сравниваются
;      все 8 байт записи; образ задан адресом в банке, и банк статичен, так
;      что сравнение записи — это сравнение НАРИСОВАННОГО, точно;
;    * у изменившегося слота стирание и рисование идут ПОДРЯД, без других
;      слотов между ними: окно «спрайта нет» — это один блит (для 16x16
;      около 630 тактов), а не весь проход.
;
;  ОТОЖДЕСТВЛЕНИЕ СЛОТОВ — ПО ПОРЯДКУ В СПИСКЕ.  Игра зовёт D0A0 из
;  фиксированной цепочки обработчиков, поэтому i-й объект кадра — тот же
;  объект, что и вчера.  Если порядок всё-таки сбился, пара «стереть
;  старый i, нарисовать новый i» остаётся ВЕРНОЙ, просто лишней.
;  Хвост длинного старого списка стирается, хвост длинного нового рисуется.
; ---------------------------------------------------------------------
SPR_SYNC:
                ; ПЕРЕКРЫТИЯ.  Стирание нулями убирает из плоскости ВСЁ, что
                ; попало в коробку, — в том числе куски СОСЕДНЕГО объекта,
                ; который сам не изменился и потому не перерисовывается.
                ; (При xor такой беды не было: стирание снимало только свои
                ; биты.)  Поэтому запоминаем прямоугольник, накрытый всеми
                ; стираниями кадра, и вторым проходом перерисовываем
                ; НЕТРОНУТЫЕ объекты, которые в него попали.  Рисование идёт
                ; через `or` и идемпотентно, так что повтор безопасен.
                ld      a,0xFF
                ld      (WC0),a         ; min столбец стёртого
                ld      (WR1),a         ; min строка (она же max lo)
                xor     a
                ld      (WC1),a         ; max столбец
                ld      (WR0),a         ; max строка (min lo)
                ld      hl,SPRL
                ld      (SD_PTR),hl
                ld      hl,SPRO
                ld      (SD_OPTR),hl
                xor     a
                ld      (SD_I),a
SS_L:
                ld      a,(SD_I)
                ld      hl,SPRL_N
                cp      (hl)
                jp      c,SS_HASNEW
                ld      hl,SPRO_N
                cp      (hl)
                jp      nc,SS_DONE      ; оба списка кончились
                ; --- новых больше нет, старый ещё есть: стереть
                call    SS_OLD
                call    SS_KILL
                jp      SS_NX2
SS_HASNEW:
                ld      a,(SD_I)
                ld      hl,SPRO_N
                cp      (hl)
                jp      nc,SS_NEWONLY
                ; --- есть и старый, и новый: одинаковы ли?
                call    SS_SAME
                jp      z,SS_NX         ; НЕ ТРОГАЕМ
#if SCHEME == SCH_EXOLON
                call    SS_OLD
                call    SS_KILL         ; стирание — повторный xor образа
                jp      SS_NEWONLY
#else
                ; --- ОДНА ЗАПИСЬ ВМЕСТО СТИРАНИЯ И РИСОВАНИЯ.
                ; Байт коробки объединения старой и новой переходит из
                ; старого состояния в новое ОДНОЙ записью, окна «спрайта
                ; нет» не существует по построению — см. SPR_MERGE.
                ; Прежний путь («стереть коробку нулями, потом нарисовать
                ; `or`-ом») остался там же сторожем на случай, когда
                ; коробка объединения слишком велика (MG_FALL).
                call    SPR_MERGE
                jp      SS_NX2
#endif
SS_NEWONLY:
                call    SS_NEW
                xor     a
                ld      (WP_CN),a       ; стирать нечего
                ld      a,(BL_HI)
                or      a
                call    nz,BLIT_OBJ
SS_NX:
SS_NX2:
                ld      hl,(SD_PTR)
                ld      de,SPRL_LEN
                add     hl,de
                ld      (SD_PTR),hl
                ld      hl,(SD_OPTR)
                add     hl,de
                ld      (SD_OPTR),hl
                ld      a,(SD_I)
                inc     a
                ld      (SD_I),a
                cp      SPRL_MAX
                jp      c,SS_L
SS_DONE:
#if SCHEME == SCH_CPC21
                call    SPR_REDRAW      ; соседи, попавшие под стирание
#endif
                ; список кадра стал «нарисованным»
                ld      a,(SPRL_N)
                ld      (SPRO_N),a
                ld      hl,SPRO
                ld      (SD_OPTR),hl
                ld      hl,SPRL
                ld      (SD_PTR),hl
                ld      a,(SPRL_N)
                or      a
                jp      z,SS_CPE
SS_CPL:
                ld      hl,(SD_PTR)
                call    SPR_LOAD
                ld      (SD_PTR),hl
                call    SPR_SAVEREC
                ld      a,(SPRL_N)
                dec     a
                ld      (SPRL_N),a
                jp      nz,SS_CPL
SS_CPE:
                xor     a
                ld      (SPRL_N),a      ; следующий кадр наполнит заново
                ret

; Второй проход нужен ТОЛЬКО схеме «2 + 1»: там стирают нулями, и они
; убирают куски соседа.  В «Exolon» стирание — повторный xor того же
; образа, чужих битов оно не трогает.
#if SCHEME == SCH_CPC21
; ---------------------------------------------------------------------
;  SPR_REDRAW — второй проход: перерисовать НЕТРОНУТЫЕ объекты, которые
;  попали в прямоугольник, накрытый стираниями кадра.
;  Рисование через `or` идемпотентно, стирания тут нет вовсе.
; ---------------------------------------------------------------------
SPR_REDRAW:
                ld      a,(WC1)
                or      a
                ret     z               ; в кадре ничего не стирали
                ld      hl,SPRL
                ld      (SD_PTR),hl
                ld      hl,SPRO
                ld      (SD_OPTR),hl
                xor     a
                ld      (SD_I),a
SR_L:
                ld      a,(SD_I)
                ld      hl,SPRL_N
                cp      (hl)
                ret     nc
                ; ВТОРОЙ ПРОХОД ИДЁТ ПО ВСЕМ СЛОТАМ, А НЕ ТОЛЬКО ПО
                ; НЕТРОНУТЫМ.  Стирание слота i убирает из плоскости и то, что
                ; нарисовал слот j < i в ЭТОМ ЖЕ проходе: у героя (он в списке
                ; последний) коробка накрывает врага, уже нарисованного.
                ; Гейт cmp_hero_msx ловил это как 292 потерянных пикселя на
                ; итерации 70 — там герой и враг перекрываются.
                call    SS_NEW
                call    SR_HIT
                jp      nz,SR_NX
                xor     a
                ld      (WP_CN),a
                ld      a,(BL_HI)
                or      a
                call    nz,BLIT_OBJ
SR_NX:
                ld      hl,(SD_PTR)
                ld      de,SPRL_LEN
                add     hl,de
                ld      (SD_PTR),hl
                ld      hl,(SD_OPTR)
                add     hl,de
                ld      (SD_OPTR),hl
                ld      a,(SD_I)
                inc     a
                ld      (SD_I),a
                jp      SR_L

; SR_HIT — коробка BL_* пересекает стёртый прямоугольник?  Z=1 — да.
SR_HIT:
                ld      a,(BL_HI)
                and     0x1F
                ld      hl,WC1
                cp      (hl)
                jp      z,SRH_C2
                jp      nc,SRH_NO       ; левее правого края? нет
SRH_C2:
                ld      a,(BL_HI)
                and     0x1F
                ld      hl,BL_W
                add     a,(hl)
                ld      hl,WC0
                cp      (hl)
                jp      c,SRH_NO        ; правее левого края? нет
                ld      a,(BL_LO)       ; верх объекта (больший lo)
                ld      hl,WR0
                cp      (hl)
                jp      c,SRH_NO        ; объект целиком ниже прямоугольника
                ld      a,(BL_LO)
                ld      hl,BL_H
                sub     (hl)
                inc     a               ; низ объекта (меньший lo)
                ld      hl,WR1
                cp      (hl)
                jp      z,SRH_YES
                jp      nc,SRH_NO       ; объект целиком выше
SRH_YES:
                xor     a               ; Z=1 — пересекает
                ret
SRH_NO:
                ld      a,0x01
                or      a
                ret

#endif
; SS_SAME — совпадают ли записи (SD_PTR) и (SD_OPTR)?  Z=1 — да.
SS_SAME:
                ld      hl,(SD_PTR)
                ex      de,hl
                ld      hl,(SD_OPTR)
                ld      b,SPRL_LEN
                jp      CMP_N

; SS_OLD / SS_NEW — запись старого / нового списка в BL_*
SS_OLD:
                ld      hl,(SD_OPTR)
                jp      SPR_LOAD
SS_NEW:
                ld      hl,(SD_PTR)
                jp      SPR_LOAD

; SS_KILL — убрать с экрана то, что описано в BL_*.
;  «2 + 1»: push нулей по коробке.  «Exolon»: плоскость A000 общая с
;  тайлами, нулями там стирать нельзя — повторный xor того же образа.
SS_KILL:
                ld      a,(BL_HI)
                or      a
                ret     z
#if SCHEME == SCH_EXOLON
                jp      BLIT_OBJ        ; xor того же образа = стирание
#else
                jp      SPR_WIPEBOX
#endif

; ---------------------------------------------------------------------
;  SPR_ERASEALL — убрать с экрана ВСЁ нарисованное.  Зовётся только там,
;  где экран всё равно перестраивается целиком: гашение спрайтов
;  (A_SPRCLEAR) и сторож тайлов схемы «Exolon».
; ---------------------------------------------------------------------
SPR_ERASEALL:
                ld      a,(SPRO_N)
                or      a
                ret     z
                ld      (SE_N),a
                ld      hl,SPRO
                ld      (SE_PTR),hl
SE_L:
                ld      hl,(SE_PTR)
                call    SPR_LOAD
                ld      (SE_PTR),hl
                call    SS_KILL
                ld      a,(SE_N)
                dec     a
                ld      (SE_N),a
                jp      nz,SE_L
                xor     a
                ld      (SPRO_N),a
                ret

; SPR_LOAD — запись по hl -> BL_*; hl уходит на следующую
SPR_LOAD:
                ld      a,(hl)
                ld      (BL_LO),a
                inc     hl
                ld      a,(hl)
                ld      (BL_HI),a
                inc     hl
                ld      a,(hl)
                ld      (BL_S),a
                inc     hl
                ld      a,(hl)
                ld      (BL_W),a
                inc     hl
                ld      a,(hl)
                ld      (BL_H),a
                inc     hl
                ld      a,(hl)
                ld      (BL_SRC),a
                inc     hl
                ld      a,(hl)
                ld      (BL_SRC+1),a
                inc     hl
                ld      a,(hl)
                ld      (BL_MIR),a
                inc     hl
                ret

; CMP_N — сравнить b байт: de = источник, hl = приёмник; Z=1 — совпали
CMP_N:
                ld      a,(de)
                cp      (hl)
                ret     nz
                inc     de
                inc     hl
                dec     b
                jp      nz,CMP_N
                ret

; CPY_N — скопировать b байт: de = источник, hl = приёмник
CPY_N:
                ld      a,(de)
                ld      (hl),a
                inc     de
                inc     hl
                dec     b
                jp      nz,CPY_N
                ret

; SPR_SAVEREC — BL_* -> очередная запись SPRO
SPR_SAVEREC:
                ld      hl,(SD_OPTR)
                ld      a,(BL_LO)
                ld      (hl),a
                inc     hl
                ld      a,(BL_HI)
                ld      (hl),a
                inc     hl
                ld      a,(BL_S)
                ld      (hl),a
                inc     hl
                ld      a,(BL_W)
                ld      (hl),a
                inc     hl
                ld      a,(BL_H)
                ld      (hl),a
                inc     hl
                ld      a,(BL_SRC)
                ld      (hl),a
                inc     hl
                ld      a,(BL_SRC+1)
                ld      (hl),a
                inc     hl
                ld      a,(BL_MIR)
                ld      (hl),a
                inc     hl
                ld      (SD_OPTR),hl
                ret

; Стирание НУЛЯМИ — только схема «2 + 1»: в «Exolon» плоскость A000 общая
; с тайлами, и стирание там — повторный xor того же образа.
#if SCHEME == SCH_CPC21
; ---------------------------------------------------------------------
;  СТИРАНИЕ КОРОБКИ НУЛЯМИ ЧЕРЕЗ SP, ПОСТОЛБЦОВО.
;  WP_SETUP — запомнить коробку из BL_* ((BL_W)+1 столбцов на (BL_H) строк);
;  WP_ONE   — стереть ОДИН столбец и сдвинуться на следующий;
;  WP_REST  — стереть всё, что осталось.
;  Высота округляется вверх до чётной: лишняя строка ложится ПОД образ, в ту
;  же плоскость подвижных объектов, и всё равно перерисовывается.  Нижняя
;  строка коробки не ниже 33-й строки памяти (y <= 191, h <= 32), так что за
;  границу столбца выход невозможен.
;  Кусок под di — один столбец: 16 пар по 26 тактов плюс обвязка, около 470
;  тактов (замер по листингу).
; ---------------------------------------------------------------------
WP_SETUP:
                ld      a,(BL_HI)
                ld      (WP_HI),a
                ld      a,(BL_LO)
                ld      (WP_LO),a
                ld      a,(BL_H)
                inc     a
                rrca
                and     0x7F
                ld      (WP_PAIRS),a    ; ceil(h/2) пар
                ld      a,(BL_HI)
                or      a
                jp      z,WPS_NONE
                ld      a,(BL_W)
                inc     a               ; коробка на столбец шире образа
                ld      (WP_CN),a
                ; --- прямоугольник, накрытый стираниями кадра
                ld      a,(BL_HI)
                and     0x1F
                ld      c,a
                ld      hl,WC0
                cp      (hl)
                jp      nc,WPS_C1
                ld      (hl),a
WPS_C1:
                ld      a,c
                ld      hl,BL_W
                add     a,(hl)
                ld      hl,WC1
                cp      (hl)
                jp      c,WPS_R
                ld      (hl),a
WPS_R:
                ld      a,(BL_LO)       ; верх коробки: БОЛЬШИЙ lo
                ld      hl,WR1
                cp      (hl)
                jp      c,WPS_R0
                ld      (hl),a
WPS_R0:
                ld      a,(BL_LO)       ; низ коробки: МЕНЬШИЙ lo
                ld      hl,BL_H
                sub     (hl)
                inc     a
                ld      hl,WR0
                cp      (hl)
                jp      nc,WPS_END
                ld      (hl),a
WPS_END:
                ret
WPS_NONE:
                xor     a
                ld      (WP_CN),a
                ret

WP_REST:
                ld      a,(WP_CN)
                or      a
                ret     z
                call    WP_ONE
                jp      WP_REST

WP_ONE:
                ld      hl,0x0000
                add     hl,sp
                ld      (TP_SAV),hl
                ld      a,(WP_LO)
                ld      l,a
                ld      a,(WP_HI)
                ld      h,a
                inc     hl              ; SP на байт выше верхней строки
                ld      a,(WP_PAIRS)
                ld      b,a
                or      a
                jp      z,WP_NX
                ld      de,0x0000
                di
                ld      sp,hl
WP_L:
                push    de
                dec     b
                jp      nz,WP_L
                ld      hl,(TP_SAV)
                ld      sp,hl
                ei
WP_NX:
                ld      a,(WP_HI)
                inc     a
                ld      (WP_HI),a
                ld      a,(WP_CN)
                dec     a
                ld      (WP_CN),a
                ret

; SPR_WIPEBOX — стереть коробку целиком (гашение, сторож «Exolon»)
SPR_WIPEBOX:
                call    WP_SETUP
                jp      WP_REST

; ---------------------------------------------------------------------
;  SPR_MERGE — ОДНА ЗАПИСЬ ВМЕСТО СТИРАНИЯ И РИСОВАНИЯ (решение владельца
;  2026-09-22, docs/adapter-requirements.md § 0d).
;
;  ЧТО БЫЛО.  Изменившийся слот сначала СТИРАЛСЯ нулями (SPR_WIPEBOX,
;  push), потом РИСОВАЛСЯ (BLIT_OBJ, or).  Между двумя проходами байт
;  плоскости лежал пустым — замер tools/flicker_probe_v06js.js: окно
;  пустоты 4.4 тыс. тактов в среднем, 30 тыс. максимум (полкадра), и луч
;  успевал пройти по пустому месту.  Это и есть мерцание на железе.
;
;  ЧТО СТАЛО.  Берётся КОРОБКА ОБЪЕДИНЕНИЯ старой и новой (по столбцам и
;  по строкам), и в неё ОДНИМ проходом пишется новый образ: где новых битов
;  нет — нули.  КАЖДЫЙ байт плоскости переходит из старого состояния в
;  новое ОДНОЙ записью (`ld (de),a`), окна «спрайта нет» не существует по
;  построению.  Луч, попавший внутрь коробки во время записи, видит
;  полстарого-полнового (СРЕЗ) — объект на месте, не мерцает.
;
;  ПОЧЕМУ НУЖНА КАРТА ПЕРЕНОСА.  Байт образа, сдвинутый на s = x and 7,
;  ложится в ДВА соседних столбца плоскости: (t and m1) в свой, (t and m2)
;  в следующий.  Значит столбец приёмника p собирается из ДВУХ столбцов
;  источника — p-го (маска m1) и (p-1)-го (маска m2).  Блиттер BLIT_OBJ
;  обходит столбцы ИСТОЧНИКА и дописывает `or`-ом, ему это всё равно;
;  здесь запись ОДНА, значит в момент записи нужны оба слагаемых.  Второе
;  (из предыдущего столбца) кладётся в MG_CARRY на предыдущем витке — один
;  байт на строку.
;
;  ПОЧЕМУ ПЕРЕКРЫТИЯ НЕ ЛОМАЮТСЯ.  Запись (а не `or`) убирает из коробки и
;  куски СОСЕДНЕГО объекта — ровно так же, как это делало стирание нулями.
;  Второй проход SPR_REDRAW перерисовывает `or`-ом всё, что попало в
;  прямоугольник кадра; прямоугольник считает WP_SETUP, и ему подсовывается
;  коробка ОБЪЕДИНЕНИЯ (раньше — старая).
;
;  СТОРОЖ.  Слоты отождествляются ПО ПОРЯДКУ в списке, и если порядок
;  сбился, «старый i» и «новый i» — разные объекты в разных концах экрана;
;  коробка объединения тогда растягивается на пол-экрана.  Замер
;  (flicker_probe, 300 итераций): столбцов 4..6 в 466 случаях из 481,
;  строк 16..37 в 465 — но есть хвост 25 столбцов и 106 строк.  Поэтому
;  коробка больше MG_MAXC x MG_MAXN уходит на СТАРЫЙ путь «стереть и
;  нарисовать» (MG_FB считает такие случаи), и мерцает в этих редких
;  случаях ровно как раньше.
;
;  Вход: SD_PTR — запись кадра, SD_OPTR — нарисованная.  Обе НЕ равны
;  (SS_SAME проверил) и обе существуют.
; ---------------------------------------------------------------------
SPR_MERGE:
                ld      hl,(SD_OPTR)    ; геометрия СТАРОЙ коробки — прямо из
                ld      a,(hl)          ; записи: lo, hi, (сдвиг), w, h
                ld      (MG_OLO),a
                inc     hl
                ld      a,(hl)
                ld      (MG_OHI),a
                inc     hl
                inc     hl
                ld      a,(hl)
                ld      (MG_OW),a
                inc     hl
                ld      a,(hl)
                ld      (MG_OH),a
                call    SS_NEW          ; BL_* — новая запись
                ld      a,(BL_HI)
                or      a
                jp      z,MG_KILLOLD    ; нового нет — просто стереть старое
                ld      a,(MG_OHI)
                or      a
                jp      z,MG_NEWONLY    ; старого нет — просто нарисовать
MG_UNION:
                ; --- СТОЛБЦЫ: MG_C0 = min(левых), правый край = max(правых)
                ld      c,a             ; c = старший байт старой
                ld      a,(BL_HI)
                cp      c
                jp      nc,MG_C0OK
                ld      c,a
MG_C0OK:
                ld      a,c
                ld      (MG_C0),a
                ld      a,(MG_OHI)
                ld      hl,MG_OW
                add     a,(hl)
                ld      b,a             ; правый столбец старой коробки
                ld      a,(BL_HI)
                ld      hl,BL_W
                add     a,(hl)
                cp      b
                jp      c,MG_C1OK
                ld      b,a
MG_C1OK:
                ld      a,b
                sub     c
                inc     a
                ld      (MG_CN),a
                cp      MG_MAXC+1
                jp      nc,MG_FALL      ; сторож: коробка слишком широкая
                ; --- СТРОКИ: верх = БОЛЬШИЙ lo, низ = МЕНЬШИЙ
                ld      a,(MG_OLO)
                ld      c,a
                ld      a,(BL_LO)
                cp      c
                jp      c,MG_R1OK
                ld      c,a
MG_R1OK:
                ld      a,c
                ld      (MG_LO),a
                ld      a,(MG_OLO)
                ld      hl,MG_OH
                sub     (hl)
                inc     a
                ld      b,a             ; низ старой коробки
                ld      a,(BL_LO)
                ld      hl,BL_H
                sub     (hl)
                inc     a
                cp      b
                jp      nc,MG_R0OK
                ld      b,a
MG_R0OK:
                ld      a,c
                sub     b
                inc     a
                ld      (MG_N),a
                cp      MG_MAXN+1
                jp      nc,MG_FALL      ; сторож: коробка слишком высокая
                ; --- пустые строки сверху и снизу от нового образа
                ld      a,c             ; верх объединения
                ld      hl,BL_LO
                sub     (hl)
                ld      (MG_G1),a
                ld      c,a
                ld      a,(BL_H)
                add     a,c
                ld      c,a             ; G1 + h
                ld      a,(MG_N)
                sub     c
                ld      (MG_G2),a
                ld      a,(BL_H)
                cpl
                inc     a
                ld      (MG_CH),a       ; карта переноса = 0x100 - h
                ; --- ПРЯМОУГОЛЬНИК КАДРА по коробке ОБЪЕДИНЕНИЯ.  Заодно
                ; WP_SETUP выставляет WP_PAIRS/WP_LO — ими чистит пустые
                ; столбцы WP_ONE.  Высота округляется вверх до чётной: пара
                ; push'ей неделима, лишняя строка ложится ПОД коробку и
                ; учтена в прямоугольнике.
                ld      a,(MG_C0)
                ld      (BL_HI),a
                ld      a,(MG_LO)
                ld      (BL_LO),a
                ld      a,(MG_CN)
                dec     a
                ld      (BL_W),a
                ld      a,(MG_N)
                inc     a
                and     0xFE
                ld      (BL_H),a
                call    WP_SETUP
                call    SS_NEW          ; BL_* обратно на новую запись
                ld      a,(BL_S)
                call    SET_ROT         ; сдвиг и маски — как у блиттера
                xor     a
                ld      (MG_J),a
MG_COL:
                ld      a,(MG_J)
                ld      hl,MG_CN
                cp      (hl)
                jp      nc,MG_DONE
                ld      hl,MG_C0
                add     a,(hl)
                ld      (MG_P),a        ; страница приёмника
                ld      hl,BL_HI
                sub     (hl)            ; s — номер столбца ИСТОЧНИКА
                jp      c,MG_ZCOL       ; левее образа — столбец пустой
                ld      hl,BL_W
                cp      (hl)
                jp      c,MG_SCOL       ; s < w — столбец образа
                jp      z,MG_ZSRC       ; s = w — только перенос
                jp      MG_ZCOL         ; правее образа — пустой
; --- пустой столбец: ни образа, ни переноса (карта переноса там нулевая)
MG_ZCOL:
                ld      a,(MG_P)
                ld      (WP_HI),a
                ld      a,(MG_LO)
                ld      (WP_LO),a
                call    WP_ONE          ; нули парами через SP
                jp      MG_NX
; --- столбец, в который приходит только перенос: источник — сорок нулей
MG_ZSRC:
                ld      hl,MG_ZBUF
                ld      (MG_SRC),hl
                jp      MG_GO
; --- столбец образа: адрес столбца в банке (при зеркале — зеркальный
;     столбец, развёрнутый по битам в MIRBUF, как у BLIT_OBJ)
MG_SCOL:
                ld      c,a
                ld      a,(BL_MIR)
                or      a
                jp      z,MG_NOMIR
                ld      a,(BL_W)
                dec     a
                sub     c
                ld      c,a
MG_NOMIR:
                ld      hl,(BL_SRC)
                ld      a,(BL_H)
                ld      e,a
                ld      d,0x00
MG_MUL:
                ld      a,c
                or      a
                jp      z,MG_MULE
                add     hl,de
                dec     c
                jp      MG_MUL
MG_MULE:
                ld      (MG_SRC),hl
                ld      a,(BL_MIR)
                or      a
                jp      z,MG_GO
                call    MIR_COL
                ld      hl,MIRBUF
                ld      (MG_SRC),hl
; --- ЗАПИСЬ СТОЛБЦА: пустые строки сверху, образ, пустые снизу
MG_GO:
                ld      a,(MG_P)
                ld      d,a
                ld      a,(MG_LO)
                ld      e,a             ; de — верхняя строка столбца
                ld      a,(MG_G1)
                or      a
                call    nz,MG_ZROWS
                ld      hl,(MG_SRC)
                ld      b,h
                ld      c,l             ; bc — столбец источника
                ld      a,(MG_CH)
                ld      l,a
                ld      h,MG_CARRY_PG   ; hl — карта переноса
MG_L:
                ld      a,(bc)
                inc     bc
MGROT:
                nop
                nop
                nop
                nop
                nop
                nop
                nop                     ; s поворотов rrca (SET_ROT)
                push    af              ; t понадобится дважды
MGM1:
                and     0xFF            ; что остаётся в ЭТОМ столбце
                or      (hl)            ; плюс перенос из предыдущего
                ld      (de),a          ; ЕДИНСТВЕННАЯ запись байта
                dec     de
                pop     af
MGM2:
                and     0x00            ; что уедет в СЛЕДУЮЩИЙ столбец
                ld      (hl),a
                inc     l
                jp      nz,MG_L         ; карта кончается на границе страницы
                ld      a,(MG_G2)
                or      a
                call    nz,MG_ZROWS
MG_NX:
                ld      a,(MG_J)
                inc     a
                ld      (MG_J),a
                jp      MG_COL
MG_DONE:
                xor     a
                ld      (WP_CN),a       ; стирать больше нечего
                ret

; MG_ZROWS — a пустых строк столбца: de идёт вниз
MG_ZROWS:
                ld      b,a
                xor     a
MGZ_L:
                ld      (de),a
                dec     de
                dec     b
                jp      nz,MGZ_L
                ret

; MG_NEWONLY / MG_KILLOLD — вырожденные случаи (их же делал прежний код)
MG_NEWONLY:
                xor     a
                ld      (WP_CN),a
                jp      BLIT_OBJ
MG_KILLOLD:
                call    SS_OLD
                jp      SS_KILL

; MG_FALL — коробка объединения слишком велика: старый путь «стереть
; коробку нулями, потом нарисовать».  Такой слот мерцает, как до правки.
; MG_FALL — коробка объединения слишком велика.  Так бывает, когда
; порядок слотов сбился и «старый i» с «новым i» — РАЗНЫЕ объекты в разных
; концах экрана: объединять их коробки незачем (и дорого).  Старая коробка
; стирается нулями, а НОВАЯ пишется тем же слиянием, только объединять её
; не с чем — коробка объединения равна новой.  Новый объект и здесь
; появляется ОДНОЙ записью на байт; исчезает при этом объект СТАРЫЙ, и это
; правильно: его на новом месте нет.
MG_FALL:
                ld      hl,(MG_FB)
                inc     hl
                ld      (MG_FB),hl
                call    SS_OLD
                call    WP_SETUP
                call    WP_REST         ; старую коробку — нулями
                call    SS_NEW
                ld      a,(BL_HI)
                or      a
                ret     z
                ld      (MG_OHI),a      ; «старая коробка» = новая:
                ld      a,(BL_LO)       ; объединение выродится в неё
                ld      (MG_OLO),a
                ld      a,(BL_W)
                ld      (MG_OW),a
                ld      a,(BL_H)
                ld      (MG_OH),a
                ld      a,(MG_OHI)
                jp      MG_UNION

#endif

; ---------------------------------------------------------------------
;  BLIT_OBJ — образ ИЗ БАНКА (по столбцам) в плоскость подвижных объектов.
;  Вход: BL_LO/BL_HI адрес левого столбца, BL_S сдвиг, BL_W столбцов
;  источника, BL_H строк, BL_SRC данные, BL_MIR зеркало.
;  Столбец источника лежит ПОДРЯД — ровно то, ради чего банк перепакован:
;  прежде столбцы собирал HR_PREP (герой) и D447 (спрайты), теперь не
;  собирает никто.
; ---------------------------------------------------------------------
BLIT_OBJ:
                ld      a,(BL_S)
                call    SET_ROT
                ld      a,(BL_W)
                ld      (BO_CN),a
                ld      a,(BL_HI)
                ld      (BO_HI),a
                ld      hl,(BL_SRC)
                ld      a,(BL_MIR)
                or      a
                jp      z,BO_SET
                ; зеркало: левый столбец приёмника берёт ПОСЛЕДНИЙ столбец
                ; источника, и дальше источник идёт назад
                ld      a,(BL_W)
                dec     a
                ld      e,a
                ld      d,0x00
                ld      a,(BL_H)
                ld      c,a
                ld      b,0x00
BO_MUL:
                ld      a,e
                or      a
                jp      z,BO_SET
                add     hl,bc
                dec     e
                jp      BO_MUL
BO_SET:
                ld      (BO_SRC),hl
BO_COL:
                ld      hl,(BO_SRC)
                ld      a,(BL_MIR)
                or      a
                jp      z,BO_NOM
                call    MIR_COL         ; развернуть столбец в MIRBUF
                ld      hl,MIRBUF
BO_NOM:
                ld      b,h
                ld      c,l
                ld      a,(BO_HI)
                ld      h,a
                ld      a,(BL_LO)
                ld      l,a
                ld      a,(BL_H)
                ld      d,a
                call    SPR_ROWS
BO_DRAWN:                               ; метка для замера окна «спрайта нет»
                ld      a,(BO_HI)
                inc     a
                ld      (BO_HI),a
                ld      hl,(BO_SRC)
                ld      a,(BL_H)
                ld      c,a
                ld      b,0x00
                ld      a,(BL_MIR)
                or      a
                jp      nz,BO_BACK
                add     hl,bc
                jp      BO_NXT
BO_BACK:
                ld      a,l             ; hl -= h
                sub     c
                ld      l,a
                jp      nc,BO_NXT
                dec     h
BO_NXT:
                ld      (BO_SRC),hl
                ld      a,(BO_CN)
                dec     a
                ld      (BO_CN),a
                jp      nz,BO_COL
                ret

; MIR_COL — столбец источника (hl) развернуть по битам в MIRBUF.
; Второй, заранее развёрнутой копии банка нет: решение по замеру,
; tools/repack_banks.py.
MIR_COL:
                ld      b,h
                ld      c,l
                ld      de,MIRBUF
                ld      a,(BL_H)
                ld      (MC_N),a
                ld      h,REV_PAGE
MC_L:
                ld      a,(bc)
                inc     bc
                ld      l,a
                ld      a,(hl)
                ld      (de),a
                inc     de
                ld      a,(MC_N)
                dec     a
                ld      (MC_N),a
                jp      nz,MC_L
                ret

; ---------------------------------------------------------------------
;  SPR_ROWS — d строк одного столбца источника: байт растекается в два
;  соседних столбца плоскости.  bc = источник (подряд!), hl = приёмник.
;  «2 + 1» кладёт через `or` (перекрытия сливаются), «Exolon» — через
;  `xor` (там стирание — повторный проход тем же образом).
; ---------------------------------------------------------------------
SPR_ROWS:
                ld      a,(bc)
                inc     bc
ROTSLOT:
                nop
                nop
                nop
                nop
                nop
                nop
                nop
                ld      e,a
ANI1:
                and     0xFF            ; что остаётся в этом столбце
#if SCHEME == SCH_EXOLON
                xor     (hl)
#else
                or      (hl)
#endif
                ld      (hl),a
                inc     h
                ld      a,e
ANI2:
                and     0x00            ; что уехало в следующий
#if SCHEME == SCH_EXOLON
                xor     (hl)
#else
                or      (hl)
#endif
                ld      (hl),a
                dec     h
                dec     l
                dec     d
                jp      nz,SPR_ROWS
                ret

; SET_ROT — выставить сдвиг a (0..7), если он не тот, что стоит сейчас.
; Витков два — блиттер (ROTSLOT/ANI1/ANI2) и слияние (MGROT/MGM1/MGM2), —
; и оба самомодифицируются одной раздачей: маски у них те же.
SET_ROT:
                ld      hl,SPR_LASTS
                cp      (hl)
                ret     z
                ld      (hl),a
                ; s поворотов rrca в тело цикла, маски в операнды and
                ld      c,a
                ld      hl,ROTSLOT
                call    SSR_FILL
#if SCHEME == SCH_CPC21
                ld      a,(SPR_LASTS)
                ld      c,a
                ld      hl,MGROT
                call    SSR_FILL
#endif
                ld      a,(SPR_LASTS)   ; маска = 0xFF >> s
                ld      c,a
                ld      a,0xFF
SSR_ML:
                ld      b,a
                ld      a,c
                or      a
                jp      z,SSR_M
                dec     c
                ld      a,b
                or      a               ; сбросить перенос
                rra
                jp      SSR_ML
SSR_M:
                ld      a,b
                ld      (ANI1+1),a
#if SCHEME == SCH_CPC21
                ld      (MGM1+1),a
#endif
                cpl
                ld      (ANI2+1),a
#if SCHEME == SCH_CPC21
                ld      (MGM2+1),a
#endif
                ret

; SSR_FILL — c поворотов rrca в семь слотов по hl, остальные nop
SSR_FILL:
                ld      b,0x07
SSR_L:
                ld      a,c
                or      a
                jp      z,SSR_NOP
                ld      (hl),0x0F       ; rrca
                dec     c
                jp      SSR_NX
SSR_NOP:
                ld      (hl),0x00       ; nop
SSR_NX:
                inc     hl
                dec     b
                jp      nz,SSR_L
                ret

; =====================================================================
;  ГЕРОЙ («гномик»)
; =====================================================================
;  На MSX героя рисует не аппаратный спрайт, а собственный движок
;  D690..DAC9: он держит окно 6x6 знакомест в низкой RAM (8000..82F3),
;  каждый кадр собирает его заново из чистой копии фона, накладывает
;  OR-ом битмап и выгружает 288 байт образов + 36 заливок цвета в VRAM.
;  Всё это существует только ради save-under, а у нас фон не трогается
;  вовсе — плоскость A000 принадлежит подвижным объектам.
;
;  Перехвачены ДВЕ точки:
;    2168 (D868) -> A_HERO       — «нарисовать героя»: только ЗАПОМИНАЕТ
;                                  кадр/зеркало/координаты;
;    200D (D70D) -> ret (байт)   — выгрузка окна, см. BYTE_TAB.
;  Оба стирающих входа (CCD0 = 15D0 и DACF = 23CF) отдельного перехвата
;  НЕ требуют: они работают тем же D868, отличаясь только байтом
;  HERO_ERASEF, который сами же и ставят, — A_HERO его читает.
;
;  ЭТАП E: HR_PREP УМЕР.  Он раскладывал кадр героя по столбцам в HR_SAV
;  (96 байт, виток на байт) — ровно ту работу, которую теперь сделала
;  ПЕРЕПАКОВКА БАНКА.  Герой стал обычной записью списка объектов и идёт
;  тем же BLIT_OBJ, что и всё остальное; своего блиттера у него нет.
;
;  ПРО ix.  Оригинальный D868 заполнял 9-байтную запись объекта по ix и
;  двигал ix на 9.  Ни одно её поле живой код не читает (docs/render-paths
;  F.7), поэтому A_HERO ix НЕ ТРОГАЕТ, и запрет на IX в подмножестве i8080
;  обходить не пришлось.
; ---------------------------------------------------------------------
;  A_HERO — перехват D868.  a = кадр (бит 7 = зеркало), b = X, c = Y низа.
;  Портит только a — как и оригинал (тот портил ещё bc/de/hl/ix).
; ---------------------------------------------------------------------
A_HERO:
                ld      (HR_FRM),a
                ld      a,b
                ld      (HR_X),a
                ld      a,c
                ld      (HR_Y),a
                ld      a,(HERO_ERASEF)
                cp      0xC9            ; D7A8 подменён на ret = «стереть»
                ld      a,0x00
                jp      z,AH_ST
                inc     a
AH_ST:
                ld      (HR_LIVE),a
                ret

; ---------------------------------------------------------------------
;  HERO_APPEND — герой как запись списка объектов.
;  ВЕРХ ОБРАЗА = Y - 8*ceil(высота/8), а НЕ Y - высота.  Y — низ, но окно
;  save-under на MSX ходило ЗНАКОМЕСТАМИ: D7A8 отсчитывал ceil(h/8) рядов
;  окна вверх от его низа и добавлял Y and 7 (D8CF кладёт в 20A5 именно
;  Y and 7).  Сумма сворачивается ровно в Y - 8*ceil(h/8); у образа 24x31
;  это на строку выше, чем Y - h.  Поймано сверкой с живым MSX.
; ---------------------------------------------------------------------
HERO_APPEND:
                ld      a,(HR_LIVE)
                or      a
                ret     z
                ld      a,(SPRL_N)
                cp      SPRL_MAX
                ret     nc
                ld      a,(HR_FRM)
                and     0x80
                ld      (SO_NUM),a      ; в записи списка нужен только бит 7
                ld      a,(HR_FRM)
                and     0x7F
                add     a,a
                ld      l,a
                ld      h,0x00
                ld      de,BKP_SPR
                add     hl,de
                ld      a,(hl)
                inc     hl
                ld      h,(hl)
                ld      l,a
                ld      a,(hl)          ; высота кадра
                ld      (SO_H),a
                inc     hl
                ld      a,(hl)
                ld      (SO_W),a
                cp      0x03            ; движок героя умеет ровно 3 байта
                ret     nz              ; ширины (24 пикселя)
                inc     hl
                ld      (SO_SRC),hl
                ld      a,(SO_H)
                cp      HERO_H+1
                ret     nc              ; выше коробки — не рисуем
                add     a,0x07
                and     0xF8
                ld      b,a
                ld      a,(HR_Y)
                sub     b
                cp      0xE0            ; верх выше экрана (отрицательный)
                ret     nc              ; или ниже 223-й строки
                cpl
                ld      (SO_LO),a
                ld      a,(HR_X)
                and     0xF8
                rrca
                rrca
                rrca
                cp      0x1D            ; коробке нужны 4 столбца
                ret     nc
                add     a,PLANE_SPR
                ld      (SO_HI),a
                ld      a,(HR_X)
                and     0x07
                ld      (SO_S),a
                jp      SPR_APPEND

; =====================================================================
;  ЭТАП F: «СКРЫТОЕ ЦВЕТОМ» БОЛЬШЕ НЕ РИСУЕТСЯ, А РИСУЕТСЯ ПРИ ПОКАЗЕ
;  (ТОЛЬКО ОСНОВНАЯ СХЕМА «2 + 1»)
; =====================================================================
;  Чернила MSX 1 — «чёрное на чёрном»: ими игра ПРЯЧЕТ уже нарисованное.
;  В схеме «2 + 1» кода под «хранить, но не показывать» нет, и до этого
;  этапа чернила 1 давали код 1 (белый) — спрятанное было ВИДНО.  Теперь
;  INK2CODE[1] = 0: в таком знакоместе пикселей нет вовсе, а всё, что игра
;  прятала, рисуется заново в момент показа.  Прятала она ровно в трёх
;  местах (сплошной поиск — docs/render-paths.md, D.0):
;
;    * ТИТРЫ.  Текст печатался в скрытые строки 17..19 и переносился в
;      видимые 9..11 процедурой D021 (32 768 чтений + 16 384 записи VRAM).
;      Теперь печать НЕ ИДЁТ ВОВСЕ (A_TITLINE только запоминает поток и его
;      длину), а перенос заменён на A_DISSOLVE — тот же эффект по тем же
;      восьми битовым маскам, но источник = шрифт по тексту.
;    * ПАНЕЛЬ HUD.  Её рисовали ДО того, как CF07 задаст цвет.  Порядок в
;      2:CA3D переставлен байтами (BYTE_TAB): сначала CF07, потом DAE9.
;      Это то же самое отклонение «сначала цвет, потом образ», что уже
;      принято для элементов комнаты на этапе D.
;    * ЗНАЧКИ OBJETOS.  Их рисовала CD94 заранее (теперь она ret), а
;      показывала смена цвета CD12/CD1F/CD2C.  Теперь показ и есть
;      отрисовка: A_ICONCOL красит прямоугольник, как красил CF28, и тут же
;      выводит образ 0x17/0x18/0x19 из банка 294B через A_TILEIMG.
; ---------------------------------------------------------------------

#if SCHEME == SCH_CPC21
; --- A_TITSTART — перехват 2:CF3E (183E), вход в титры.
; На экране после CFCA ничего нет, значит и «прежней строки», которую
; растворение обязано стереть, тоже нет.
A_TITSTART:
                call    G_18CA          ; CFCA: гашение спрайтов + очистка
                xor     a
                ld      (TT_PLEN),a
                call    A_PALSTART      ; стартовая палитра вместо цветов комнаты
                jp      G_1841          ; дальше оригинал: цвет строк 9..11

; --- A_ENDSTART — перехват 2:CC0D (150D), вход на ЭКРАН ИТОГА
; («ПРОЙДЕНО / 00% / ПРИКЛЮЧЕНИЯ»; дальше CF28 заливает цвет, CDF9 печатает,
; CFAA ждёт клавишу).  Решение владельца 2026-09-22: «по надписи окончания
; игры тоже фиксируем палитру» — по той же причине, что и у титров, и тем же
; кодом.  Перехваченные три байта — `call CFCA` (CD CA 18), их и повторяем.
A_ENDSTART:
                call    A_PALSTART
                call    G_18CA          ; оригинал 150D: гашение + очистка
                jp      G_1510          ; дальше оригинал экрана итога

; --- A_PALSTART — ВЕРНУТЬ СТАРТОВУЮ ПАЛИТРУ (решение владельца 2026-09-22).
;  Титры и экран итога показываются не только при старте: после конца игры
;  управление приходит туда же, а PAL_TAB к этому времени несёт цвета
;  ПОСЛЕДНЕЙ КОМНАТЫ (коды 2 и 3 раздаёт SET_ROOM_PAL).  Строка «SPIRITS»
;  покрашена чернилами 7, то есть кодом 2, и после разных комнат титры
;  выходили разного цвета; та же беда была у экрана итога.
;  Возвращаем стартовые: код 1 — белый, код 2 — циан 0xF8 (как на MSX,
;  docs/msx-title.md § 2.2), код 3 — красный 0x07 (на титрах не встречается).
;  Пишет палитру не этот код, а прерывание в гашении: луч защёлкивает её
;  построчно (reference_vector06c_palette_latch), поэтому только PAL_DIRTY.
A_PALSTART:
                ld      a,RP21_WHITE
                ld      (PAL_TAB+1),a
                ld      a,0xF8
                ld      (PAL_TAB+2),a
                ld      a,0x07
                ld      (PAL_TAB+3),a
                ld      de,PAL_TAB      ; зеркало 8..15: невидима одна плоскость
                ld      hl,PAL_TAB+8
                ld      b,0x08
                call    CPY_N
                ld      a,0x01
                ld      (PAL_DIRTY),a
                jp      PAL_HOOKUP      ; перехват 0038 мог ещё не стоять

; --- A_TITLINE — врезка в ОПЕРАНД `call CDF9` по 1873 (цикл титров 2:CF63).
; Печать в скрытые строки отменена целиком: запоминаем поток и длину.
; Позиция у всех шести строк одна и та же — de = 0x1108, строка 17,
; знакоместо 8; её знает A_XOR, и брать её из de незачем.
A_TITLINE:
                ld      (TT_CUR),hl
                ld      a,b
                ld      (TT_CLEN),a
                ret

; --- A_DISSOLVE — перехват 2:D021 (1921).
;
;  ЧТО ДЕЛАЛ ОРИГИНАЛ (docs/render-paths.md, C.8 и D.1).  Две ветки,
;  чередуются флагом 1969.  Ветка B: восемь проходов по 2048 байт,
;  dst(0800+i) ^= src(1000+i) & d, маска d = 80 40 20 10 08 04 02 01, между
;  проходами пауза; в конце скрытая треть гасится.  Ветка A: та же треть
;  копируется целиком, скрытое НЕ гасится.  Печать в скрытую треть идёт
;  XOR-ом (2:CE4D = 0xA9), поэтому к ветке B в скрытом лежит L(n-1) ^ L(n),
;  а к ветке A — L(n).  В обоих случаях в видимой трети после вызова ровно
;  L(n).  ПОРЯДОК ПОЯВЛЕНИЯ НЕ СЛУЧАЙНЫЙ: это битовые плоскости байта,
;  слева направо внутри каждой восьмёрки пикселей (проверено по коду
;  1921..1968 и трассой: 2048 RDBYTE ret=d07f на ветку A).
;
;  ЧТО ДЕЛАЕМ.  Переход «видно L(n-1)» -> «видно L(n)» — это XOR обеих
;  строк в видимые знакоместа, и XOR коммутативен, поэтому ДВЕ строки можно
;  прогнать ПОРОЗНЬ: dst ^= L(n-1)&d, затем dst ^= L(n)&d даёт ровно
;  dst ^= (L(n-1)^L(n))&d.  Значит скрытая копия не нужна ни в каком виде —
;  довольно двух пар (указатель, длина).  Ветка A — тот же проход одной
;  маской 0xFF.
A_DISSOLVE:
                ld      hl,G_1969       ; флаг чередования веток — игры
                ld      a,(hl)
                cpl
                ld      (hl),a
                and     a
                jp      z,AD_FLAT
                ld      a,0x80
AD_PASS:
                ld      (AD_M+1),a
                call    AD_BOTH
                call    AD_WAIT
                ld      a,(AD_M+1)
                rrca
                jp      nc,AD_PASS
                jp      AD_FIN
AD_FLAT:
                ld      a,0xFF
                ld      (AD_M+1),a
                call    AD_BOTH
AD_FIN:
                ld      hl,(TT_CUR)
                ld      (TT_PRV),hl
                ld      a,(TT_CLEN)
                ld      (TT_PLEN),a
                ret

AD_BOTH:
                ld      hl,(TT_PRV)
                ld      a,(TT_PLEN)
                call    AD_XOR
                ld      hl,(TT_CUR)
                ld      a,(TT_CLEN)
; AD_XOR — пройти поток hl длиной a и наXOR-ить его глифы в видимые строки
; под маской (AD_M+1).  Курсор — как у 2:CDF9/CE19: код < 0x20 двигает на a
; ячеек (a = 0 означает 256, ровно как djnz у оригинала), перенос по
; ширине 32.  Строка 17 оригинала = наша 9: перенос D021 на 8 рядов вверх
; входит в начальное значение AD_ROW.
AD_XOR:
                or      a
                ret     z
                ld      (AD_N),a
                ld      a,0x09
                ld      (AD_ROW),a
                ld      a,0x08
                ld      (AD_COL),a
AD_L:
                ld      a,(hl)
                inc     hl
                cp      0x20
                jp      nc,AD_GLYPH
                ld      c,a
AD_SK:
                call    AD_ADV
                dec     c
                jp      nz,AD_SK
                jp      AD_NEXT
AD_GLYPH:
                push    hl
                call    AD_DRAW
                pop     hl
                call    AD_ADV
AD_NEXT:
                ld      a,(AD_N)
                dec     a
                ld      (AD_N),a
                jp      nz,AD_L
                ret

AD_ADV:
                ld      a,(AD_COL)
                inc     a
                cp      0x20
                jp      c,ADA_S
                ld      a,(AD_ROW)
                inc     a
                ld      (AD_ROW),a
                xor     a
ADA_S:
                ld      (AD_COL),a
                ret

; AD_DRAW — восемь байт глифа a в знакоместо (AD_ROW, AD_COL), XOR-ом,
; под маской прохода.  База шрифта берётся из САМОМОДИФИЦИРУЕМОГО операнда
; 2:CE37 (1737), как у оригинала: её подменяет логотип DAE9.
AD_DRAW:
                dec     a
                ld      l,a
                ld      h,0x00
                add     hl,hl
                add     hl,hl
                add     hl,hl           ; (код-1)*8
                ld      (AD_SRC),hl
                ld      hl,(G_1737)
                ex      de,hl
                ld      hl,(AD_SRC)
                add     hl,de
                ld      (AD_SRC),hl
                ld      a,(AD_ROW)
                cp      0x18
                ret     nc              ; ниже 191-й строки знакомест нет
                add     a,a
                add     a,a
                add     a,a
                cpl
                ld      e,a             ; l = 255 - ряд*8 (верх знакоместа)
                ld      a,(AD_COL)
                add     a,PLANE_A
                ld      h,a
                ld      l,e
                call    INK_SET
                ld      a,(P3_MC+1)     ; маски знакоместа — в XOR-путь
                ld      (PX_MC+1),a
                ld      a,(P3_ME+1)
                ld      (PX_ME+1),a
                ld      (AD_DST),hl
                ld      hl,(AD_SRC)
                ex      de,hl
                ld      hl,(AD_DST)
                ld      b,0x08
AD_R:
                ld      a,(de)
                inc     de
AD_M:           and     0x00
                call    PX_PUT
                dec     l
                dec     b
                jp      nz,AD_R
                ret

; PX_PUT — XOR байта a в плоскости знакоместа.  Инвариант «байт лежит в
; каждой плоскости своего кода одинаковым» XOR сохраняет, поэтому читать
; и собирать байт незачем.  hl = адрес в плоскости A000; сохраняет hl, bc, de.
PX_PUT:
                ld      (P3_B),a
                ld      a,h
                add     a,0x20
                ld      h,a
                ld      a,(P3_B)
PX_MC:          and     0x00
                xor     (hl)
                ld      (hl),a
                ld      a,h
                add     a,0x20
                ld      h,a
                ld      a,(P3_B)
PX_ME:          and     0x00
                xor     (hl)
                ld      (hl),a
                ld      a,h
                sub     0x40
                ld      h,a
                ret

; AD_WAIT — пауза между проходами.  На MSX темп растворения задавала не
; пауза (она там 10 витков `dec h`), а сама цена 6144 обращений к VDP на
; проход; у нас проход стоит около трёх тысяч тактов, и без паузы все
; восемь прошли бы за четверть кадра.  Константа подобрана замером,
; docs/known-issues.md.
AD_WAIT:
                ld      hl,AD_DELAY
AW_L:
                dec     hl
                ld      a,h
                or      l
                jp      nz,AW_L
                ret

; --- A_ICONCOL — врезка в ОПЕРАНД `call CF28` по 1634 (показ значка
; OBJETOS из 2:CD12/CD1F/CD2C).  Красит прямоугольник ровно как CF28, а
; затем ВЫВОДИТ образ: рисовать его заранее (CD94) больше некуда — под
; чернилами 1 пикселей не хранится.  Какой именно значок — видно по адресу
; цветового прямоугольника, он у трёх вызовов разный.
A_ICONCOL:
                push    hl
                push    bc
                push    af
                call    G_1828          ; CF28 — цвет, как было
                pop     af
                pop     bc
                pop     hl
                ld      a,l
                cp      0xE8
                jp      z,AI_19         ; 6CE8: строка 12, колонка 29
                ld      a,h
                cp      0x70
                jp      z,AI_18         ; 70C8: строка 16, колонка 25
                ld      bc,0xC860       ; 6CC8: строка 12, колонка 25
                ld      a,0x17
                jp      AI_GO
AI_18:
                ld      bc,0xC880
                ld      a,0x18
                jp      AI_GO
AI_19:
                ld      bc,0xE860
                ld      a,0x19
AI_GO:
                ld      (AI_NUM),a
                push    bc
                ld      hl,0x294B       ; банк подвижных объектов
                ld      (SPR_BANK_VAR+1),hl
                pop     bc
                ld      a,(AI_NUM)
                call    A_TILEIMG
                ld      hl,0x8E76       ; вернуть банк декораций комнат
                ld      (SPR_BANK_VAR+1),hl
                ret

#endif
