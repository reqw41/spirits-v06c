; =====================================================================
;  ПАЛИТРА НА КОМНАТУ
; =====================================================================
;  Перехват D184 (1A84) накрывает `xor a / bit 7,b` — три байта; дальше игра
;  продолжается с 1A8B (`ld (1AA5),a` — смещение Y комнаты).  Бит 7 номера
;  комнаты = «нижняя половина экрана»: у неё смещение Y 0x60, и палитру она
;  НЕ ЗАДАЁТ — как на CPC (docs/cpc-render.md § 1.3), палитра берётся у
;  ВЕРХНЕЙ комнаты, той, где герой.
