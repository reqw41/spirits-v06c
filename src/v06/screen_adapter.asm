; =====================================================================
;  СТОРОЖ ПОДВИЖНЫХ ОБЪЕКТОВ
; =====================================================================
;  Тайлы кодов 4..7 ложатся в плоскость A000 — ту же, в которую XOR-ом идут
;  подвижные объекты.  Запись тайла ЗАМЕЩАЕТ байт, поэтому биты слота,
;  попавшие в тот же байт, пропали бы, и стирание (повторный XOR) оставило
;  бы призрак.  Значит перед записью тайлов в занятые слотами столбцы слоты
;  надо стереть; ближайший A_SPRFLUSH нарисует их заново.
;
;  Чтобы не гасить объекты на каждую мелочь (полоска ENERGIA и цифры счёта
;  пишутся в панель почти каждый кадр), сторож сверяет СТОЛБЦЫ: после
;  каждого прохода SPR_SCAN считает, какие столбцы заняты живыми слотами.
; ---------------------------------------------------------------------
; ЭТАП E: сторож свёлся к «стереть всё, что нарисовано».  Столбцовое
; уточнение (SPR_SCAN/min/max) больше не нужно: рисование идёт не по 33
; слотам с сохранёнными образами, а по списку объектов кадра, и ближайший
; A_SPRFLUSH перерисует их все.  Стирание в «Exolon» — повторный xor того
; же образа (плоскость A000 там общая с тайлами).
#if SCHEME == SCH_EXOLON
