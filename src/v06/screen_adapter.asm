V_VAR2_END      equ     V_VAR2+0x13

SHADOW_SAT      equ     0x407E          ; теневая SAT (32 записи по 4 байта)
SHADOW_PAT      equ     0x4100          ; теневые образы спрайтов (2048 б)
SPR_BANK_A89C   equ     G_1B4C          ; слой игры: то же для банка ЦВЕТА
                                        ; 8B9C, база не переключается
                                        ; (оригинал D24C)
SPR_BANK_VAR    equ     G_1B52          ; слой игры: b = номер записи банка ->
                                        ; hl = запись банка ДЕКОРАЦИЙ (8E76);
                                        ; операнд по 1B53 перебивают 2:CD94 и
