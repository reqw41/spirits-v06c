; ============================================================================
;  ЗАСТАВКА ПРИ СТАРТЕ: картинка CPC + мелодия CPC, до первой клавиши.
;  Spirits (Topo Soft, 1987), порт на ванильный Вектор-06Ц.
;  ВЕСЬ КОД — В ПОДМНОЖЕСТВЕ i8080 (гейт tools/check_i8080.py).
; ----------------------------------------------------------------------------
;  ПОРЯДОК СТАРТА (docs/adapter-requirements.md § 0b):
;     boot 0100 -> TITLE -> [картинка + мелодия, ждём клавишу]
;                        -> [СТРАНИЦА СПРАВКИ, ждём клавишу] -> SCR_INIT 5000
;  Дальше всё как раньше: SCR_INIT чистит плоскости (картинка заставки гибнет
;  вместе с ними), патчит резидентный слой и уходит в V_START, а тот ставит
;  свой кадровый ISR и стартует игру.
; ----------------------------------------------------------------------------
;  МЕСТО: 4620.. — хвост МЁРТВЫХ ТЕНЕВЫХ ТАБЛИЦ спрайтов игры (407E..49FF),
;  сразу за списками объектов SPRL/SPRO (docs/v06-memory.md § 13).  Прежнее
;  место 6100.. (SPRSAV) занял разросшийся адаптер экрана: после слияния
;  этапов E и F его тело — 4467 б, и зона стала 5000..631F; после слияния
;  стирания и рисования (2026-09-22) — 5150 б и 5000..6425.
;  Почему сюда класть можно: этап E выбросил обе чистки в D0F2, и код игры
;  за 3000 кадров не читал и не писал 407E..49FF ни разу (счётчик SHADOW в
;  tools/trap_stale_v06js.js).  В образе .rom кусок 43C6..49FF — НУЛИ (ни
;  один блок сборки туда не пишет), так что код ложится в пустое место.
;  К моменту, когда адаптер начнёт вести списки объектов, заставки уже нет.
; ----------------------------------------------------------------------------
;  КАРТИНКА лежит В САМОМ ОБРАЗЕ по A000..FFFF (tools/mk_title.py): .rom
;  Вектора грузится линейно с 0x0100, так что после загрузки она уже на
;  экране — ни распаковщика, ни вывода не нужно.  Образ от этого становится
;  65280 б (0100..FFFF) вместо 40585.
;
;  ВОСЕМЬ ЦВЕТОВ, А НЕ ШЕСТНАДЦАТЬ.  Четвёртая плоскость (8000..9FFF) занята
;  хвостом блока данных игры, и палитра зеркальна: pal[i] == pal[i & 7].
;  Чтобы отдать её заставке, пришлось бы где-то сохранить 8073 б 8000..9F88;
;  ЗАМЕР: ZX0 жмёт их до 7120 б (88.2 %), deflate -9 — до 6049 б (74.9 %), а
;  свободно на время заставки 2405 б.  Не влезает втрое — значит 8 цветов.
; ----------------------------------------------------------------------------
;  РАЗВЁРТКА.  Игра рисует 192 строки и держит порт 3 в SCROLL_TOP = 0x1F,
;  чтобы картинка стояла по центру.  Заставка — 256 строк во всю высоту, ей
;  нужен 0xFF: экранная строка r показывает строку памяти 255 - r, то есть
;  y = r.  При 0x1F верхние 32 строки картинки уехали бы вниз.
;  Значение лежит и в ЯЧЕЙКЕ v_scroll адаптера ввода — её читает V_KBD_POLL
;  после скана матрицы (выбор ряда идёт в тот же порт 3).  Обе на выходе
;  возвращаются к 0x1F.
; ----------------------------------------------------------------------------
;  МЕЛОДИЯ — ВАРИАНТ CPC (docs/cpc-sound.md § 2).  Ни партитуру, ни таблицу
;  нот сюда копировать НЕ НАДО, и это не экономия, а доказанный факт:
;    * партитура CPC совпадает с MSX БАЙТ В БАЙТ (§ 2.3), а партитура MSX уже
;      лежит в образе — голоса A и B трека 1 по 2651 и 2732 (оригинал
;      DD51/DE32 минус 0xB700), по 225 байт, оба кончаются FE «с начала»;
;    * таблица нот CPC — это таблица MSX, сдвинутая РОВНО НА ОКТАВУ ВНИЗ
;      (§ 2.4: 12.00..12.12 полутона на всём рабочем участке).  Октава вниз =
;      период вдвое, поэтому вместо 192 байт таблицы здесь стоит одна
;      команда `add hl,hl` над словом из таблицы MSX (база трека 1 — 25C5,
;      она же DCC5 канона, индекс 30).
;  Брать сами байты CPC (клок AY 1 МГц) нельзя: наш V_AY2VI переводит период
;  в делитель ВИ53 по клоку MSX, и период CPC дал бы ноту на 1.79 выше.
;  ЗАМЕР по образу: коды нот в партитуре 1..24, удвоенные периоды 302..1140 —
;  все в 12 битах, которые читает V_SND_CH.
;
;  ТЕМП — 10 кадров на тик (решение владельца; на CPC замерено 10.156 кадра,
;  docs/cpc-sound.md § 2.5).  Круг мелодии 225 тиков = 2250 кадров = 45 с.
;
;  ПЛЕЕР — структурный повтор CPC A604 (§ 2.2) на два голоса: на тик по
;  одному байту на голос, FF — пауза (канал молчит, указатель идёт дальше),
;  FE — вернуться в начало своего голоса.  Голос C на CPC и на MSX — заглушка
;  FF FE, его здесь просто нет.  Записи в PSG идут через V_PSG_WR адаптера
;  звука: она копит зеркало регистров AY и выдаёт в ВИ53 по записи в микшер
;  (R7) — ровно та граница ноты, на которой стоит и оригинальный плеер.
; ----------------------------------------------------------------------------
;  ВВОД: джойстик (порт 0x0E) + ЛЮБАЯ клавиша.  Матрицу Вектора читает
;  V_KBD_POLL адаптера ввода — раз в кадр, в гашении, с возвратом порта 3
;  (иначе развёртка уедет).  Здесь только просмотр готовой тени v_msxrow,
;  строки 0..8: в них V_KBD_POLL сводит клавиши игры (курсоры, не буквы QAOP).
; ============================================================================

                org     0x4620

TITLE:
                di
                ld      sp,0x6500       ; вершина стека порта (docs/v06-memory.md § 13)
                call    V_SND_INIT      ; заготовка v_stub, зеркало AY, счётчики стоят
                call    V_KBD_INIT      ; тень клавиатуры: всё отпущено

;  Развёртка на время заставки: 256 строк во всю высоту экрана.
                ld      a,0xFF
                ld      (v_scroll),a
                out     (0x03),a

;  Начальный дамп плеера (CPC A779, замер в докладе § 2.7: R7=3F R8=0F R9=0E
;  R10=00).  Громкости 0F и 0E — из обёртки MUS_TRACK_1; голосу C нот нет.
;  Микшер пишем ПОСЛЕДНИМ: по записи в R7 V_PSG_WR выдаёт зеркало в ВИ53.
                ld      c,0x0F
                ld      a,0x08
                call    V_PSG_WR        ; R8 — громкость A
                ld      c,0x0E
                ld      a,0x09
                call    V_PSG_WR        ; R9 — громкость B
                ld      c,0x00
                ld      a,0x0A
                call    V_PSG_WR        ; R10 — громкость C (нот нет)
                ld      c,0x3F
                ld      a,0x07
                call    V_PSG_WR        ; R7 — все каналы выключены

;  Кадровое прерывание заставки: палитра (её защёлкивает луч — писать только
;  в гашении, reference_vector06c_palette_latch), скан матрицы, счёт кадров.
;  ПАЛИТРУ ПИШЕМ ОДИН РАЗ НА ЭКРАН, А НЕ КАЖДЫЙ КАДР (правка по наблюдению
;  владельца НА ЖЕЛЕЗЕ, 2026-09-23): t_pdirty = «сколько прерываний осталось
;  до записи», 0 = записано.  Двойка, а не единица: первое прерывание после
;  долгого di приходит ПОСРЕДИ кадра (стек, V_SND_INIT, V_KBD_INIT, четыре
;  V_PSG_WR — всё это время прерывания запрещены), и запись палитры в нём
;  легла бы на видимые строки.  Ровно так же ждёт второго прерывания
;  SCR_INIT экранного адаптера (PAL_CNT, screen_adapter.asm).
                ld      a,0x02
                ld      (t_pdirty),a
                ld      a,0xC3          ; jp
                ld      (0x0038),a
                ld      hl,T_ISR
                ld      (0x0039),hl
                ei

; ---------------------------------------------------------------------------
;  Главный цикл: ждём смены кадра, раз в T_TEMPO кадров — шаг мелодии,
;  между делом смотрим ввод.
; ---------------------------------------------------------------------------
T_WAIT:
                ld      a,(t_frame)
                ld      b,a             ; кадр, с которого ждём смены
T_POLL:
                call    T_KEY
                jp      nz,T_EXIT
                ld      a,(t_frame)
                cp      b
                jp      z,T_POLL        ; кадр ещё не сменился
                ld      hl,t_left
                dec     (hl)
                jp      nz,T_WAIT
                ld      (hl),T_TEMPO
                call    T_TICK
                jp      T_WAIT

; ---------------------------------------------------------------------------
;  T_EXIT — заглушить звук и показать СТРАНИЦУ СПРАВКИ, а уже с неё уйти в
;  SCR_INIT.  Прерывание здесь НЕ снимается: страницу надо кому-то listen —
;  клавиатуру читает V_KBD_POLL из T_ISR, палитру защёлкивает T_PAL.
;  Развёртка и палитра переключаются ЧЕРЕЗ ЯЧЕЙКИ (t_scroll/t_palptr), а сама
;  запись — ОДНА, по флагу t_pdirty: его взводят ПОСЛЕ T_CLS, когда экран уже
;  чёрный, и ближайшее прерывание защёлкивает палитру справки в гашении.
;  Развёртку (порт 3) каждый кадр возвращает V_KBD_POLL из ячейки v_scroll —
;  ей флаг не нужен, она затирается сканом матрицы и без нас.
;  SCR_INIT дальше сам делает di и кладёт на 0038 безобидный `ei / ret`.
; ---------------------------------------------------------------------------
T_EXIT:
                ld      c,0x3F          ; R7 = 3F — то же, чем кончает плеер
                ld      a,0x07          ; оригинала (Вектор 255C): полная
                call    V_PSG_WR        ; тишина, все три счётчика встали
                ld      a,SCROLL_GAME   ; 192 строки по центру — как у игры
                ld      (v_scroll),a
                ld      (t_scroll),a
                out     (0x03),a
                ld      hl,HELP_PAL
                ld      (t_palptr),hl
                call    T_CLS           ; картинка заставки гаснет
;  ТЕПЕРЬ, А НЕ ДО T_CLS: пока экран не очищен, новая палитра перекрасила бы
;  картинку заставки на кадр-другой.  Прерывания идут давно, значит ближайшее
;  придёт в гашении — ждать второго, как на старте, не нужно.
                ld      a,0x01
                ld      (t_pdirty),a
                call    T_FRAME         ; рамка орнаментом панели HUD
                call    T_HELP          ; текст справки
                call    T_WAITKEY       ; отпустить -> нажать (антидребезг)
                di
                ld      sp,0x6500
                jp      SCR_INIT

; ---------------------------------------------------------------------------
;  T_WAITKEY — АНТИДРЕБЕЗГ.  Сюда приходят с уже нажатой клавишей (ею ушли с
;  картинки), поэтому сперва ждём, пока всё отпустят, и только потом — нового
;  нажатия.  Иначе одно нажатие пролетело бы обе страницы насквозь.
; ---------------------------------------------------------------------------
T_WAITKEY:
tw_rel:
                call    T_KEY
                jp      nz,tw_rel
tw_prs:
                call    T_KEY
                jp      z,tw_prs
                ret

; ---------------------------------------------------------------------------
;  T_CLS — погасить все три ВИДИМЫЕ плоскости A000..FFFF (24 576 б).
;  Невидимую 8000..9FFF не трогаем: там данные игры.
; ---------------------------------------------------------------------------
T_CLS:
                ld      hl,0xA000
                ld      c,0x00
tc_l:
                ld      (hl),c
                inc     hl
                ld      a,h
                or      a               ; FFFF -> 0000: h стал нулём — конец
                jp      nz,tc_l
                ret

; ---------------------------------------------------------------------------
;  T_FRAME — рамка по периметру ТЕМ ЖЕ орнаментом, что у панели HUD: коды
;  глифов 0x70/0x71 вперемежку (docs/i18n-inventory.md § 1.3 — в потоке
;  панели 9B56 они и образуют рамку), пером панели, то есть кодом цвета 2
;  (плоскость C000).  Правило чередования — чётность (ряд + колонка).
;  Те же знакоместа независимо считает tools/mk_help.py для гейта.
; ---------------------------------------------------------------------------
T_FRAME:
                ld      a,0xC0
                ld      (t_plane),a
                ld      c,0x00          ; ряд
tf_row:
                ld      b,0x00          ; колонка
tf_col:
                ld      a,c
                or      a
                jp      z,tf_put        ; верхний ряд
                cp      23
                jp      z,tf_put        ; нижний ряд
                ld      a,b
                or      a
                jp      z,tf_put        ; левая колонка
                cp      31
                jp      nz,tf_skip      ; правая колонка — иначе мимо
tf_put:
                ld      a,b
                add     a,c
                and     0x01
                ld      a,0x71
                jp      z,tf_cell
                ld      a,0x70
tf_cell:
                call    T_CELL
tf_skip:
                inc     b
                ld      a,b
                cp      32
                jp      nz,tf_col
                inc     c
                ld      a,c
                cp      24
                jp      nz,tf_row
                ret

; ---------------------------------------------------------------------------
;  T_HELP — текст страницы из потока, который кладёт tools/mk_help.py:
;     [флаги][колонка][длина][коды...] ... [0xFF]
;     флаги: биты 0..4 — ряд, бит 7 — плоскость C000 (цвет 2) вместо E000.
;  Ни одного знака в коде: поменять текст = пересобрать поток.
; ---------------------------------------------------------------------------
T_HELP:
                ld      hl,HELP_TEXT
th_rec:
                ld      a,(hl)
                cp      0xFF
                ret     z
                ld      e,a
                and     0x1F
                ld      c,a             ; ряд
                ld      a,e
                and     0x80
                ld      a,0xE0          ; плоскость белого текста
                jp      z,th_plane
                ld      a,0xC0          ; плоскость орнамента/заголовка
th_plane:
                ld      (t_plane),a
                inc     hl
                ld      a,(hl)
                ld      b,a             ; колонка
                inc     hl
                ld      a,(hl)
                ld      (t_len),a       ; длина
                inc     hl
th_ch:
                ld      a,(t_len)
                or      a
                jp      z,th_rec
                dec     a
                ld      (t_len),a
                ld      a,(hl)
                inc     hl
                push    hl
                call    T_CELL
                pop     hl
                inc     b
                jp      th_ch

; ---------------------------------------------------------------------------
;  T_CELL — знак a в знакоместо (ряд c, колонка b), плоскость (t_plane).
;  Адрес байта = плоскость + колонка*256 + (255 − строка растра): на Векторе
;  больший адрес — строка ВЫШЕ.  Портит a, de, hl; bc сохраняет.
; ---------------------------------------------------------------------------
T_CELL:
                push    bc
                call    T_GLYPH         ; de = адрес глифа
                pop     bc
                push    bc
                ld      a,(t_plane)
                add     a,b
                ld      h,a             ; старший байт = плоскость + колонка
                ld      a,c
                add     a,a
                add     a,a
                add     a,a             ; строка растра = ряд*8
                ld      l,a
                ld      a,0xFF
                sub     l
                ld      l,a             ; младший = 255 − строка
                ld      b,0x08
tcl_l:
                ld      a,(de)
                ld      (hl),a
                inc     de
                dec     l               ; следующая строка знакоместа — ниже
                dec     b
                jp      nz,tcl_l
                pop     bc
                ret

; ---------------------------------------------------------------------------
;  T_GLYPH — код a -> de = адрес восьми байт глифа.
;  Коды ниже 0xF0 — ШРИФТ САМОЙ ИГРЫ, и база берётся из ТОГО ЖЕ операнда
;  1737, что читает печатник 2:CE36: переедет шрифт — страница поедет с ним.
;  Коды 0xF0.. — девять знаков препинания, дорисованных tools/mk_help.py:
;  в шрифте игры их нет, и трогать её таблицу ради них не пришлось.
; ---------------------------------------------------------------------------
T_GLYPH:
                cp      0xF0
                jp      c,tg_font
                sub     0xF0
                ld      l,a
                ld      h,0x00
                add     hl,hl
                add     hl,hl
                add     hl,hl
                ld      de,HELP_PUNCT
                add     hl,de
                ex      de,hl
                ret
tg_font:
                dec     a
                ld      l,a
                ld      h,0x00
                add     hl,hl
                add     hl,hl
                add     hl,hl           ; (код − 1) * 8
                ex      de,hl
                ld      hl,(GM_FONTPTR) ; база шрифта — операнд печатника игры
                                        ; (адрес даёт сборка: в образе
                                        ;  i8080 код игры переехал)
                add     hl,de
                ex      de,hl
                ret

; ---------------------------------------------------------------------------
;  T_KEY — нажато ли что-нибудь.  Ответ: NZ = да.  Портит a, hl, de, флаги.
; ---------------------------------------------------------------------------
T_KEY:
                in      a,(0x0E)        ; джойстик Вектора, активный ноль
                cp      0xFF
                ret     nz
                ld      hl,v_msxrow     ; тень матрицы, строки MSX 0..8
                ld      e,0x09
tk_l:
                ld      a,(hl)
                cp      0xFF
                ret     nz
                inc     hl
                dec     e
                jp      nz,tk_l
                xor     a               ; Z — ничего не нажато
                ret

; ---------------------------------------------------------------------------
;  T_ISR — кадровое прерывание заставки.
;  Порядок обязателен: сперва скан матрицы (он затирает порт 3 и роняет
;  выходные защёлки ВВ55, а в конце возвращает порт 3 из v_scroll и порт 2 из
;  v_border), и только потом палитра, которая порт 2 тоже трогает.
; ---------------------------------------------------------------------------
T_ISR:
                push    af
                push    bc
                push    de
                push    hl
                call    V_KBD_POLL
                call    T_PAL
                ld      hl,t_frame
                inc     (hl)
                pop     hl
                pop     de
                pop     bc
                pop     af
                ei
                ret

; ---------------------------------------------------------------------------
;  T_PAL — 16 слотов палитры в порт 0C, записи 8..15 — зеркало записей 0..7
;  (невидима ровно одна плоскость, 8000).  Устроено как PAL_WRITE экранного
;  адаптера: номер слота в порт 02, значение восемь раз подряд в порт 0C.
;
;  ПИШЕМ ТОЛЬКО ПО ФЛАГУ t_pdirty — ДВА РАЗА ЗА ВСЮ ЗАСТАВКУ, а не 50 раз в
;  секунду.  Почему: палитру защёлкивает РАСТР (reference_vector06c_palette_latch,
;  RTL MiSTer video.sv) — слот берётся из индекса пикселя, который выводится В
;  ТАКТ записи.  Попал out (0C) в видимую строку — на ней проступает цвет
;  записываемого слота.  На vector06js этого не видно (эмулятор огрубляет), на
;  железе владелец увидел БЕЛУЮ ПОЛОСКУ СВЕРХУ страницы справки: слот 1 у неё
;  0xFF, и кадр от кадра прерывание входило чуть позже гашения.  На картинке
;  полоска была тоже, но тёмно-синяя (слот 1 картинки) и незаметная.
;  В игре ровно так же устроен PAL_ISR2 экранного адаптера: пишет по
;  PAL_DIRTY, а не каждый кадр — и полоски в игре нет.
;  Порт 02 (кайма) и порт 03 (развёртка) внутри тоже трогаются, поэтому они
;  ушли под флаг вместе с палитрой; развёртку каждый кадр восстанавливает
;  V_KBD_POLL, ей флага не надо.
; ---------------------------------------------------------------------------
T_PAL:
                ld      a,(t_pdirty)
                or      a
                ret     z               ; уже защёлкнуто — в порт 0C ни байта
                dec     a
                ld      (t_pdirty),a
                ret     nz              ; ждём следующего прерывания (первое
                                        ; после долгого di — посреди кадра)
                ld      a,(t_scroll)    ; 0xFF у картинки, SCROLL_GAME у справки
                out     (0x03),a
                ld      c,0x0F
                ld      b,0x10
tp_l:
                ld      a,c
                out     (0x02),a        ; номер слота (он же цвет каймы)
                and     0x07
                ld      e,a
                ld      d,0x00
                ld      hl,(t_palptr)   ; TITLE_PAL у картинки, HELP_PAL у справки
                add     hl,de
                ld      a,(hl)
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                out     (0x0C),a
                dec     c
                dec     b
                jp      nz,tp_l
                xor     a
                out     (0x02),a
                ret

; ---------------------------------------------------------------------------
;  T_TICK — один тик мелодии: по байту на голос.
; ---------------------------------------------------------------------------
T_TICK:
                ld      hl,t_va
                call    T_VOICE
                ld      hl,t_vb
                jp      T_VOICE

; ---------------------------------------------------------------------------
;  T_VOICE — голос, hl = дескриптор:
;     +0 dw текущий указатель, +2 dw начало, +4 маска канала, +5 номер R0
;  Повторяет CPC A66A..A6B5: микшер выключить -> разобрать байт -> период ->
;  микшер включить -> указатель вперёд.
;  V_PSG_WR сохраняет bc/de/hl, поэтому маска живёт в b через все вызовы.
; ---------------------------------------------------------------------------
T_VOICE:
                ld      (t_vd),hl
                ld      de,0x0004
                add     hl,de
                ld      b,(hl)          ; маска канала (01 / 02)
                inc     hl
                ld      a,(hl)
                ld      (t_vreg),a      ; номер регистра периода (00 / 02)
;  микшер: канал выключить (CPC: or маска -> R7)
                ld      a,(t_mix)
                or      b
                ld      (t_mix),a
                ld      c,a
                ld      a,0x07
                call    V_PSG_WR
;  очередной байт партитуры
                ld      hl,(t_vd)
                ld      e,(hl)
                inc     hl
                ld      d,(hl)          ; de = указатель
                ld      a,(de)
                cp      0xFE
                jp      nz,tv_byte
                ld      hl,(t_vd)       ; FE — вернуться в начало своего голоса
                inc     hl
                inc     hl
                ld      e,(hl)
                inc     hl
                ld      d,(hl)
                ld      a,(de)
tv_byte:
                cp      0xFF
                jp      z,tv_next       ; FF — пауза: канал так и остался выключен
;  нота: период из таблицы MSX, УДВОЕННЫЙ — это и есть таблица CPC
                push    de
                add     a,a             ; коды нот 1..24, переноса быть не может
                ld      l,a
                ld      h,0x00
                ld      de,T_NOTES
                add     hl,de
                ld      e,(hl)
                inc     hl
                ld      d,(hl)
                ex      de,hl           ; hl = период MSX
                add     hl,hl           ; октава вниз = таблица нот CPC
                ld      c,l
                ld      a,(t_vreg)
                call    V_PSG_WR        ; R0 / R2 — период, младший байт
                ld      c,h
                ld      a,(t_vreg)
                inc     a
                call    V_PSG_WR        ; R1 / R3 — период, старший байт
                pop     de
;  микшер: канал включить (CPC: and ~маска -> R7)
                ld      a,b
                cpl
                ld      c,a
                ld      a,(t_mix)
                and     c
                ld      (t_mix),a
                ld      c,a
                ld      a,0x07
                call    V_PSG_WR
tv_next:
                inc     de
                ld      hl,(t_vd)
                ld      (hl),e
                inc     hl
                ld      (hl),d
                ret

; ---------------------------------------------------------------------------
;  Конец кода: ниже только данные и ОЗУ заставки.
; ---------------------------------------------------------------------------
T_CODE_END:

t_frame:        db      0               ; счётчик кадров (ведёт T_ISR)
t_left:         db      T_TEMPO         ; сколько кадров до следующего тика
t_mix:          db      0x3F            ; зеркало R7: все каналы выключены
t_vd:           dw      0               ; дескриптор голоса, который сейчас играем
t_vreg:         db      0               ; номер регистра периода этого голоса

t_scroll:       db      0xFF            ; порт 3: 0xFF — 256 строк картинки
t_palptr:       dw      TITLE_PAL       ; чью палитру защёлкивает T_PAL
t_pdirty:       db      0x02            ; сколько прерываний до записи палитры
                                        ; (0 = записана; ставит TITLE и T_EXIT)
t_plane:        db      0xE0            ; старший байт плоскости для T_CELL
t_len:          db      0               ; сколько знаков осталось в записи

;  Палитра страницы справки: фон чёрный, текст белый (код 1 — плоскость
;  E000), рамка и заголовок — перо панели HUD (код 2 — плоскость C000,
;  0x18 = тот же байт, что стоит во втором слоте палитры комнаты, замер
;  tools/cmp_color_msx.py).  Слоты 3..7 не используются: двух цветов хватает.
HELP_PAL:       db      0x00, 0xFF, 0x18, 0x00, 0x00, 0x00, 0x00, 0x00

t_va:           dw      T_SCORE_A, T_SCORE_A
                db      0x01, 0x00      ; канал A: маска 01, регистры R0/R1
t_vb:           dw      T_SCORE_B, T_SCORE_B
                db      0x02, 0x02      ; канал B: маска 02, регистры R2/R3

                .include "title-pal.inc"

T_END:
