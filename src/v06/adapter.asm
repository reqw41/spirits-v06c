; ============================================================================
;  Spirits (Topo Soft, 1987), MSX -> Вектор-06Ц.
;  АДАПТЕР ВВОДА И ЗВУКА. Экран сюда не входит — им занимается отдельный слой.
;
;  Цель: ВАНИЛЬНЫЙ Вектор-06Ц, 64 КБ, без квазидиска, без AY.
;  Код целиком в подмножестве i8080 (игра уже рекомпилирована тем же
;  подмножеством — docs/recompilation.md), синтаксис мнемоник — Z80, как в
;  дизасме проекта. Чистота проверяется инструментом tools/check_i8080.py:
;  он декодирует собранные байты и валит сборку на любом опкоде, которого
;  нет у 8080.
;
;  Сборка:  tools/build_v06_rom.py / tools/build_port_rom.py (zasm --8080)
;  Выход:   build/adapter/*.rom, build/port/*.rom; листинги адаптера рядом
;
;  Место: свободная низкая ОЗУ 4A00..7FFF (docs/v06-memory.md). Ниже 4A00
;  стек (вершина 4A00), выше 8000 — свободная плоскость 0.
; ----------------------------------------------------------------------------
;  ТОЧКИ ВРЕЗКИ В ИГРУ (адреса Вектора; канон = адрес + 0xB800 для резидента
;  и + 0x8100 для головы SPIRITS.2 — пересчёт по V06_MAP в tools/disasm_msx.py).
;  Патч образа делает сборщик (tools/build_*_rom.py), не этот файл.
;
;  ЗВУК
;    2569  PSG_WR            -> jp V_PSG_WR     (3 байта вместо 6; a=рег, c=знач)
;                                через неё идут все 14 вызовов проигрывателя
;    03FC  out (0xA0),a  \   -> проигрыватель эффектов в SPIRITS.2: заменить
;    03FF  out (0xA1),a  /      пять байт «out A0h / ld a,c / out A1h» на
;                               «call V_PSG_WR» + nop nop (a уже = регистр,
;                               c уже = значение — ABI совпадает)
;    раз в кадр            -> call V_SND_TICK  (из кадрового прерывания)
;    на старте             -> call V_SND_INIT
;
;  КЛАВИАТУРА (везде «ld a,0xFx / out (0xAA),a / [nop] / in a,(0xA9)» ->
;              «ld a,0x0x / call V_KBD_ROW», 5 байт вместо 7..8)
;    1CDF  KBD_SCAN          -> jp V_KBD_SCAN   (ABI тот же: c = код, ответ CF)
;    1F84  KBD_CHK           -> строка 3
;    088E  выбор персонажа   -> строка 0
;    12BC  SHIFT             -> строка 6
;    155F  пауза             -> строка 3
;    156A  ждать любую       -> строка из b
;    18B4  опрос с тайм-аутом-> строка из b
;    2465  опрос в плеере    -> строка из c
;    раз в кадр            -> call V_KBD_POLL  (ТОЛЬКО в гасящем ходе!)
;    на старте             -> call V_KBD_INIT
;
;  ДЖОЙСТИК
;    12E1  R7=FF/R14/in A2h  -> call V_JOY_RD   (13 байт заменяются на 3,
;                               дальше игра делает and 0x1F как раньше)
; ----------------------------------------------------------------------------
;  ЕДИНСТВЕННАЯ ВНЕШНЯЯ ЗАВИСИМОСТЬ: кадровый тик 50 Гц, который зовёт
;  V_KBD_POLL и V_SND_TICK. Без него клавиатура замрёт на состоянии последнего
;  опроса, а звуковые эффекты будут тянуться бесконечно (у ВИ53 нет огибающей,
;  гасить ноту больше некому). Мелодия и джойстик от тика не зависят.
; ============================================================================

	org	0x4A00

;  Состав адаптера ввода/звука (все — подмножество i8080):
;    snd.asm  — AY → ВИ53 (V_PSG_WR, V_SND_TICK, V_SND_INIT)
;    kbd.asm  — матрица Вектора → тень строк MSX (V_KBD_POLL/ROW/SCAN)
;    joy.asm  — порт 0x0E → байт RDPSG(14) (V_JOY_RD)
;  Точки врезки в игру и карта ячеек — шапка файла и docs/v06-input-sound.md.

	.include "snd.asm"
	.include "kbd.asm"
	.include "joy.asm"

; ---------------------------------------------------------------------------
;  Конец кода. Всё, что ниже, — данные и ОЗУ адаптера: линейный дизассемблер
;  проверки идёт от начала образа ровно до этой метки, поэтому НИ ОДНОГО
;  байта данных выше быть не должно.
; ---------------------------------------------------------------------------
V_CODE_END:

	.align 16
v_ayreg:	ds	16	; зеркало регистров AY: выровнено на 16, номер регистра
				; складывается с младшим байтом адреса без переноса
v_dead:		ds	1	; биты 0..2: канал погашен по истечении срока жизни ноты
v_own:		ds	3	; 1 = счётчик ВИ53 канала считает, 0 = остановлен
v_life:		ds	3	; сколько кадров осталось звучать (0 = бессрочно)
v_div:		ds	6	; кэш делителя счётчика (мл., ст.) — запись перезапускает счёт
V_SND_VARS:	equ	$ - v_ayreg	; столько байт чистит V_SND_INIT

v_stub:		ds	3	; «out (порт),a : ret» — у i8080 нет OUT по регистру
v_bit1:		db	0x01, 0x02, 0x04	; 1 << номер канала

	.align 16
v_msxrow:	ds	16	; тень строк MSX (0..8 строятся, 9..15 всегда FF)

;  ЧИТЫ (docs/cheats.md). Байты ведёт V_KBD_POLL (kbd.asm), читает и чистит
;  модуль читов src/v06/cheat.asm (org 4F3E, кладёт tools/build_port_rom.py).
;  Все пять лежат ЗДЕСЬ, а не в модуле читов, потому что скан клавиатуры —
;  в адаптере, а модуль читов собирается отдельно и адреса получает через
;  equ из листинга адаптера (тот же приём, что у связки).
v_cheat:	db	0	; 1 = режим читов включён (F1+F3 на старте)
v_god:		db	0	; 1 = god mode
v_cpend:	db	0	; копилка ФРОНТОВ: b0 8 b1 9 b2 6 b3 7 b4 K
v_cprev:	db	0	; что было нажато в прошлом кадре (те же биты + b5 G)
v_carm:		db	0	; окно включения читов: 0 — закрыто, V_CHEAT_INF —
				; без срока (титры), иначе — сколько кадров осталось

;  Видеорегистры, которые затирает скан клавиатуры. Их ведёт адаптер ЭКРАНА:
;  меняешь развёртку или кайму — положи новое значение и сюда, иначе первый же
;  кадровый опрос клавиатуры вернёт старое.
v_ppi_c:	db	0x02	; порт C ВВ55 (как у эталонных игр Вектора)
v_scroll:	db	0x1F	; порт 3 — вертикальная развёртка: 0x1F = картинка MSX (192 строки,
			; строки 255..64 памяти) отцентрирована по вертикали, сверху и снизу
			; по 32 пустых строки. То же значение пишет PAL_WRITE экранного адаптера.
v_border:	db	0x00	; порт 2 — кайма 0 + режим 256 (бит 4 = 0)

V_END:

; ---- константы для адресной арифметики (младший/старший байт выровненных таблиц)
V_AYREG_LO:	equ	v_ayreg & 0xFF
V_AYREG_HI:	equ	v_ayreg >> 8
V_MSXROW_LO:	equ	v_msxrow & 0xFF
V_MSXROW_HI:	equ	v_msxrow >> 8

; ---- окно включения читов (docs/cheats.md). Открывается БЕССРОЧНО в
;      V_CHEAT_ARM (идут титры, партия ещё не началась), а первый виток
;      игрового цикла (V_JOY_PACE связки) ставит ему срок: 150 кадров = 3 с.
V_CHEAT_INF:	equ	0xFF		; v_carm = «окно без срока»
V_CHEAT_WIN:	equ	150		; кадров окна после начала партии
