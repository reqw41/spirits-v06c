; Связка порта: старт и кадровое прерывание. Только подмножество i8080.
;
; Лежит в промежутке между адаптером ввода/звука (4A00..4DD7) и таблицей
; звуковых эффектов (4EAA).  org опущен с 4E00 до 4DD8 (2026-09-23): 40
; байт дырки за адаптером ввода понадобились под перенос головы блока
; сценариев в V_START.  Потолок прежний — 4EAA. Управление сюда приходит из SCR_INIT экранного адаптера:
; его последний `jp GAME_ENTRY` перенаправлен сюда статическим патчем
; образа (tools/build_port_rom.py) — файл экранного адаптера не тронут.
;
; Кадровое прерывание 50 Гц нужно адаптеру ввода и звука: без V_KBD_POLL
; тень клавиатуры не обновляется (игра не видит нажатий), без V_SND_TICK
; звуковые эффекты не кончаются — у ВИ53 нет огибающей, ноту гасит срок.
;
; Адреса V_* подставляет сборочный скрипт из листинга адаптера.

                org     0x4DE8

V_START:
                di
;  СЦЕНАРИИ ХОДА БРОДЯЧИХ ОБЪЕКТОВ — ГОЛОВА БЛОКА В ЗОНУ ЗАСТАВКИ.
;  Байт-код, по которому ходят доспех, орёл и принцесса, лежит в образе
;  по SCR_SRC (это его штатное место в верхней копии SPIRITS.1).  Игра
;  затирает его буфером атрибутов с первой же отрисовки комнаты, поэтому
;  голову блока переносим в зону заставки: здесь заставка и справка уже
;  отработали (V_START — единственная такая точка), а комнату ещё не
;  рисовали.  Остальные куски блока сборка разложила по мёртвым местам
;  статически, указатели переписаны там же (tools/mk_scripts.py).
                ld      hl,SCR_SRC
                ld      de,SCR_DST
                ld      bc,SCR_LEN
V_SCR_CP:                               ; ldir нет: связка — подмножество i8080
                ld      a,(hl)
                ld      (de),a
                inc     hl
                inc     de
                dec     bc
                ld      a,b
                or      c
                jp      nz,V_SCR_CP
                call    V_SND_INIT
                call    V_KBD_INIT
;  ОКНО ВКЛЮЧЕНИЯ ЧИТОВ (docs/cheats.md).  Именно здесь, и только здесь:
;  V_START — единственная точка, где заставка и справка уже позади, а игра
;  ещё не начала первый виток.  V_CHEAT_ARM открывает окно БЕЗ СРОКА, и всё
;  время титров V_KBD_POLL смотрит, не зажаты ли F1 и F3; срок V_CHEAT_WIN
;  окну ставит первый виток игрового цикла (V_JOY_PACE ниже).
                call    V_CHEAT_ARM
                ld      a,0xC3          ; jp
                ld      (0x0038),a
                ld      hl,V_ISR
                ld      (0x0039),hl
                ei
                jp      GAME_ENTRY

; Экранный адаптер на время блита через SP делает di/ei, так что сюда
; прерывание приходит только с настоящим стеком игры.
V_ISR:
                push    af
                push    bc
                push    de
                push    hl
                ld      hl,v_frames
                inc     (hl)            ; счётчик кадров — по нему идёт темп мелодий
;  ФАЗА ПЛАМЕНИ — ПО КАДРАМ, А НЕ ПО ВИТКАМ (решение владельца «как на MSX»,
;  2026-09-22).  В оригинале кадр пламени переключает `xor 1` на КАЖДОМ витке
;  игрового цикла (BC91): на MSX виток 4.78 кадра, то есть смена раз в 96 мс,
;  а у нас виток идёт темпом ZX (3.5 кадра) и пламя мигало бы в 1.4 раза
;  быстрее оригинала.  Здесь фаза отмеряется кадрами: V_FLAME_DIV кадров на
;  кадр пламени = 100 мс, 10 смен в секунду (на MSX 10.5).  Саму ячейку
;  читает ВРЕЗКА в 058E (tools/build_port_rom.py) вместо `xor 1`.
                ld      hl,v_fldiv
                dec     (hl)
                jp      nz,vi_noflame
                ld      (hl),V_FLAME_DIV
                ld      hl,v_flame
                ld      a,(hl)
                xor     0x01
                ld      (hl),a
vi_noflame:
                call    V_KBD_POLL      ; опрос матрицы раз в кадр, в гашении
                call    V_SND_TICK      ; срок жизни нот
                pop     hl
                pop     de
                pop     bc
                pop     af
                ei
                ret
;  ТЕМП МЕЛОДИЙ ПО КАДРАМ. В оригинале шаг мелодии — пустой цикл 2460..2476
;  на `tempo` итераций, внутри которого игра девять раз опрашивает клавиатуру.
;  Такой темп зависит от тактов процессора и цены опроса: на Z80-Векторе он
;  уехал в 2.07 раза, на i8080 уедет ещё раз. Здесь шаг отмеряется кадрами
;  прерывания: в ячейке темпа (2581) лежит уже не число итераций, а число
;  кадров (его кладут врезки в MUS_TRACK_1/2).
;  Поведение сохранено: пока мелодия играет, игра стоит, любая клавиша
;  обрывает мелодию. Выход по клавише идёт на 255C с одним словом на стеке —
;  так же, как выходил оригинальный цикл (он держал там `push bc`).
V_MUS_WAIT:
                ld      a,(MUS_TEMPO)
                ld      b,a             ; сколько кадров ждать
vmw_f:
                ld      a,(v_frames)
                ld      c,a             ; кадр, с которого ждём смены
vmw_w:
                push    bc
                ld      b,0x09          ; строки 0..8 тени клавиатуры
                ld      c,0xF0
vmw_k:
                ld      a,c
                call    V_KBD_ROW
                cp      0xFF
                jp      nz,MUS_KEY_EXIT ; клавиша: на стеке bc, 255C его снимет
                inc     c
                dec     b
                jp      nz,vmw_k
                pop     bc
                ld      a,(v_frames)
                cp      c
                jp      z,vmw_w         ; кадр ещё не сменился
                dec     b
                jp      nz,vmw_f
                jp      MUS_AFTER_WAIT

;  ТЕМП ИГРЫ — ПО ZX SPECTRUM (решение владельца, 2026-09-22). Виток
;  игрового цикла у нас свободно бежит за ~2.9 кадра, на ZX — ~3.5 кадра
;  (docs/zx-tempo.md: шаг героя 3 px за виток, ~42 px/с), на MSX — 4.78.
;  Раз за виток игра опрашивает джойстик (врезка 12E1 -> V_JOY_PACE):
;  здесь ждём, пока с прошлого витка пройдёт не меньше 4 кадров
;  (решение владельца 2026-09-23 по сравнению на MiSTer: 3.5 показалось
;  быстровато; 4 = 12.5 витка/с, герой ~37 px/с; MSX 4.78, ZX ~3.5). Тяжёлые витки (отрисовка комнаты) и так
;  длиннее — они проходят без ожидания, как и на ZX. Сохраняет bc, de, hl.
V_LOOP_PACE:
;  ТЕМП ОТМЕРЯЕТСЯ НА ГОЛОВЕ ГЛАВНОГО ЦИКЛА (BB8F), А НЕ В ОПРОСЕ ДЖОЙСТИКА.
;  Через опрос CC7B (врезка 12E1) идут только 212 витков из 394: витки
;  прыжка (C425) и падения (C3EF) уходят на свои ветки в C185/C18C ДО
;  вызова CC7B и шли БЕЗ пейсера — прыжок 1.51 кадра на виток вместо 4
;  (весь прыжок 10.6 кадра вместо 28), на i8080 2.46.  На живом MSX виток
;  прыжка 4.50 кадра при ходьбе 4.81 — прыжок обязан идти темпом ходьбы.
;  Точка BB8F исполняется РОВНО РАЗ за виток на всех 394 витках замера
;  (tools/jump_pace_probe.js).  Замер после правки: прыжок 4.00 кадра на
;  виток, весь прыжок 28.0 кадра, отношение прыжок/ходьба 0.95 (MSX 0.94).
;
;  ПЕРВЫЙ ВИТОК ИГРЫ ЗАКРЫВАЕТ БЕССРОЧНОЕ ОКНО ЧИТОВ (docs/cheats.md):
;  V_CHEAT_ARM открыла его в V_START ещё до титров и БЕЗ СРОКА
;  (V_CHEAT_INF = 0xFF), титры игрок смотрит сколько угодно.  Срабатывает
;  только на 0xFF; идущий срок и закрытое окно не трогаем.
                ld      a,(v_carm)
                inc     a
                jp      nz,vlp_armed
                ld      a,V_CHEAT_WIN
                ld      (v_carm),a
vlp_armed:
                push    hl
                push    bc
                ld      a,(v_pace_per)  ; кадров на виток (решение владельца: 4)
                ld      c,a
vlp_w:
                ld      a,(v_frames)
                ld      hl,v_pace_last
                sub     (hl)            ; кадров с прошлого витка (по модулю 256)
                cp      c
                jp      c,vlp_w         ; ещё рано
                ld      a,(v_frames)
                ld      (hl),a
                pop     bc
                pop     hl
                jp      GAME_ITER       ; тело витка BF34

;  ПУСТОЙ СПИСОК «ДОРИСОВАТЬ В НИЖНЕМ ОКНЕ» — ЗАЩИТА ОТ djnz НА 256
;  (найдено сверкой с живым картриджем, docs/jump-geometry.md § 9).
;  D124 считает длину списка b := ((F7FE − (D416)) >> 2) и уходит на D655
;  (lddr + add a,0x60 + djnz).  Очередь записей в VDP D333..D352 заменил
;  адаптер экрана, заполнитель D352 у нас не исполняется НИ РАЗУ, список
;  всегда пуст, (D416) = F7FE и b = 0 — а djnz при нуле крутится 256 раз и
;  уезжает на 1024 байта вниз, в теневой буфер атрибутов F34D..F58C
;  (Вектор 3C4D).  Итог: в КОМНАТЕ ШАРА (той, что в нижнем окне) решётка
;  ложных «полов» и невидимых стен через 32 px от Y=0x38 вниз: герой стоит
;  на пустом месте и не долетает в прыжке.  Замер: у картриджа b = 3 и 123
;  прохода за прогон, у нас b = 0 и 7424.
;  Лечение: при пустом списке уходить туда же, куда уходит штатная
;  проверка пустоты, — на D664 (выгрузка спрайтов).  Сохраняет порядок
;  вызовов; если заполнитель очереди когда-нибудь вернут, проверка не
;  мешает (на картридже она недостижима).
V_LIST_GUARD:
                ld      a,l
                or      a
                jp      z,GAME_SPRFLUSH ; список пуст — рисовать нечего
                ld      b,l
                dec     de
                ld      hl,GAME_LIST_TAIL
                jp      GAME_LIST_DRAW

v_frames:       db      0
v_pace_last:    db      0
v_pace_per:     db      4
v_flame:        db      0               ; кадр пламени: 0 -> образ 0x24, 1 -> 0x25
v_fldiv:        db      V_FLAME_DIV     ; сколько кадров до следующей смены
V_GLUE_END:
